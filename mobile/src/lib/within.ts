/**
 * Проба з межею очікування.
 *
 * Локальні проби — SQLite, дозволи, стан приймача — зазвичай відповідають за
 * мілісекунди, але не завжди: `getProviderStatusAsync` мовчить, поки система
 * думає про вимкнену геолокацію, а база може стояти на замку іншої транзакції.
 * Без межі одна така пауза тримає весь екран на вертушці, бо `setLoading(false)`
 * стоїть після `Promise.all`. Для водія це означає порожній екран замість
 * маршруту — і жодного способу зрозуміти, що сталося.
 *
 * Тому: не дочекалися за відведений час — беремо запасне значення й малюємо
 * екран. Проба не скасовується (скасувати її нічим), просто її відповідь уже
 * нікого не цікавить; наступне оновлення прочитає стан наново.
 */
export function within<T>(promise: Promise<T>, ms: number, fallback: T): Promise<T> {
  return Promise.race([
    promise.catch(() => fallback),
    new Promise<T>((resolve) => setTimeout(() => resolve(fallback), ms)),
  ]);
}

/** Скільки чекаємо на локальну пробу, перш ніж малювати екран без неї. */
export const PROBE_MS = 3_000;
