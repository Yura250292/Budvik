/** Чи лежить точка всередині області (промінь — парність перетинів). */
export function inLvivOblast(lat: number, lng: number): boolean {
  let inside = false;
  for (let i = 0, j = LVIV_OBLAST.length - 1; i < LVIV_OBLAST.length; j = i++) {
    const [xi, yi] = LVIV_OBLAST[i];
    const [xj, yj] = LVIV_OBLAST[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Той самий контур літералом Postgres: `${LVIV_OBLAST_SQL} @> point(lng, lat)`. */
export const LVIV_OBLAST_SQL = `polygon '(${LVIV_OBLAST.map(([x, y]) => `(${x},${y})`).join(",")})'`;
