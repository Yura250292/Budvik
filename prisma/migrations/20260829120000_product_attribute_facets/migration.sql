-- Атрибути товару, за якими фільтрує вітрина.
--
-- Живлення — найширший і найцінніший фасет: «болгарка акумуляторна чи
-- мережева» — це перше, чим покупець звужує вибір, і єдине, що можна
-- витягнути на весь каталог із назви з 1С (характеристик обмін не дає).
-- Напруга акумулятора йде поруч: усередині акумуляторного це другий за
-- значенням параметр, бо визначає сумісність із наявною батареєю.
--
-- Текстом, а не PG-енумом: додати «гібридне» чи «ручне» треба буде однією
-- правкою реєстру src/lib/catalog/facets.ts, а не міграцією з ALTER TYPE.
-- NULL означає «невідомо» — дефолтів не вигадуємо, бо вигаданий фасет
-- викидає товар із видачі мовчки.
ALTER TABLE "Product" ADD COLUMN "powerSource" TEXT; -- 'akum' | 'merezha' | 'benzo'
ALTER TABLE "Product" ADD COLUMN "voltageV" INTEGER; -- напруга акумулятора, В

-- Фасети рахуються завжди в межах групи чи розділу («діаметр диска» питають
-- лише про болгарки), тож індекс складений із typeKey.
--
-- Без CONCURRENTLY навмисно, на відміну від 20260811180000_perf_indexes:
-- це нові колонки, суцільно NULL, і побудова індексу по них — секунда.
-- Той самий вибір, що в 20260826170000_product_type_section.
CREATE INDEX "Product_typeKey_powerSource_idx" ON "Product"("typeKey", "powerSource");
CREATE INDEX "Product_typeKey_discDiameterMm_idx" ON "Product"("typeKey", "discDiameterMm");
