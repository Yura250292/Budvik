export interface Classified {
  /** Ключ групи товару — значення ?type=. */
  type: string;
  /** Розділ каталогу. */
  section: string;
}

/** Назва групи для показу: «Свердла» замість «Свердло». */
export const TYPE_LABELS: Record<string, string> = Object.fromEntries(
  RULES.map((r) => [r.type, r.label])
);

/** Розділ, до якого належить група товару. */
export const TYPE_SECTION: Record<string, string> = Object.fromEntries(
  RULES.map((r) => [r.type, r.section])
);

/** Усі групи розділу — у порядку оголошення правил. */
export function typesOfSection(sectionId: string): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const r of RULES) {
    if (r.section !== sectionId || seen.has(r.type)) continue;
    seen.add(r.type);
    out.push(r.type);
  }
  return out;
}

/**
 * До якої групи належить товар.
 *
 * Бренд у назві не зрізаємо: правила дивляться на слова-іменники, а не на
 * перше слово, тож «SIGMA» попереду нікому не заважає. Зате зрізання
 * ламало б «STREND PRO» і «12 ATELIE», де бренд сам складається зі слів,
 * що трапляються в назвах товарів.
 */
export function classify(name: string): Classified | null {
  const text = normalizeName(name);
  for (const rule of RULES) {
    if (rule.re.test(text)) return { type: rule.type, section: rule.section };
  }
  return null;
}

/** Одне правило так, як його бачить аудит: із порядковим номером. */
export interface RuleHit extends Classified {
  /** Місце в RULES — саме воно вирішує суперечку, бо перше збіжне виграє. */
  index: number;
  label: string;
}

/**
 * Усі правила, що збіглися з назвою, а не лише переможець.
 *
 * classify() зупиняється на першому збігу — це і є механізм розвʼязання
 * суперечок, але він мовчазний: коли широке правило ручного інструменту
 * («ножиці», «ніж», «ключ») перехоплює захисні окуляри чи садовий секатор,
 * у базі лишається тільки результат, а не факт, що вибір узагалі був.
 *
 * Аудит (scripts/audit-classify.mts) читає всі збіги й показує, яке правило
 * кого затінило — з цього списку й народжуються нові правила-розвʼязання у
 * верхньому блоці RULES.
 */
export function classifyAll(name: string): RuleHit[] {
  const text = normalizeName(name);
  const out: RuleHit[] = [];
  RULES.forEach((rule, index) => {
    if (rule.re.test(text)) {
      out.push({ index, type: rule.type, section: rule.section, label: rule.label });
    }
  });
  return out;
}
