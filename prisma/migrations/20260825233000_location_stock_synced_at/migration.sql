-- Мітка «залишок підтвердив зріз 1С».
--
-- Регістр ТоварыНаСкладах віддає лише ненульові рядки: продана в нуль пара
-- «товар+склад» зникає з вивантаження. На інкрементальних прогонах агент
-- домальовує нуль сам — він знає, що позиція рухалась. На повному прогоні
-- такого списку немає, тож саме там залишок і застигав ненульовим.
ALTER TABLE "LocationStock" ADD COLUMN "syncedAt" TIMESTAMP(3);

-- Стартова точка відліку: без неї NULL не відрізнити від «зникло давно».
UPDATE "LocationStock" SET "syncedAt" = now();

CREATE INDEX "LocationStock_syncedAt_idx" ON "LocationStock"("syncedAt");
