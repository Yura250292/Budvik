-- Мітка «оплату підтвердило вивантаження 1С».
--
-- Запит ПКО бере лише проведені документи (`П.Проведен`), тож розпроведений
-- у 1С ордер зникає з вікна читання, а не приходить зі зміненим станом. Без
-- цієї мітки він назавжди лишався б на сайті: гроші, яких не було, рахувались
-- би торговому як зібрані, а рахунок стояв би оплаченим.
ALTER TABLE "Payment" ADD COLUMN "syncedAt" TIMESTAMP(3);

-- Стартова точка відліку для того, що вже прийшло з 1С: момент завантаження.
-- Оплати, заведені руками (source = 'MANUAL'), лишаються з NULL — вивантаження
-- 1С їх не підтверджує за визначенням, і звірка їх не чіпає.
UPDATE "Payment" SET "syncedAt" = "createdAt" WHERE source = '1C';

-- Звірка шукає за парою (source, syncedAt) у вікні дат оплати.
CREATE INDEX "Payment_source_syncedAt_idx" ON "Payment"("source", "syncedAt");
