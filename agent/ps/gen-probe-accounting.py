import os

def esc(s):
    """Рядок → вираз PowerShell без жодного не-ASCII символу.

    ASCII-шматки лишаються "літералами", решта (кирилиця й лапки) іде плоским
    масивом кодів: (-join [char[]]@(0x0412,0x042b,...)). Ланцюжок із сотень
    +[char] для парсера PS — глибоко вкладене дерево, масив — ні.
    """
    out, buf, codes = [], "", []
    def flush_buf():
        nonlocal buf
        if buf:
            out.append('"' + buf + '"'); buf = ""
    def flush_codes():
        nonlocal codes
        if codes:
            out.append("(-join [char[]]@(" + ",".join("0x%04x" % c for c in codes) + "))"); codes = []
    for ch in s:
        if ord(ch) < 128 and ch not in '"$`':
            flush_codes(); buf += ch
        else:
            flush_buf(); codes.append(ord(ch))
    flush_buf(); flush_codes()
    return "+".join(out) if out else '""'

