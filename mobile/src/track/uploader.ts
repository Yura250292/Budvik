/**
 * Стеля пачки. Сервер відхиляє понад 500 одним 400, і колись через це поїхав
 * увесь буфер разом — а з ним і день маршруту. 200 — те саме число, що в
 * Kotlin-службі.
 */
const MAX_BATCH = 200;

/** Скільки чекати між відправками, якщо точок мало. */
const FLUSH_INTERVAL_MS = 120_000;
/** Стільки точок — і відправляємо, не чекаючи інтервалу. */
const FLUSH_AT_POINTS = 10;
const HEARTBEAT_INTERVAL_MS = 180_000;

/**
 * Замок відправки — і мить її останнього поступу.
 *
 * Самого замка виявилося мало. 01.09 у полі стояли три планшети з буфером у
 * сотні точок: пульс ішов, GPS писав, помилок не було жодної — а точки не
 * їхали. Відправка висіла на запиті, який не завершиться ніколи (у тій збірці
 * ще не було тайм-ауту), і тримала замок до смерті процесу. Тайм-аут додано,
 * але покладатися лише на нього не можна: будь-яке нове зависання всередині
 * циклу знову зачинило б буфер назавжди — і знову мовчки.
 *
 * Тому замок тепер із поступом: він чинний, лише поки відправка рухається.
 * Стоїть довше за FLUSH_STALL_MS — його забирає наступна спроба.
 */
let flushing = false;
let flushProgressAt = 0;
/** Хто тримає замок: зависла спроба не має знімати його з-під живої. */
let flushOwner = 0;

/**
 * Мітка часу останньої точки, яку ми вже ВІДДАЛИ серверу в цьому процесі.
 *
 * Головне виправлення 03.09. Досі поступ відправки існував лише у вигляді
 * порожнього буфера: точки зникали з нього після підтвердження, і наступна
 * спроба читала те, що лишилось. Виглядало надійно — і трималося рівно до
 * дня, коли відправка почала зависати ПІСЛЯ того, як сервер пачку прийняв.
 *
 * Тоді видалення не відбувалося, буфер не порожнів, і кожна нова спроба
 * везла те саме. Поки буфер був менший за пачку, разом зі старим їхав і
 * свіжий хвіст, тож збою ніхто не бачив. А коли переріс — у пачці не
 * лишалося жодної нової точки, і трек на карті ставав. Планшет при цьому
 * щохвилини звітував «пишу, зв'язок є» — і був правий.
 *
 * Курсор рухається ПЕРЕД відправкою, а не після підтвердження: сервер або
 * прийняв пачку (тоді повторювати нічого), або відповів помилкою — і тоді
 * курсор вертається на місце тут же, у catch. Зависання лишається єдиним
 * випадком, коли ми не знаємо відповіді, і саме там дорожча помилка —
 * тиснути серверу те саме, замість того щоб везти нове.
 *
 * У пам'яті, а не у сховищі, і це навмисно: після перезапуску процесу
 * курсор порожній, буфер віддається з початку, а сервер відсіює повтори сам
 * (`recordedAt` — унікальний ключ у межах доби). Збережений курсор у тій
 * самій ситуації міг би пропустити точки, яких сервер так і не отримав.
 */
let sentThrough: string | null = null;

/**
 * Скільки відправка може стояти без поступу, перш ніж її визнають зависною.
 *
 * Утричі більше за межу однієї пачки (90 с у staffRequest): повільна сільська
 * мережа в неї вкладається, а запит, який не завершиться ніколи, — ні.
 */
const FLUSH_STALL_MS = 5 * 60_000;

/**
 * Крок відправки з власною межею часу — і з іменем кроку в помилці.
 *
 * Тайм-аут у staffRequest прикриває рівно одне: очікування відповіді сервера.
 * Але 01.09 відправка зависала й на 1.4.0, де той тайм-аут уже стояв, — отже
 * вішає щось поза ним. Найімовірніше сам запит: у React Native скасування
 * через AbortController не завжди доходить до з'єднання, яке застрягло на
 * рівні Android, і тоді обіцянка не завершується ніколи.
 *
 * Гонка нижче не скасовує зависле — воно лишається висіти в порожнечі й
 * помирає разом із процесом. Але вона робить дві речі, яких бракувало:
 * звільняє замок і НАЗИВАЄ крок. Наступного разу не доведеться гадати, у
 * якому з чотирьох місць стоїть відправка, — це буде написано в пульсі.
 */
function step<T>(what: string, ms: number, run: () => Promise<T>): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  return Promise.race([
    run().finally(() => clearTimeout(timer)),
    new Promise<never>((_, reject) => {
      timer = setTimeout(
        () => reject(new Error(`Крок «${what}» не завершився за ${Math.round(ms / 1000)} с`)),
        ms
      );
    }),
  ]);
}

/**
 * Скільки точок беремо в пачку ЗАРАЗ.
 *
 * Пачка на 200 точок — це десятки кілобайт, і на сільському каналі саме вона
 * застрягає першою, тоді як пульс на кілька сотень байтів проходить. Тому
 * після невдачі ріжемо пачку навпіл, а після вдалої — вертаємо стелю. Так
 * поганий зв'язок сповільнює відправку, замість того щоб зупиняти її зовсім.
 */
let batchSize = MAX_BATCH;
const MIN_BATCH = 25;

/**
 * Віддає буфер пачками, доки він не спорожніє.
 *
 * Видаляє РІВНО те, що сервер підтвердив, і аж після відповіді: у цю мить трек
 * пишеться далі, і зріз «перші N» зніс би свіжі точки, яких сервер не бачив.
 */
export async function flush(force = false): Promise<void> {
  /**
   * `force` — для виходу з акаунта: там після відправки буфер СТИРАЄТЬСЯ, тож
   * тихе повернення на замку означає не «відкладемо», а «день видалено».
   * Чекати п'ять хвилин на визнання замка зависним у цьому місці нема коли.
   */
  const stalled = flushing && (force || Date.now() - flushProgressAt >= FLUSH_STALL_MS);
  if (flushing && !stalled) return;

  const me = ++flushOwner;
  flushing = true;
  flushProgressAt = Date.now();

  /**
   * Запис стану теж під межею і теж мовчазний: пульс — це довідка, і
   * зависання на ній не має тримати саму відправку. Саме через те, що ці
   * рядки були звичайними await, помилка не встигала дійти до сервера.
   */
  const note = async (msg: string | null) => {
    try {
      await step("запис стану", 10_000, () => setLastError(msg));
    } catch {
      /* стан — не робота */
    }
  };
  const markSent = async () => {
    try {
      await step("позначка відправки", 10_000, () => setLastFlushAt(Date.now()));
    } catch {
      /* те саме */
    }
  };

  // Про зависання мусить дізнатися сервер: без цього рядка в пульсі не
  // лишається сліду, і причина знову виглядає як «немає зв'язку».
  if (stalled) await note("Відправка зависла — почато заново");

  /**
   * Стеля обертів за один злив.
   *
   * Замок тримається, поки цикл крутиться, — і поки він чинний, кожна нова
   * спроба тихо повертається на першому ж рядку. Досить одного шляху, на
   * якому пачка їде, а буфер не порожніє (сервер прийняв, видалення тихо не
   * спрацювало), щоб цикл став вічним, а відправка — назавжди зачиненою.
   * Ззовні це виглядає рівно як зависання, і 03.09 ми чотири години не могли
   * відрізнити одне від одного.
   *
   * Двадцять обертів — це до чотирьох тисяч точок, тобто більше за будь-який
   * реальний денний буфер. Хвіст, якщо він колись буде, забере наступний
   * оберт через дві хвилини.
   */
  const MAX_ROUNDS = 20;
  let rounds = 0;

  try {
    for (;;) {
      if (++rounds > MAX_ROUNDS) {
        await note(`Злив зупинено на ${MAX_ROUNDS} пачках — буфер не порожніє`);
        break;
      }
      const slice = await step("читання буфера", 20_000, () => pointsAfter(sentThrough, batchSize));
      if (slice.length === 0) {
        /**
         * Нових точок немає, а буфер не порожній — значить, підтвердження
         * попередніх пачок загубилися разом із зависанням, і рядки лишилися
         * лежати. Сервер їх найімовірніше має, але певності немає, тож
         * віддаємо ще раз: повтор він відсіє сам, а втрачений день — ні.
         */
        if (sentThrough != null && (await bufferedCount()) > 0) {
          sentThrough = null;
          continue;
        }
        break;
      }

      /**
       * Фаза їде одна на пачку, а буфер може містити межу закриття зміни:
       * робочі точки і дорога додому лежать поруч. Тому ріжемо пачку на першій
       * зміні фази — інакше вечірні кілометри лягли б у робочий пробіг, і
       * рахунок дня розійшовся б із одометром. Хвіст забере наступний оберт.
       */
      const phase = slice[0]?.phase ?? undefined;
      const cut = slice.findIndex((p: BufferedPoint) => (p.phase ?? undefined) !== phase);
      const batch = cut === -1 ? slice : slice.slice(0, cut);

      /**
       * Курсор рухаємо ДО відправки — див. sentThrough. Попереднє значення
       * тримаємо, щоб на явній відмові сервера вернути його назад.
       */
      const markBefore = sentThrough;
      sentThrough = batch[batch.length - 1]?.recordedAt ?? sentThrough;
      /**
       * Чи дійшла пачка. Далі в тому самому try падають ще й видалення та
       * позначки — а вони трапляються ПІСЛЯ того, як сервер пачку взяв.
       * Вертати на них курсор означало б знову везти серверу те, що він уже
       * має, тобто рівно та поведінка, від якої ми тут і лікуємось.
       */
      let landed = false;

      try {
        await step("відправка пачки", 120_000, () =>
          staffApi.trackPoints({
            points: batch.map((p: BufferedPoint) => ({
              lat: p.lat,
              lng: p.lng,
              accuracyM: p.accuracyM ?? undefined,
              speedKmh: p.speedKmh ?? undefined,
              headingDeg: p.headingDeg ?? undefined,
              // Час пристрою, а не час відправки: на ньому тримається і дедуп на
              // сервері, і сам порядок точок у дні.
              recordedAt: p.recordedAt,
            })),
            phase: phase ?? undefined,
          })
        );
        landed = true;
        await step("видалення надісланого", 20_000, () => dropPoints(batch));
        await note(null);
        /**
         * Пачка пройшла — ростемо вдвічі, а не стрибаємо на стелю.
         *
         * Стрибок був хибним висновком: успіх пачки на 25 точок не обіцяє,
         * що пройде пачка на 200. На каналі, який тягне лише малі пачки, це
         * давало вічну пилку — 200 падає, 100 падає, 50 падає, 25 проходить,
         * і знову 200. Три падіння коштують по межі часу кожне, тобто шість
         * хвилин на кожні 25 доставлених точок, тоді як нові пишуться далі.
         * Буфер за таких умов не спорожніє ніколи.
         *
         * Подвоєння вертає стелю за три вдалі пачки, якщо канал справді
         * тримає, і лишається на робочому розмірі, якщо ні.
         */
        batchSize = Math.min(MAX_BATCH, batchSize * 2);
        /**
         * Позначка «остання вдала відправка» — після КОЖНОЇ пачки, а не коли
         * буфер спорожніє. Інакше довгий злив виглядає з сервера як цілковите
         * мовчання: рівно так і виглядав день, з якого це почалося.
         */
        await markSent();
        flushProgressAt = Date.now();
      } catch (e) {
        const status = e instanceof StaffApiError ? e.status : 0;

        /**
         * Впала сама відправка — отже пачки в сервера немає (або він її не
         * візьме). Курсор вертається на місце: наступна спроба почне саме з
         * неї. Якщо ж пачка вже долетіла, курсор лишається зрушеним.
         */
        if (!landed) sentThrough = markBefore;

        /**
         * 401 обробляє сам клієнт (стирає токен і зупиняє службу) — тут лишаємо
         * буфер недоторканим: людина увійде знову, і день доїде.
         */
        if (status === 401) throw e;

        /**
         * Решта 4xx, крім 403 і 429, — це «сервер ніколи не прийме цю пачку».
         * Тримати її означало б забити буфер назавжди і втратити все, що після
         * неї. 403 віддає захист хостингу, 429 — стеля частоти: обидва минають.
         */
        if (status >= 400 && status < 500 && status !== 403 && status !== 429) {
          await step("видалення відхиленого", 20_000, () => dropPoints(batch)).catch(() => {});
          // Пачку викинуто назавжди — вертати на неї курсор нема сенсу.
          sentThrough = batch[batch.length - 1]?.recordedAt ?? sentThrough;
          await note(`Пачку відхилено (${status})`);
          flushProgressAt = Date.now();
          continue;
        }

        // Не долетіло — наступного разу пробуємо меншою пачкою.
        batchSize = Math.max(MIN_BATCH, Math.floor(batchSize / 2));
        await note(e instanceof Error ? e.message : String(e));
        return; // мережа або сервер — спробуємо наступного разу
      }
    }
    await markSent();
  } catch (e) {
    /**
     * Усе, що впало ПОЗА відправкою пачки, досі зникало безслідно.
     *
     * Внутрішній catch нижче стереже рівно один крок — саму пачку. Читання
     * буфера, видалення надісланого, позначка часу лишалися голими: їхня
     * помилка летіла повз нього, повз maybeFlush і onLocations, і гасла в
     * task.ts, де виняток душать навмисно (інакше Android перестане будити
     * завдання). Коментар там обіцяє «причина осідає в lastError» — для цієї
     * половини випадків обіцянка була порожня.
     *
     * Коштувало це 03.09 цілого дня трьох торгових: у пульсі чотири години
     * висіла фраза «Відправка зависла — почато заново», записана о 09:10, а
     * що саме падало відтоді — не знав ніхто. Причину шукали в мережі, хоча
     * пульс тією самою мережею проходив щохвилини.
     *
     * Тепер будь-яке падіння називає свій крок: step() уже вшив назву в текст
     * помилки, лишалося її не загубити.
     */
    await note(e instanceof Error ? e.message : String(e));
  } finally {
    // Замок знімає лише його власник: зависла спроба, яка нарешті відповіла,
    // не має відчиняти буфер з-під тієї, що працює просто зараз.
    if (flushOwner === me) flushing = false;
  }
}

/** Чи час відправляти: або назбиралося, або минув інтервал. */
export async function maybeFlush(): Promise<void> {
  const [count, last] = await Promise.all([unsentCount(sentThrough), getLastFlushAt()]);
  if (count === 0) return;
  if (count >= FLUSH_AT_POINTS || Date.now() - last >= FLUSH_INTERVAL_MS) {
    await flush();
  }
}

/** Не частіше ніж раз на стільки нагадуємо про вимкнену геолокацію. */
const LOCATION_OFF_WARN_MS = 30 * 60_000;
const LOCATION_OFF_KEY = "locationOffWarnedAt";

/**
 * Межа та сама, що й у попередження про зупинений запис: пульс іде раз на
 * три хвилини, і без неї планшет дзвенів би двадцять разів на годину.
 */
async function warnLocationOff(): Promise<void> {
  const last = Number(await getMeta(LOCATION_OFF_KEY).catch(() => null)) || 0;
  if (Date.now() - last < LOCATION_OFF_WARN_MS) return;
  await setMeta(LOCATION_OFF_KEY, String(Date.now())).catch(() => {});
  await notifyNow(
    "Геолокацію вимкнено",
    "Маршрут пишеться приблизно, по вежах. Увімкніть визначення місця в налаштуваннях планшета."
  );
}

/**
 * Пульс: сервер має бачити живий пристрій навіть тоді, коли точок немає.
 *
 * Без нього мовчання планшета неможливо відрізнити від «людина не виїхала».
 * Відповідь заразом звіряє локальний стан із серверним: зміну міг закрити офіс,
 * і застосунок мусить дізнатися про це, а не малювати своє.
 */
export async function heartbeat(force = false): Promise<{ shouldTrack: boolean } | null> {
  // Межу рахуємо від СПРОБИ, а не від успіху: без зв'язку успіху немає
  // взагалі, і пульс ломився б у мережу на кожній пачці фіксів.
  const lastTry = await getLastHeartbeatTryAt();
  if (!force && Date.now() - lastTry < HEARTBEAT_INTERVAL_MS) return null;
  await setLastHeartbeatTryAt(Date.now());

  const { isTracking } = await import("./controller");
  const subscribed = await isTracking().catch(() => null);

  const [
    buffered,
    mode,
    shiftOpen,
    fix,
    fixAt,
    lastError,
    startError,
    startErrorMeta,
    lastSync,
    device,
    watchdogAt,
    watchdogStatus,
  ] = await Promise.all([
    unsentCount(sentThrough),
    getMode(),
    isShiftOpen(),
    getLastFix(),
    getLastFixAt(),
    getLastError(),
    getStartError(),
    getStartErrorMeta(),
    getLastFlushAt(),
    readDeviceState(),
    getWatchdogRun(),
    getWatchdogStatus(),
  ]);

  /**
   * Коли запис не піднявся — це головніше за будь-яку скаргу буфера: там даних
   * немає взагалі, а тут вони просто чекають. Тому причина запуску йде першою і
   * не може бути затерта мережевою дрібницею.
   */
  /**
   * Префікс лише для СПРАВЖНЬОЇ невдачі запуску. Разова проба приймача пише в
   * той самий канал, і з префіксом виходило «Запис не піднявся: проба
   * приймача: ±12 м» — тобто текст казав протилежне до того, що сталося.
   * Читати ці рядки доводиться саме тоді, коли шукаєш поламку, і брехати вони
   * не мають права.
   */
  /**
   * До причини додаємо її вік і кількість спроб.
   *
   * Рядок без віку читається як свіжий, і саме так 02.09 тридцять сім
   * однакових пульсів Олександра виглядали як тридцять сім відмов — тоді як
   * це була одна, записана вранці. Час тут дорожчий за самий текст: він
   * відповідає на питання «це зараз чи вже полагодилось».
   */
  const startErrorAge =
    startErrorMeta && startError
      ? ` (${new Date(startErrorMeta.at).toLocaleTimeString("uk-UA", {
          hour: "2-digit",
          minute: "2-digit",
        })}` + (startErrorMeta.count > 1 ? `, спроб ${startErrorMeta.count})` : ")")
      : "";

  const problem = startError
    ? startError.startsWith("проба приймача")
      ? startError
      : `Запис не піднявся${startErrorAge}: ${startError}`
    : lastError;

  /**
   * Геолокацію вимкнули перемикачем — сказати про це НЕГАЙНО.
   *
   * Стан, у якому все виглядає справним: служба працює, картка в шторці
   * висить, застосунок відкривається. А координати приходять по вежах із
   * похибкою в сотні метрів, і день пишеться районами замість вулиць — у
   * Валентина так минув майже весь серпень, і побачили ми це лише з бази.
   *
   * Офіс дізнається про це з пульсу, але офіс не в машині. Людина в машині
   * дізнається лише звідси.
   */
  if (device.locationMode === "OFF" && (shiftOpen || (await getRole()) === "DRIVER")) {
    await warnLocationOff().catch(() => {});
  }

  try {
    const pulse = await staffApi.heartbeat({
      reportedAt: new Date().toISOString(),
      tracking: mode !== null,
      /**
       * Що каже САМА система, а не наш прапорець режиму. Два стани, які досі
       * зливалися в один: «ми думаємо, що пишемо» і «підписка справді жива».
       */
      subscribed: subscribed ?? undefined,
      mode: mode ?? "NONE",
      shiftOpen,
      buffered,
      /**
       * Пізніше з двох: мітка фікса або час останньої записаної точки. Одна
       * мітка вже колись розійшлася з дійсністю й спричинила хибну тривогу
       * «приймач мовчить» на планшеті, який у ту саму мить писав трек.
       */
      lastFixAt: fixAt != null ? new Date(fixAt).toISOString() : undefined,
      lastFixAccuracyM: fix?.accuracyM ?? undefined,
      lastSyncAt: lastSync ? new Date(lastSync).toISOString() : undefined,
      lastError: problem ?? undefined,
      /**
       * Стан пристрою — заради відповіді на питання «чому трек обірвався».
       * Ті самі значення, що шле Kotlin-трекер, щоб адмінка не мала двох шкал.
       */
      locationPermission: device.locationPermission,
      locationMode: device.locationMode,
      batteryPct: device.batteryPct ?? undefined,
      batteryOptimized: device.batteryOptimized ?? undefined,
      appVersion: APP_BUILD,
      // Прошивка планшета: різні оболонки по-різному душать фон, і без цього
      // рядка кожен розбір «чому в нього не пише» починається з дзвінка.
      osVersion: device.osVersion ?? undefined,
      osBuild: device.osBuild ?? undefined,
      /**
       * Коли сторож прокидався востаннє і чи дозволяє йому система працювати
       * взагалі. Без цих двох полів «пульсу немає» означало і мертвий
       * застосунок, і сплячий сторож при живому треку — тобто не означало
       * нічого.
       */
      watchdogAt: watchdogAt ? new Date(watchdogAt).toISOString() : undefined,
      watchdogStatus: watchdogStatus ?? undefined,
    });
    await setLastHeartbeatAt(Date.now());

    // Правда про зміну — серверна: її міг закрити офіс, поки планшет був поза мережею.
    if (typeof pulse?.shiftOpen === "boolean" && pulse.shiftOpen !== shiftOpen) {
      await setShiftOpen(pulse.shiftOpen);

      /**
       * Зміну закрили не з цього пристрою — офіс або автозакриття.
       *
       * Без цієї гілки служба лишалася б у робочому режимі з карткою «зміна
       * відкрита»: людина бачила б одне, а сервер знав інше, і трек далі
       * писався б як робочий. Тому переводимо запис у режим «після зміни» й
       * кажемо людині, що сталося — інакше вона дізнається про це аж тоді,
       * коли не зійдеться пробіг.
       *
       * Водія не чіпаємо: він зміну не відкриває взагалі, і його трек іде від
       * входу до виходу (див. controller.onStaffLogin).
       */
      if (!pulse.shiftOpen) {
        const role = await getRole();
        if (role !== "DRIVER") {
          const { endShiftTracking } = await import("./controller");
          await endShiftTracking();
          // Нагадування «зміна ще відкрита» тепер брехали б: її вже
          // закрито, і о 19:30 людина отримала б спонукання зробити те,
          // що зроблено.
          await cancelCloseReminders();
          await notifyNow(
            "Зміну закрито",
            "Зміну закрито не з цього пристрою. Зранку сфотографуйте одометр — інакше пробіг порахується за GPS."
          );
        }
      }
    }
    return { shouldTrack: pulse?.shouldTrack ?? false };
  } catch {
    // Пульс — довідка, а не робота: його втрата не має нічого ламати.
    return null;
  }
}
