-- Роздріб з опту для брендів без роздрібної ціни в 1С.
--
-- TOTAL (433 товари) і POLAX (983) заведені в 1С лише типами «2.ВХІД USD»,
-- «4.ОПТ», «5.VIP» — «6.МАГАЗИНИ», який тягне агент, для них порожній, тому
-- на сайті вони стояли з ціною 0 і не показувались. Рішення власника
-- (25.08.2026): роздріб = опт × коефіцієнт, за замовчуванням 1,3 (у SIGMA,
-- де роздріб заведений, він саме такий), з можливістю задати свій по бренду.
ALTER TABLE "Brand" ADD COLUMN "retailMarkup" DOUBLE PRECISION;

-- Мітка «ціна розрахункова»: без неї не відрізнити ціну, яку назвала 1С, від
-- тієї, що порахував сайт, а отже — не перерахувати при зміні коефіцієнта і
-- не замінити справжньою, коли «6.МАГАЗИНИ» в 1С нарешті зʼявиться.
ALTER TABLE "Product" ADD COLUMN "priceDerived" BOOLEAN NOT NULL DEFAULT false;
