/**
 * Порядок точок маршруту: нумерація і хвіст.
 *
 * Обидва правила народилися з одного бага. Оптимізатор бачить лише точки
 * з координатами, а список у планувальнику — усі; поки нумерація велася
 * незалежно, «четвертий» на карті і «четвертий» у списку були різними
 * клієнтами, а точки без піна після збереження ще й розліталися в
 * середину списку зі своїми старими номерами.
 *
 * Тому номер — це позиція РЯДКА маршруту, а не піна на карті, і зберігати
 * порядок треба одразу для всього маршруту, а не для його геокодованої
 * частини.
 */

/**
 * Проставляє номери по рядках маршруту.
 *
 * Одна точка на карті може представляти кілька рядків: дві накладні на ту
 * саму адресу водій везе за одну зупинку (див. mergeByAddress у
 * day-stops). Такий пін займає стільки номерів, скільки рядків склеїв, —
 * інакше номери піна й списку розійшлися б рівно на кількість дублів.
 */
export function sequenceByRows<T extends { mergedKeys: string[] }>(
  points: T[]
): Array<T & { sequence: number }> {
  let row = 0;
  return points.map((p) => {
    const sequence = row + 1;
    row += Math.max(1, p.mergedKeys.length);
    return { ...p, sequence };
  });
}

/**
 * Дописує в кінець те, чого немає в запропонованому порядку.
 *
 * Точки без координат в оптимізацію не потрапляють. Якщо їх не
 * перенумерувати разом з усіма, вони лишаться зі старими номерами (5, 8,
 * 11) і перетнуться з новими 1…N — у списку це виглядає так, ніби
 * маршрут переплутався сам собою. Порядок серед «дописаних» зберігаємо
 * той, що був.
 */
export function appendMissing(order: string[], all: string[]): string[] {
  const seen = new Set<string>();
  const head: string[] = [];
  for (const id of order) {
    if (!all.includes(id) || seen.has(id)) continue;
    seen.add(id);
    head.push(id);
  }
  return [...head, ...all.filter((id) => !seen.has(id))];
}
