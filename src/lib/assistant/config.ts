/**
 * Кому даємо міркування — і тільки тому.
 *
 * Заміряно пробою `scripts/probe-deepseek-thinking.mts` на питанні «у трьох
 * торгових такі обороти й така дебіторка, кому не давати відстрочку»:
 * без міркувань модель обрала НЕ ТОГО і пояснила це плутано, з
 * міркуваннями — обрала правильного й назвала причину (дебіторка 84%
 * обороту). Це рівно той клас питань, з якими приходять до помічника
 * керівника: зважити й проранжувати, а не знайти.
 *
 * Чому не всім. Торговий, водій і складовщик питають «де», «скільки» й
 * «кому везти». Там міркування додають секунди й токени, не додаючи
 * правильності, — а саме для цього все й будувалося швидким.
 *
 * Кого це насправді охоплює: вид ADMIN дає kindForThread лише офісу
 * (ADMIN і MANAGER) і лише в розмові про ВСЮ фірму. Щойно керівник обирає
 * конкретного торгового, вид інший, і хід знову швидкий — тобто думання
 * вмикається саме там, де питання загальне й відповідь треба зважити.
 *
 * Заміряно на бойовому прогоні 11.09.2026 («середній чек у серпні проти
 * вересня, і чи це через менші замовлення, чи через менше клієнтів»):
 * без міркувань модель порівняла повний серпень з 11 днями вересня й
 * відповіла «впало все одразу» — неправильно; з міркуваннями перевела
 * обидва періоди в денні темпи й знайшла справжню причину. Ціна: 45 с
 * проти 9 с і 80 тис. токенів проти 28 тис.
 *
 * Вимкнути цілком, не чіпаючи код: ASSISTANT_THINKING=off.
 */
export const THINKING_KINDS: readonly AssistantKind[] = ["ADMIN"];

/** Запобіжник на випадок, якщо міркування почнуть шкодити в проді. */
