import type { AssistantKind } from "@/lib/assistant/types";

/**
 * Розпізнавання наміру без моделі.
 *
 * Дев'ять із десяти питань торгового — це та сама десятка запитів:
 * «сплануй день», «хто винен», «з чим зайти до Химича», «що там із
 * мертвим», «скільки я продав». На кожен з них у базі є точна відповідь,
 * і платити моделі за те, щоб вона переказала готовий список, немає сенсу:
 * хід через модель коштує 20-30 тисяч токенів і 12-30 секунд, а той самий
 * список код складає за секунду й безкоштовно.
 *
 * Тому модель тут — не головний шлях, а запасний. Вона вмикається на
 * питаннях, яких немає в цьому списку: порівняти, пояснити, зважити «чи
 * давати відстрочку», зв'язати кілька фактів докупи.
 *
 * ДВІ МЕЖІ, за які цей розпізнавач не переступає.
 *
 * Перша: жодних здогадів. Якщо шаблон не збігся дослівно — повертаємо
 * null і йдемо до моделі. Хибно розпізнаний намір гірший за виклик
 * моделі: людина дістане впевнену відповідь не на своє питання.
 *
 * Друга: посилання на попередню репліку («а в нього скільки?», «а що з
 * тим клієнтом») ідуть до моделі завжди. Код не знає, про кого мова, а
 * вгадувати тут — те саме, що вигадувати.
 */

const WEEKDAYS: Array<[RegExp, number]> = [
  [/понеділ/i, 1],
  [/вівтор/i, 2],
  [/серед[аиу]/i, 3],
  [/четвер/i, 4],
  [/п.?ятниц/i, 5],
  [/субот/i, 6],
  [/неділ/i, 7],
];

