/**
 * Розбір брудних адрес клієнтів з 1С для геокодера.
 *
 * Адреси написані для людини: «м..Львів, вул.Городницька,47 маг.Е1»,
 * «м.Стрий, Базар, вул.Зелена 25 маг.Садиба», «Мартинець Уляна (м.Мостиська)».
 * Геокодер на хвостах здається і повертає центр міста, тож звідси беремо
 * лише потрібне: вулицю з будинком, населений пункт, назву магазину.
 *
 * Граблі: `\b` у JS не знає кирилиці — «\b(маг|ряд)\b» різало «Магерова» й
 * «Городницька». Тому тут витягуємо потрібне, а не вичищаємо навколо.
 */

const HOME_REGION = "Львівська область";

/**
 * Населений пункт: «м.Львів», «смт.Шкло», «с.Солонка». Беремо ОСТАННІЙ у
 * рядку — «м. Львів, с.Солонка, вул.Стрийська» означає село Солонка під
 * Львовом, і вулиця там своя. Двослівні назви теж: «Новий Розділ»,
 * «Рава-Руська», «Кам'янка-Бузька».
 */
export function settlementOf(address: string): string | null {
  // «м.Камянка -Бузька» — пробіл перед дефісом рвав назву надвоє.
  const raw = address.replace(/\s*-\s*(?=[А-ЯІЇЄҐ])/gu, "-");
  const places = [
    ...raw.matchAll(
      /(?:^|[,(\s])(?:м|с|смт|с-ще|село|місто|селище)\.{0,2}\s*([А-ЯІЇЄҐ][А-ЯІЇЄҐа-яіїєґ'`’\-]{2,}(?:\s+[А-ЯІЇЄҐ][а-яіїєґ'`’\-]{2,})?)/gu
    ),
  ];
  const city = places.at(-1)?.[1];
  if (city) return withApostrophe(city);

  // Без префікса: «Золочів, вул.Бродівська 19», «НОВА ПОШТА №1, Ахтирка, вул…»,
  // «Rozetka.Надвірна,вул…». Перша частина, яка після зняття службового
  // (пошта, №, дужки) — одне-два слова з великої літери без цифр і не вулиця.
  const parts = raw.replace(/(rozetka|розетка)\s*\./giu, "$1,").split(/[,;]/);
  for (const part of parts) {
    const t = part
      .replace(/\([^)]*\)/g, " ")
      .replace(/(нова\s*пошта|meest\s*пошта|meest|rozetka|розетка|укрпошта|самовивіз|поштомат|відділення|пункт\s+приймання\s*-?\s*видачі|нп)/giu, " ")
      .replace(/№\s*\d+/g, " ")
      .replace(/\s+/g, " ")
      .trim();
    if (
      /^[А-ЯІЇЄҐ][а-яіїєґ'`’\-]{2,}(\s+[А-ЯІЇЄҐ][а-яіїєґ'`’\-]{2,})?$/u.test(t) &&
      !/^(вул|пров|просп|пл|бульв|площ|шосе)/iu.test(t)
    ) {
      return withApostrophe(t);
    }
  }
  return null;
}

/**
 * «Камянка-Бузька» з 1С → «Кам'янка-Бузька»: без апострофа OSM міста не
 * знаходить. Правило правопису: після губного (б, п, в, м, ф), перед яким
 * голосний, і перед я/ю/є/ї пишеться апостроф. Після збігу приголосних —
 * ні («Звягель»), тому вимагаємо голосний перед губним.
 */
export function withApostrophe(name: string): string {
  return name
    .replace(/[`’ʼ]/g, "'")
    .replace(/([аеєиіїоуюяАЕЄИІЇОУЮЯ])([бпвмфБПВМФ])([яюєї])/gu, "$1$2'$3");
}

/**
 * Вулиця з будинком + населений пункт (+ область для львівських адрес) — те,
 * що геокодер здатен знайти. null, якщо вулиці з номером у рядку немає.
 *
 * `lviv` — дописувати «Львівська область». Лише для адрес, які й так про
 * Львівщину: 24.09.2026 без цієї умови «НОВА ПОШТА №1, Ахтирка, вул. Шевченка 3»
 * ставала вул. Шевченка в Белзі, а «Чернігів, просп. Миру 49» — у Сокалі.
 * `requireSettlement` — без населеного пункту не віддавати нічого: вулиця
 * Шевченка з номером є в кожному місті, і пошук лише за нею — лотерея.
 */
export function cleanAddress(
  raw: string,
  opts: { lviv: boolean; requireSettlement?: boolean } = { lviv: true }
): string | null {
  const street = raw.match(
    /(вул|вулиц\w*|просп\w*|проспект|пл|площ\w*|пров|провул\w*|бульв\w*|шосе|наб\w*)[.\s]*([А-ЯІЇЄҐа-яіїєґ'.\-\s]{3,32}?)[,\s]+(?:буд\.?\s*)?(\d+[а-яА-Яa-zA-Z]?)/u
  );
  if (!street) return null;

  const [, kind, name, house] = street;
  // «Б.Хмельницького» → «Хмельницького»: ініціал Nominatim лише заважає.
  const cleanName = name
    .replace(/^(?:[А-ЯІЇЄҐ]\.\s*)+/u, "")
    .replace(/\s{2,}/g, " ")
    .trim();
  if (!cleanName) return null;

  const kindWord = /вул/i.test(kind)
    ? "вулиця"
    : /просп/i.test(kind)
      ? "проспект"
      : /пл|площ/i.test(kind)
        ? "площа"
        : /пров/i.test(kind)
          ? "провулок"
          : /бульв/i.test(kind)
            ? "бульвар"
            : kind;

  const settlement = settlementOf(raw);
  if (opts.requireSettlement && !settlement) return null;
  return [`${kindWord} ${cleanName}, ${house}`, settlement, opts.lviv ? HOME_REGION : null, "Україна"]
    .filter(Boolean)
    .join(", ");
}

/**
 * Назва магазину з адреси: «маг.Садиба», «магазин Будівельник», «ТЦ Епіцентр»,
 * «маг. "Ковка"». Для пошуку закладу за назвою (Google Places).
 */
export function shopNameOf(raw: string): string | null {
  const m = raw.match(
    /(?:^|[\s,(])(маг\.?|магазин|м-н|тц|тк|бмц|будмаркет)\s*[«"“']?\s*([А-ЯІЇЄҐA-Z][\wА-ЯІЇЄҐа-яіїєґ'\-]{2,}(?:\s+[А-ЯІЇЄҐA-Z][\wА-ЯІЇЄҐа-яіїєґ'\-]{2,})?)/u
  );
  if (!m) return null;
  const kind = /^(тц|тк|бмц)$/iu.test(m[1]) ? m[1].toUpperCase() + " " : "";
  return `${kind}${m[2]}`.trim();
}

/**
 * Населений пункт із назви клієнта: «Мартинець Уляна (м.Мостиська)».
 *
 * У дужках буває й вулиця — «DNIPRO-M ЛЬВІВ (Джорджа Вашингтона, 1)», —
 * тому беремо лише те, що позначене як населений пункт (м./с./смт) або
 * складається з одного слова без цифр. Інакше геокодер шукав би вулицю
 * без міста й ставив пін у випадковій області: рівно так маршрут колись
 * вийшов 837 км замість 150.
 *
 * Область додається завжди: однойменних сіл в Україні десятки.
 */
export function settlementFromName(name: string): string | null {
  const inside = name.match(/\(([^)]*)\)/)?.[1]?.trim();
  if (!inside) return null;

  const prefixed = inside.match(/(?:^|\s)(?:м|с|смт)\.?\s*([А-ЯЇІЄҐA-Z][^,;]*)/iu)?.[1]?.trim();
  const candidate =
    prefixed ?? (!/\d/.test(inside) && !inside.includes(",") && inside.split(/\s+/).length === 1 ? inside : null);

  if (!candidate || candidate.length < 3) return null;
  return `${candidate}, ${HOME_REGION}, Україна`;
}
