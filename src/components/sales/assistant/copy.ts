export function errorCopy(status: number, serverMessage?: string | null): string {
  if (status === 401 || status === 403) return "Немає доступу. Спробуйте увійти знову.";
  if (status === 404) return "Розмову не знайдено — можливо, її видалили.";
  if (status === 409) return "Попередня відповідь ще формується. Зачекайте кілька секунд.";
  if (status === 429) return "Ліміт запитів на сьогодні вичерпано. Помічник знову доступний завтра.";
  if (status === 503) return "Помічник тимчасово недоступний: не налаштовано ключ до моделі.";
  if (status === 504) return "Модель не відповіла вчасно. Спробуйте коротше питання або ще раз.";
  return serverMessage || `Не вдалося отримати відповідь (код ${status}).`;
}

