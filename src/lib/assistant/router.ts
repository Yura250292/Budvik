/**
 * Слова, що вказують на попередню репліку.
 *
 * «А в нього борг який?» — питання про клієнта, названого раніше. Шаблон
 * «борг» тут збігся б, і код відповів би зведенням по всій дебіторці:
 * впевнено й повз питання.
 */
const ANAPHORA = /(^|\s)(він|його|йому|ним|нього|вона|її|їй|цей|цього|цьому|там|туди|той|тому клієнт|ще раз|а що|а як|а скільки|а коли)(\s|[?.,!]|$)/i;

/**
 * Те, що виглядає як назва, але нею не є.
 *
 * «Що запропонувати цьому клієнту» — хвіст «цьому клієнту» формально
 * підходить під ім'я, і пошук за ним не знайде нічого; питання ж мало на
 * увазі клієнта, чию картку торговий щойно відкрив.
 */
const NOT_A_NAME =
  // Закінчення виписані як [а-яіїєґ], а не \w: у JavaScript \w — це ASCII,
  // і «клієнт\w*» не збігається з «клієнту» взагалі.
  /^((цьому|цього|цей|тому|того|цим|нашому|нашого|своєму)\s+)?(клієнт[а-яіїєґ]*|боржник[а-яіїєґ]*|магазин[а-яіїєґ]*|точ[кц][а-яіїєґ]*|контрагент[а-яіїєґ]*|йому|його|їм|когось|кого|всіх|усіх|них|мої|моїх|сьогодні|завтра|тут|це|щось|грош[а-яіїєґ]*|борг[а-яіїєґ]*|оплат[а-яіїєґ]*|замовлен[а-яіїєґ]*|продаж[а-яіїєґ]*|повернен[а-яіїєґ]*|точ[а-яіїєґ]*|нагадуван[а-яіїєґ]*|маршрут[а-яіїєґ]*|план[а-яіїєґ]*)$|^за\s+(тиждень|тижн[а-яіїєґ]*|місяц[ья]?|день|дні|днів|\d+\s*дн[а-яіїєґ]*|квартал|сьогодні|вчора)$/i;

/**
 * Хвіст, що починається зі сполучника чи питального слова, — це друга
 * половина питання, а не ім'я: «скільки винен і що памʼятаємо».
 */
const TAIL_NOT_NAME = /^(і|й|та|а|чи|що|як|коли|скільки|де|чому|навіщо|який|яка|яке)(\s|$)/i;

/**
 * Як питають про товар і залишок.
 *
 * Список довгий навмисно. «Скільки ще піни», «залишки піни», «що по
 * піні» — це те саме питання, і кожне непізнане формулювання коштує
 * дев'ять тисяч токенів і десять секунд там, де код відповідає за
 * секунду й безкоштовно.
 */
const PRODUCT_ASK =
  /(чи\s+є\s+(в\s+наявності\s+)?|скільки\s+(ще\s+)?(на\s+складі|залишилось|лишилось|є)\s*|який\s+залишок\s*|(скажи|покажи|глянь|подивись)\s+(мені\s+)?(який\s+)?(залиш[а-яіїєґ]*|наявність|ціну)?\s*(по|на)?\s*|залиш[а-яіїєґ]*\s+(по\s+)?|є\s+на\s+складі\s*|що\s+(там\s+)?по\s+|яка\s+ціна\s+(на\s+)?|почім\s+|скільки\s+кошту[а-яіїєґ]*\s+|скільки\s+ще\s+|скільки\s+|^(чи\s+)?є\s+)/i;

/**
 * Те саме питання з товаром ПОСЕРЕДИНІ: «скільки піни залишилось».
 *
 * PRODUCT_ASK ловить лише хвіст після ключових слів, а тут назва стоїть
 * між «скільки» і «залишилось» — і найчастіше питають саме так. Без цієї
 * гілки просте питання про залишок ішло в модель за дев'ять тисяч токенів.
 */
const PRODUCT_MIDDLE =
  /(?:скільки|чи)\s+(?:ще\s+|є\s+)?(.{2,40}?)\s+(?:ще\s+)?(?:залишилось|лишилось|залишилося|є\s+в\s+наявності|є\s+на\s+складі|на\s+складі|в\s+наявності)/i;

const clean = (raw: string) =>
  raw
    .replace(/[«»"'’`]/g, "")
    .replace(/[?!.,;:]+\s*$/g, "")
    .replace(/\s+/g, " ")
    .trim();

/** Хвіст питання після ключового слова — ім'я клієнта або назва товару. */
function subjectAfter(text: string, re: RegExp): string | null {
  const match = re.exec(text);
  if (!match) return null;

  const tail = clean(text.slice(match.index + match[0].length))
    .replace(/^(до|в|у|про|для|клієнта|клієнту|магазину|магазин)\s+/i, "")
    // «скільки в нас піни на складі» — питальні хвости не є назвою.
    .replace(/^(нас|мене|тебе|вас)\s+/i, "")
    // Хвіст «…залишилось на складі» — це питання, а не частина назви.
    .replace(
      /(\s+(на\s+складі|в\s+наявності|у\s+наявності|на\s+залишку|залишилось|залишилося|лишилось|лишилося|лишилися|є))+\s*$/i,
      ""
    )
    .replace(/\s+(і|та)\s+(чи|що|як|скільки)(\s|$).*$/i, "");

  /**
   * «Скільки я продав за тиждень» — це не назва товару.
   *
   * Широке «скільки …» ловить і питання про себе. У торгового такі
   * питання перехоплюються раніше власними шаблонами, а от у водія
   * шаблонів продажів немає взагалі — і хвіст «я продав за тиждень»
   * ішов у пошук товару.
   */
  if (/^(я|мені|мій|моя|моїх|мого|нам)\s/i.test(tail)) return null;

  if (tail.length < 3 || NOT_A_NAME.test(tail) || TAIL_NOT_NAME.test(tail)) return null;
  if (!/[а-яіїєґa-z]/i.test(tail)) return null;
  // Довгий хвіст — це вже не назва, а окреме питання.
  return tail.length > 60 ? null : tail;
}

/** Назва, затиснута між двома половинами питання. */
function subjectBetween(text: string, re: RegExp): string | null {
  const match = re.exec(text);
  if (!match?.[1]) return null;

  const name = clean(match[1]).replace(/^(ще|там|у\s+нас|в\s+нас|нам|мені)\s+/i, "");
  if (name.length < 3 || NOT_A_NAME.test(name) || TAIL_NOT_NAME.test(name)) return null;
  if (!/[а-яіїєґa-z]/i.test(name)) return null;
  return name;
}

function weekdayIn(text: string): number | null {
  for (const [re, n] of WEEKDAYS) if (re.test(text)) return n;
  return null;
}

/**
 * Який період мали на увазі.
 *
 * «Місяць» — це КАЛЕНДАРНИЙ місяць, з першого числа (рішення власника
 * 06.09.2026). Доти будь-яке «за місяць» перетворювалося на ковзні 30
 * днів, і в одній відповіді верхня сума йшла за 7 серпня — 6 вересня, а
 * блок плану під нею — з 1 вересня. Пояснити цю різницю неможливо, а
 * помічатися вона починає рівно тоді, коли за нею ухвалюють рішення.
 */
export type PeriodSpec =
  | { kind: "days"; days: number }
  /** offset 0 — поточний місяць, -1 — попередній. */
  | { kind: "month"; offset: 0 | -1 }
  /** Руками названі межі: «з 01.08 по 15.08». */
  | { kind: "range"; from: string; to: string };

/**
 * «за тиждень», «за місяць», «за 45 днів» — інакше типові 30.
 *
 * Межа слова тут виписана як (^|\s), а не \b. У JavaScript \b визначена
 * на ASCII-символах слова, тож перед кирилицею вона просто не спрацьовує:
 * /\bтижд/ не знаходить «за тиждень» узагалі, і період мовчки лишався
 * місячним на кожне питання про тиждень.
 */
function periodIn(
  text: string,
  fallback: PeriodSpec = { kind: "month", offset: 0 }
): PeriodSpec {
  if (/(^|\s)сьогодн/i.test(text)) return { kind: "days", days: 1 };
  if (/(^|\s)тижд|(^|\s)тижн/i.test(text)) return { kind: "days", days: 7 };
  if (/(^|\s)квартал/i.test(text)) return { kind: "days", days: 90 };

  /**
   * Межі руками: «з 01.08 по 15.08».
   *
   * Рік можна не називати — беремо поточний; якщо початок виявився
   * пізнішим за кінець, це минулорічний хвіст (грудень → січень).
   */
  const range = /з\s+(\d{1,2})[.\/](\d{1,2})(?:[.\/](\d{2,4}))?\s+(?:по|до)\s+(\d{1,2})[.\/](\d{1,2})(?:[.\/](\d{2,4}))?/i.exec(
    text
  );
  if (range) {
    const iso = (d: string, m: string, y: string | undefined, fallbackYear: number) => {
      const year = y ? (y.length === 2 ? 2000 + Number(y) : Number(y)) : fallbackYear;
      return `${year}-${String(Number(m)).padStart(2, "0")}-${String(Number(d)).padStart(2, "0")}`;
    };
    const year = new Date().getFullYear();
    const from = iso(range[1], range[2], range[3], year);
    const to = iso(range[4], range[5], range[6], year);
    if (from <= to) return { kind: "range", from, to };
    return { kind: "range", from: `${Number(from.slice(0, 4)) - 1}${from.slice(4)}`, to };
  }

  const explicit = /за\s+(\d{1,3})\s*(дн|день|днів|дні)/i.exec(text);
  if (explicit) {
    return { kind: "days", days: Math.min(365, Math.max(1, Number(explicit[1]))) };
  }

  if (/(минул|попередн)[а-яіїєґ]*\s+місяц/i.test(text)) return { kind: "month", offset: -1 };
  if (/(^|\s)(місяц|місяць)/i.test(text)) return { kind: "month", offset: 0 };

  return fallback;
}

/**
 * Прохання щось СКЛАСТИ, а не показати.
 *
 * «Склади лист клієнту про борг» містить слово «борг» і за шаблоном
 * потрапило б у зведення по дебіторці — тобто торговий попросив би текст,
 * а отримав таблицю. Такі питання — робота моделі за визначенням.
 */
const COMPOSE =
  /(склади|напиши|сформулюй|придумай|переклади|поясни|порівняй|чому|що\s+(мені\s+)?зробити|як\s+мені\s+(закрити|витягнути|підняти)|варто\s+ли|чи\s+(давати|варто|можна|треба))/i;

export function detectIntent(
  raw: string,
  opts: { hasHistory: boolean; hasClientHint?: boolean; kind?: AssistantKind }
): Intent | null {
  const text = clean(raw);
  if (!text) return null;

  // Продовження розмови — тільки модель: код не знає, про кого йшлося.
  if (opts.hasHistory && ANAPHORA.test(text)) return null;
  if (COMPOSE.test(text)) return null;

  if (opts.kind === "DRIVER") return driverIntent(text);
  if (opts.kind === "WAREHOUSE") return warehouseIntent(text);

  /* Спершу шаблони з назвою клієнта: «скільки винен Химич» — це картка
     клієнта, а не зведення по всій дебіторці. */

  const entry = subjectAfter(
    text,
    /(з\s+чим\s+(за)?(ходити|йти|їхати|заїжджати|зайти|заїхати)|з\s+чим\s+іти)/i
  );
  if (/з\s+чим\s+/i.test(text)) return { kind: "ENTRY_OFFER", subject: entry };

  const recommend = subjectAfter(
    text,
    /(що\s+(йому\s+|мені\s+)?(за)?пропонувати|що\s+порадити|що\s+продати)/i
  );
  if (/(що\s+(йому\s+|мені\s+)?(за)?пропонувати|що\s+порадити)/i.test(text)) {
    return { kind: "RECOMMEND", subject: recommend };
  }

  if (/(що\s+ти\s+(вмієш|можеш|умієш)|чим\s+(ти\s+)?(можеш\s+)?допоможеш|які\s+в\s+тебе\s+можливості|довідка|підказк[аи]\s+по\s+тобі)/i.test(text)) {
    return { kind: "HELP" };
  }

  /**
   * «Покажи останню накладну Кунанця».
   *
   * Перед карткою клієнта: інакше шаблон «покажи …» забирає питання собі
   * й показує профіль там, де просили конкретний документ.
   */
  const lastOrder = subjectAfter(
    text,
    /((покажи|дай|глянь)\s+)?(останн[ьяєюій]{1,3}|остатн[ьяєюій]{1,3})\s+(накладн[а-яіїєґ]*|замовлен[а-яіїєґ]*|документ[а-яіїєґ]*|реалізаці[а-яіїєґ]*|відвантаженн[а-яіїєґ]*)\s*(у|в|по|для)?\s*/i
  );
  if (lastOrder) return { kind: "LAST_ORDER", subject: lastOrder };
  if (/(останн[ьяєюій]{1,3}|остатн[ьяєюій]{1,3})\s+(накладн|замовлен|документ|реалізаці)/i.test(text)) {
    return { kind: "LAST_ORDER", subject: null };
  }

  /**
   * «Чи брав Налисник піну», «коли Кунанець брав дріт».
   *
   * Питання про ПЕРЕТИН клієнта й товару: до дієслова — ім'я, після —
   * товар. Найдорожче з усього, що досі йшло в модель (до 24 тисяч
   * токенів за хід), і найпростіше для коду: дані вже є в картці з
   * фільтром товару.
   */
  /**
   * Два порядки слів, обидва живі.
   *
   * «Налисник брав піну» — ім'я до дієслова. «Чи брав Налисник піну» —
   * після нього, і тоді ім'я це ОДНЕ слово, а решта — товар: інакше
   * розділити їх у «брав Налисник піну монтажну» неможливо.
   */
  const pair =
    /^(?:чи\s+|коли\s+|скільки\s+(?:разів\s+)?)?(.{3,40}?)\s+(?:колись\s+)?(?:брав|бере|брала|купував|купувала|замовляв|замовляла)\s+(?:колись\s+)?(.{3,40})$/i.exec(
      text
    ) ??
    /^(?:чи\s+|а\s+)?(?:брав|бере|брала|купував|купувала|замовляв|замовляла)\s+([^\s]{3,30})\s+(.{3,40})$/i.exec(
      text
    );
  if (pair) {
    const client = clean(pair[1]).replace(/^(клієнт|фоп|магазин)\s+/i, "");
    const product = clean(pair[2]).replace(/\s+(востаннє|останній\s+раз|коли|і\s+скільки|\?)+$/i, "");
    if (client.length >= 3 && product.length >= 3 && !NOT_A_NAME.test(client) && !NOT_A_NAME.test(product)) {
      return { kind: "CLIENT_PRODUCT", subject: client, product };
    }
  }

  const card =
    subjectAfter(text, /(скільки\s+винен|який\s+борг\s+(у|в)|борг\s+(у|в))/i) ??
    subjectAfter(text, /(що\s+з\s+|розкажи\s+про\s+|профіль\s+|картка\s+|що\s+ми\s+знаємо\s+про\s+|хто\s+такий\s+)/i);
  if (card) return { kind: "CLIENT_CARD", subject: card };

  /**
   * Питання без назви, коли помічник відкрито з картки клієнта.
   *
   * «Скільки винен» на екрані конкретного магазину означає саме його — і
   * без цієї гілки воно потрапляло б у зведення по всій дебіторці, тобто
   * відповідь була б про інше й виглядала б упевнено.
   */
  if (
    opts.hasClientHint &&
    /(скільки\s+винен|який\s+борг|що\s+ми\s+(про\s+нього\s+)?(знаємо|пам.ята)|пам.ять\s+про|що\s+з\s+ним|що\s+брав|що\s+замовляв|останнє\s+замовлення)/i.test(
      text
    )
  ) {
    return { kind: "CLIENT_CARD", subject: null };
  }

  /* Далі — питання без назви клієнта. */

  /**
   * План дня. День питаємо, коли його не назвали.
   *
   * «Сплануй мій день» о шостій вечора найчастіше означає «на завтра», а
   * о дев'ятій ранку — «на сьогодні». Вгадувати тут дорого: людина
   * поїде не туди й не тоді. Один дотик по кнопці дешевший за зіпсований
   * день, тому без явного дня показуємо вибір.
   */
  if (
    /(сплануй|які\s+клієнт[а-яіїєґ]*\s+(сьогодні|завтра)|кого\s+(сьогодні|завтра)|план\s+(на\s+)?(день|сьогодні|завтра|понеділок|вівторок|середу|четвер|п.?ятницю|суботу|неділю)|кого\s+(сьогодні|завтра|мені)?\s*(відвід|об.?їх)|куди\s+(мені\s+)?(сьогодні|завтра)\s+(їхати|їздити)|маршрут\s+на\s+(сьогодні|завтра|понеділок|вівторок|середу|четвер|п.?ятницю|суботу|неділю))/i.test(
      text
    )
  ) {
    const weekday = weekdayIn(text);
    if (/завтра/i.test(text)) return { kind: "DAY_PLAN", day: "tomorrow", weekday: null };
    if (/сьогодні/i.test(text)) return { kind: "DAY_PLAN", day: "today", weekday: null };
    if (weekday) return { kind: "DAY_PLAN", day: "ask", weekday };
    return { kind: "DAY_PLAN", day: "ask", weekday: null };
  }

  if (/(мертв|неліквід|залежал|не\s+продаєть|висить\s+на\s+складі|застоял)/i.test(text)) {
    const brand = subjectAfter(text, /(по\s+бренду|бренд[уа]?)\s*/i);
    return { kind: "DEAD_STOCK", brand };
  }

  if (
    /(давно\s+не\s+бра|хто\s+мовчить|ризик\s+втрат|перестал?[иов]?\s+бра|хто\s+зник|відстає|згаса)/i.test(
      text
    )
  ) {
    return { kind: "CHURN" };
  }

  if (/(поверненн|повертают|повернул|повертає|повернень)/i.test(text)) {
    return { kind: "RETURNS", period: periodIn(text, { kind: "days", days: 90 }) };
  }

  /**
   * «Побудуй маршрут: Кунанець, Левкович, Склад».
   *
   * Перед усім, що ловить назви клієнтів: інакше «маршрут до Кунанця»
   * забрав би шаблон картки клієнта й показав борг замість дороги.
   */
  const routeTo = subjectAfter(
    text,
    /(побуду(й|вати)\s+маршрут|склади\s+маршрут|проклад[еи]\s+маршрут|маршрут\s+(до|через|по)|покажи\s+(на\s+карті|маршрут)|заїду\s+(до|в))\s*:?\s*/i
  );
  if (routeTo) {
    const names = routeTo
      .split(/[,;]|\s+(?:і|й|та|потім|далі)\s+/i)
      .map((n) => n.trim())
      .filter((n) => n.length >= 3)
      .slice(0, 12);
    if (names.length > 0) return { kind: "ROUTE_TO", names };
  }

  /**
   * Нагадування — перше, бо в тексті прохання лежить будь-що.
   *
   * «Нагадай у пʼятницю про борг Кунанця» містить і «борг», і назву
   * клієнта: будь-який пізніший шаблон забрав би це собі й показав
   * дебіторку замість того, щоб поставити нагадування.
   */
  if (/(^|\s)(нагадай|нагадати|нагадуй|не\s+дай\s+забути|постав(ити)?\s+нагадування)/i.test(text)) {
    return { kind: "REMIND", text };
  }
  if (/(мої\s+нагадуванн|які\s+(в\s+мене\s+)?нагадуванн|що\s+я\s+маю\s+зробити|що\s+на\s+мені|список\s+нагадувань)/i.test(text)) {
    return { kind: "REMINDERS" };
  }

  /**
   * «Хто поруч» — питання про МІСЦЕ, і воно перебиває решту.
   *
   * Стоїть перед боргами навмисно: «хто поруч із боргом» — це все ще
   * питання про радіус, а шаблон дебіторки забрав би його собі й видав
   * список по всій області.
   */
  if (
    /(хто|що|кого)\s+(тут\s+)?(є\s+)?(поруч|поблизу|неподалік|близько|найближч)|поруч\s+зі\s+мною|де\s+я\s+зараз|кого\s+(тут\s+)?заїхати/i.test(
      text
    )
  ) {
    const km = /(\d{1,3})\s*(км|кілометр)/i.exec(text);
    return { kind: "NEARBY", radiusKm: km ? Math.min(100, Math.max(1, Number(km[1]))) : null };
  }

  /**
   * Оплати — це НЕ дебіторка.
   *
   * «Хто заплатив» і «хто винен» — питання протилежні, а слово «гроші» в
   * них спільне. Тому оплати розпізнаються раніше: інакше шаблон боргів
   * відповідав би списком боржників на питання про надходження.
   */
  if (
    /(хто\s+(мені\s+)?(заплатив|платив|оплатив)|чи\s+заплатив|які\s+(були\s+)?оплати|оплати\s+за|скільки\s+я\s+зібрав|скільки\s+зібрав|надійшл[аи]\s+гроші|прийшли\s+гроші)/i.test(
      text
    )
  ) {
    const subject =
      subjectAfter(text, /(чи\s+заплатив|заплатив|платив|оплатив)\s+/i) ??
      subjectAfter(text, /(оплати\s+(від|по))\s*/i);
    return { kind: "PAYMENTS", period: periodIn(text, { kind: "days", days: 7 }), subject };
  }

  /**
   * «Чи витягну план» — питання про ТЕМП, а не про факт.
   *
   * Стоїть перед продажами навмисно: «як мій план» під шаблоном продажів
   * віддавало суму за місяць, тобто відповідало на «скільки», коли
   * питали «чи встигаю».
   */
  if (
    /(прогноз|чи\s+(виконаю|витягну|встигаю|закрию|дотягну|буде\s+бонус)|виконання\s+плану|як\s+(мій|там\s+мій)\s+план|іду\s+по\s+плану|мій\s+темп|скільки\s+(вийде|буде)\s+до\s+кінця|встигаю\s+по\s+плану|який\s+бонус)/i.test(
      text
    )
  ) {
    return { kind: "FORECAST" };
  }

  if (
    /(на\s+фоні|порівняно\s+з\s+командою|проти\s+команди|серед\s+торгових|моє\s+місце|яке\s+в\s+мене\s+місце|рейтинг|табло|хто\s+(перший|лідер)|хто\s+попереду|як\s+я\s+проти|де\s+я\s+провисаю|мої\s+сильні)/i.test(
      text
    )
  ) {
    return { kind: "BENCHMARK", period: periodIn(text) };
  }

  if (
    /(abc|авс|80\s*\/\s*20|двадцять\s+відсотків|найважливіш[а-яіїєґ]*\s+клієнт|топ\s+клієнт|хто\s+тримає\s+(мій\s+)?оборот|головні\s+клієнт|ключові\s+клієнт)/i.test(
      text
    )
  ) {
    return { kind: "ABC_CLIENTS", period: periodIn(text, { kind: "days", days: 180 }) };
  }

  if (/(борг|дебіторк|прострочен|прострочк|заборгован|хто\s+(мені\s+)?винен|нагадати\s+про\s+гроші)/i.test(text)) {
    return { kind: "DEBTS" };
  }

  if (
    /(скільки\s+я\s+(продав|наторгував|зробив)|мої\s+продажі|мій\s+оборот|скільки\s+наторгував)/i.test(
      text
    )
  ) {
    return { kind: "SALES", period: periodIn(text) };
  }

  if (/(маршрут|куди\s+я\s+(їжджу|їзжу)|де\s+я\s+буваю|звичн\w+\s+маршрут)/i.test(text)) {
    return { kind: "ROUTE", weekday: weekdayIn(text) };
  }

  const basket = subjectAfter(
    text,
    /(що\s+(беруть|брати|йде|іде|купують)\s+разом\s+(з|із|зі)?|що\s+(докласти|додати|допродати)\s+до|що\s+іде\s+в\s+парі\s+(з|із))\s*/i
  );
  if (basket) return { kind: "BASKET", query: basket };

  const substitute = subjectAfter(
    text,
    /(чим\s+замінити|яка\s+заміна\s+(для|на)?|аналог\s+(до|для)?|що\s+замість|чим\s+можна\s+замінити)\s*/i
  );
  if (substitute) return { kind: "SUBSTITUTE", query: substitute };

  const product = subjectAfter(text, PRODUCT_ASK) ?? subjectBetween(text, PRODUCT_MIDDLE);
  if (product) return { kind: "PRODUCT", query: product };

  return null;
}

/**
 * Питання водія — окремий, набагато вужчий список.
 *
 * Не тому, що водієві менше довіряють, а тому, що решта питань про нього
 * просто не має відповіді: продажів на водія не оформлюють, портфеля в
 * нього немає, і «скільки я продав» повернуло б нуль, який виглядає як
 * поламка. Усе, чого тут немає, іде до моделі — вона чесно скаже, що
 * таких даних у водія немає.
 */
function driverIntent(text: string): Intent | null {
  if (
    /(маршрут|мій\s+день|що\s+(в\s+мене\s+)?сьогодні|куди\s+(мені\s+)?їхати|скільки\s+точок|скільки\s+лишилось|скільки\s+(грошей\s+)?(мені\s+)?(зібрати|забрати)|скільки\s+привезти|каса|скільки\s+в\s+касі|лист\s+на\s+сьогодні)/i.test(
      text
    )
  ) {
    return {
      kind: "DRIVER_DAY",
      day: /завтра/i.test(text) ? "tomorrow" : /вчора/i.test(text) ? "yesterday" : "today",
    };
  }

  const card =
    subjectAfter(text, /(скільки\s+винен|який\s+борг\s+(у|в)|борг\s+(у|в))/i) ??
    subjectAfter(text, /(що\s+з\s+|розкажи\s+про\s+|картка\s+|адреса\s+|телефон\s+|як\s+доїхати\s+до\s+)/i);
  if (card) return { kind: "CLIENT_CARD", subject: card };

  const product = subjectAfter(text, PRODUCT_ASK) ?? subjectBetween(text, PRODUCT_MIDDLE);
  if (product) return { kind: "PRODUCT", query: product };

  return null;
}

/**
 * Питання складовщика — ще вужчий список, і навмисно.
 *
 * Кодом ловимо лише те, у чому неможливо помилитися: довідку, картку клієнта
 * й наявність товару. Головні складські питання — про водіїв, збірку й власні
 * накладні — свідомо йдуть до моделі: форм у них надто багато («де Пайда»,
 * «що везе», «чи вже виїхав», «що лишилось пакувати»), і хибне розпізнавання
 * коштує дорожче за один похід до моделі. Інструменти в неї вже є.
 *
 * Решта — зведення торгового — не ловиться взагалі: на складовщика продажів
 * не оформлюють, і код повернув би нуль, який виглядає як поламка.
 */
function warehouseIntent(text: string): Intent | null {
  if (
    /(що\s+ти\s+(вмієш|можеш|умієш)|чим\s+(ти\s+)?(можеш\s+)?допоможеш|які\s+в\s+тебе\s+можливості|довідка)/i.test(
      text
    )
  ) {
    return { kind: "HELP" };
  }

  const card =
    subjectAfter(text, /(скільки\s+винен|який\s+борг\s+(у|в)|борг\s+(у|в))/i) ??
    subjectAfter(text, /(що\s+з\s+|розкажи\s+про\s+|картка\s+|адреса\s+|телефон\s+)/i);
  if (card) return { kind: "CLIENT_CARD", subject: card };

  const product = subjectAfter(text, PRODUCT_ASK) ?? subjectBetween(text, PRODUCT_MIDDLE);
  if (product) return { kind: "PRODUCT", query: product };

  return null;
}
