import os

def esc(s):
    out, buf, codes = [], "", []
    def flush_buf():
        nonlocal buf
        if buf:
            out.append('"' + buf + '"'); buf = ""
    def flush_codes():
        nonlocal codes
        if codes:
            out.append("(-join [char[]]@(" + ",".join("0x%04x" % c for c in codes) + "))"); codes = []
    for ch in s:
        if ord(ch) < 128 and ch not in '"$`':
            flush_codes(); buf += ch
        else:
            flush_buf(); codes.append(ord(ch))
    flush_buf(); flush_codes()
    return "+".join(out) if out else '""'

