/**
 * Наскільки складне питання — щоб знати, скільки думати.
 *
 * Правилами, а не моделлю: окремий виклик «оціни складність» коштував би
 * секунди й гроші на КОЖНЕ питання, а помилка тут дешева — рівнем нижче
 * модель однаково відповість, лише менш зважено.
 *
 * Сходинки (таблиця власника 23.09.2026):
 *   none — показати одну річ: «покажи залишок Bosch», «де Пайда»;
 *   low  — порахувати за період: «скільки продали за місяць»;
 *   high — порівняти або пояснити: «порівняй продажі та маржу», «чому впав
 *          прибуток»;
 *   max  — зібрати аналіз: «побудуй складний аналіз закупівель».
 * Нічого не впізнали — low: безпечна середина.
 *
 * Межі слів — через (?<!\p{L}), бо \b у JavaScript не бачить кирилиці.
 */

import type { ThinkLevel } from "@/lib/assistant/config";
import type { ChatMessage } from "@/lib/assistant/types";

const W = "(?<!\\p{L})";
const re = (src: string) => new RegExp(src, "iu");

/** Зібрати аналіз, стратегію, прогноз — багато джерел і висновок. */
const MAX_RE = [
  re(`${W}(проаналізу|аналіз|розбери|розбір|аудит)\\p{L}*[^?]{0,50}${W}(закуп|асортимент|стратег|прогноз|сезон|ціноутвор|структур|рентабельн|портфел|цілої фірми|всієї фірми|усієї фірми)`),
  re(`${W}(побудуй|підготуй|зроби|склади)\\p{L}*[^?]{0,30}${W}(аналіз|стратег|прогноз|бюджет)`),
  re(`${W}(повн|детальн|глибок|комплексн|складн|ґрунтовн|всебічн)\\p{L}*\\s+(аналіз|звіт|розбір|огляд)`),
  re(`${W}(план закупів|що закупити|що замовити|що дозамовити)`),
];

/** Порівняти, пояснити причину, оцінити ризик. */
const HIGH_RE = re(
  `${W}(чому|причин|через що|з чим пов|поясни|порівня|проти|динамік|тренд|впал|впав|знизи|зниж|падін|просі|зріс|зрос|вплив|залежн|спрогноз|прогноз|що робити|як покращ|як збільш|порад|рекоменд|оціни|ризик|аномал|відхил|ефективн|відстроч|кому[^?]{0,30}не давати)`
);

/** Порахувати: суми, кількості, рейтинги за період. */
const LOW_RE = re(
  `${W}(скільки|сума|суму|оборот|виручк|продаж|продал|всього|разом|топ|рейтинг|найбільш|найкращ|найгірш|середн|відсот|частк|за (місяць|тиждень|квартал|рік|день|вчора|сьогодні|період)|дебітор|борг|маржа|маржу|прибут|перестал|не купу)`
);

/** Показати чи знайти одну річ. */
const NONE_RE = re(
  `^(покажи|знайди|де|хто|який|яка|яке|які|чи є|є |ціна|залишок|телефон|адрес|відкрий|дай|нагадай|привіт|дякую|так|ні|ок)(?!\\p{L})`
);

/** Прохання подумати глибше про попереднє — підняти рівень. */
const DEEPER_RE = re(`${W}(детальніш|глибш|подумай|перевір ще|ще раз|уважніш|розпиши|обґрунту)`);

/** Різні показники в одному питанні: три й більше — це вже аналіз. */
const METRICS = [
  re(`${W}(продаж|оборот|виручк|продал)`),
  re(`${W}(марж|прибут|націнк|собіварт)`),
  re(`${W}(борг|дебітор|оплат|кас)`),
  re(`${W}(залиш|склад|запас)`),
  re(`${W}(закуп|приход|постачал)`),
  re(`${W}(клієнт|покупц)`),
  re(`${W}(чек|замовлен|накладн)`),
  re(`${W}(доставк|воді|маршрут|пробіг)`),
  re(`${W}(ціна|ціни|цін)`),
];

/** Два періоди в одному питанні — порівняння, навіть без слова «порівняй». */
const PERIODS = re(
  `${W}(січ|лют|берез|квіт|трав|черв|лип|серп|верес|жовт|листопад|груд)\\p{L}*`
);

const RANK: Record<ThinkLevel, number> = { none: 0, low: 1, high: 2, max: 3 };
const higher = (a: ThinkLevel, b: ThinkLevel) => (RANK[a] >= RANK[b] ? a : b);

function levelOf(text: string): ThinkLevel | null {
  const t = text.trim();
  if (MAX_RE.some((r) => r.test(t))) return "max";

  const metrics = METRICS.filter((r) => r.test(t)).length;
  if (metrics >= 4) return "max";

  const months = new Set((t.match(new RegExp(PERIODS.source, "giu")) ?? []).map((m) => m.slice(0, 4).toLowerCase()));
  if (HIGH_RE.test(t) || metrics >= 3 || months.size >= 2) return "high";

  if (LOW_RE.test(t)) return "low";
  if (NONE_RE.test(t)) return "none";
  return null;
}

/**
 * Рівень для ходу.
 *
 * Коротке продовження («а у вересні?», «детальніше») саме по собі нічого не
 * каже — береться рівень попереднього питання, а «детальніше/подумай» ще й
 * піднімає його до high.
 */
export function levelFor(text: string, history: ChatMessage[] = []): ThinkLevel {
  const own = levelOf(text);
  const words = text.trim().split(/\s+/).length;
  const deeper = DEEPER_RE.test(text);

  if (words <= 6 || deeper) {
    const prevUser = [...history].reverse().find((m) => m.role === "user" && typeof m.content === "string");
    const prev = prevUser ? levelOf(prevUser.content as string) : null;
    let level = higher(own ?? "none", prev ?? (own ? "none" : "low"));
    if (deeper) level = higher(level, "high");
    return level;
  }
  return own ?? "low";
}
