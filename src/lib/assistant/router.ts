function weekdayIn(text: string): number | null {
  for (const [re, n] of WEEKDAYS) if (re.test(text)) return n;
  return null;
}

/**
 * Який період мали на увазі.
 *
 * «Місяць» — це КАЛЕНДАРНИЙ місяць, з першого числа (рішення власника
 * 06.09.2026). Доти будь-яке «за місяць» перетворювалося на ковзні 30
 * днів, і в одній відповіді верхня сума йшла за 7 серпня — 6 вересня, а
 * блок плану під нею — з 1 вересня. Пояснити цю різницю неможливо, а
 * помічатися вона починає рівно тоді, коли за нею ухвалюють рішення.
 */
export type PeriodSpec =
  | { kind: "days"; days: number }
  /** offset 0 — поточний місяць, -1 — попередній. */
  | { kind: "month"; offset: 0 | -1 }
  /** Руками названі межі: «з 01.08 по 15.08». */
  | { kind: "range"; from: string; to: string }
  /** Один день: 0 — сьогодні, −1 — вчора, −2 — позавчора. */
  | { kind: "day"; offset: number }
  /** Тиждень пн–нд за Києвом: 0 — поточний (до сьогодні), −1 — минулий. */
  | { kind: "week"; offset: 0 | -1 };

const MONTHS_GEN = [
  "січня", "лютого", "березня", "квітня", "травня", "червня",
  "липня", "серпня", "вересня", "жовтня", "листопада", "грудня",
];
const MONTH_GEN = `(${MONTHS_GEN.join("|")})`;

/**
 * Дата без року — цього року, а якщо вона ще не настала — минулого.
 *
 * «Оборот за 10 грудня», поставлене в січні, — про грудень, що минув, а не
 * про той, що буде; питати про майбутній оборот немає сенсу.
 */
function isoDay(d: string, month: number, y: string | undefined): string | null {
  const day = Number(d);
  if (month < 1 || month > 12 || day < 1 || day > 31) return null;
  const today = kyivDate(new Date());
  const year = y ? (y.length === 2 ? 2000 + Number(y) : Number(y)) : Number(today.slice(0, 4));
  const iso = `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  return !y && iso > today ? `${year - 1}${iso.slice(4)}` : iso;
}

/**
 * «за тиждень», «за місяць», «за 45 днів» — інакше типові 30.
 *
 * Межа слова тут виписана як (^|\s), а не \b. У JavaScript \b визначена
 * на ASCII-символах слова, тож перед кирилицею вона просто не спрацьовує:
 * /\bтижд/ не знаходить «за тиждень» узагалі, і період мовчки лишався
 * місячним на кожне питання про тиждень.
 */
function periodIn(
  text: string,
  fallback: PeriodSpec = { kind: "month", offset: 0 }
): PeriodSpec {
  /*
   * Один день і тиждень словами — перед усім іншим: «вчорашній оборот»
   * містить і «оборот», і «вчорашній», і без цієї гілки «вчора» мовчки
   * ставало поточним місяцем. Порядок важливий: «позавчора» містить «вчора».
   */
  if (/(^|\s)(позавчора|позавчорашн[а-яіїєґ]*)(\s|$)/i.test(text)) return { kind: "day", offset: -2 };
  if (/(^|\s)(вчора|учора|вчорашн[а-яіїєґ]*|учорашн[а-яіїєґ]*)(\s|$)/i.test(text)) return { kind: "day", offset: -1 };
  if (/(^|\s)(сьогодні|сьогоднішн[а-яіїєґ]*)(\s|$)/i.test(text)) return { kind: "day", offset: 0 };
  // «тиждень» і «тижня» — різні основи (тижд/тижн), тому [дн].
  if (/(^|\s)(цього|поточного|за\s+цей|на\s+цьому)\s+тиж[дн]/i.test(text)) return { kind: "week", offset: 0 };
  if (/(^|\s)(минулого|попереднього|за\s+минулий|за\s+попередній)\s+тиж[дн]/i.test(text)) {
    return { kind: "week", offset: -1 };
  }
  if (/(^|\s)тижд|(^|\s)тижн/i.test(text)) return { kind: "days", days: 7 };
  if (/(^|\s)квартал/i.test(text)) return { kind: "days", days: 90 };

  /**
   * Межі руками: «з 01.08 по 15.08».
   *
   * Рік можна не називати — беремо поточний; якщо початок виявився
   * пізнішим за кінець, це минулорічний хвіст (грудень → січень).
   */
  const range = /з\s+(\d{1,2})[.\/](\d{1,2})(?:[.\/](\d{2,4}))?\s+(?:по|до)\s+(\d{1,2})[.\/](\d{1,2})(?:[.\/](\d{2,4}))?/i.exec(
    text
  );
  if (range) {
    const iso = (d: string, m: string, y: string | undefined, fallbackYear: number) => {
      const year = y ? (y.length === 2 ? 2000 + Number(y) : Number(y)) : fallbackYear;
      return `${year}-${String(Number(m)).padStart(2, "0")}-${String(Number(d)).padStart(2, "0")}`;
    };
    const year = new Date().getFullYear();
    const from = iso(range[1], range[2], range[3], year);
    const to = iso(range[4], range[5], range[6], year);
    if (from <= to) return { kind: "range", from, to };
    return { kind: "range", from: `${Number(from.slice(0, 4)) - 1}${from.slice(4)}`, to };
  }

  const explicit = /за\s+(\d{1,3})\s*(дн|день|днів|дні)/i.exec(text);
  if (explicit) {
    return { kind: "days", days: Math.min(365, Math.max(1, Number(explicit[1]))) };
  }

  /* Конкретний день: «за 10.09», «за 10 вересня». */
  const single = /(^|\s)(за\s+|на\s+|по\s+)?(\d{1,2})[.\/](\d{1,2})(?:[.\/](\d{2,4}))?(\s|$)/.exec(text);
  if (single) {
    const day = isoDay(single[3], Number(single[4]), single[5]);
    if (day) return { kind: "range", from: day, to: day };
  }
  const named = new RegExp(`(^|\\s)(за\\s+)?(\\d{1,2})\\s+${MONTH_GEN}(\\s+(\\d{4}))?(\\s|$)`, "i").exec(text);
  if (named) {
    const day = isoDay(named[3], MONTHS_GEN.indexOf(named[4].toLowerCase()) + 1, named[6]);
    if (day) return { kind: "range", from: day, to: day };
  }

  if (/(минул|попередн)[а-яіїєґ]*\s+місяц/i.test(text)) return { kind: "month", offset: -1 };
  if (/(^|\s)(місяц|місяць)/i.test(text)) return { kind: "month", offset: 0 };

  return fallback;
}

/**
 * Прохання щось СКЛАСТИ, а не показати.
 *
 * «Склади лист клієнту про борг» містить слово «борг» і за шаблоном
 * потрапило б у зведення по дебіторці — тобто торговий попросив би текст,
 * а отримав таблицю. Такі питання — робота моделі за визначенням.
 */
const COMPOSE =
  /(склади|напиши|сформулюй|придумай|переклади|поясни|порівняй|чому|що\s+(мені\s+)?зробити|як\s+мені\s+(закрити|витягнути|підняти)|варто\s+ли|чи\s+(давати|варто|можна|треба))/i;

export function detectIntent(
  raw: string,
  opts: { hasHistory: boolean; hasClientHint?: boolean; kind?: AssistantKind }
): Intent | null {
  const text = clean(raw);
  if (!text) return null;

  // Продовження розмови — тільки модель: код не знає, про кого йшлося.
  if (opts.hasHistory && ANAPHORA.test(text)) return null;
  if (COMPOSE.test(text)) return null;

  if (opts.kind === "DRIVER") return driverIntent(text);
  if (opts.kind === "WAREHOUSE") return warehouseIntent(text);
  if (opts.kind === "ADMIN") return adminIntent(text, opts);

  return salesIntent(text, opts);
}

/**
 * Питання торгового — найдовший каскад, і він же основа для керівника.
 *
 * Керівник ставить половину тих самих питань («що з Химичем», «чим
 * замінити», «кого розпрацювати в Сокільниках»), тож adminIntent після
 * власних шаблонів звертається сюди — і пропускає лише те, що має сенс
 * без портфеля. Дублювати цей каскад було б гірше: він росте, і друга
 * копія почала б відставати з першого ж тижня.
 */
function salesIntent(
  text: string,
  opts: { hasHistory: boolean; hasClientHint?: boolean }
): Intent | null {
  /* Спершу шаблони з назвою клієнта: «скільки винен Химич» — це картка
     клієнта, а не зведення по всій дебіторці. */

  const entry = subjectAfter(
    text,
    /(з\s+чим\s+(за)?(ходити|йти|їхати|заїжджати|зайти|заїхати)|з\s+чим\s+іти)/i
  );
  if (/з\s+чим\s+/i.test(text)) return { kind: "ENTRY_OFFER", subject: entry };

  const recommend = subjectAfter(
    text,
    /(що\s+(йому\s+|мені\s+)?(за)?пропонувати|що\s+порадити|що\s+продати)/i
  );
  if (/(що\s+(йому\s+|мені\s+)?(за)?пропонувати|що\s+порадити)/i.test(text)) {
    return { kind: "RECOMMEND", subject: recommend };
  }

  if (/(що\s+ти\s+(вмієш|можеш|умієш)|чим\s+(ти\s+)?(можеш\s+)?допоможеш|які\s+в\s+тебе\s+можливості|довідка|підказк[аи]\s+по\s+тобі)/i.test(text)) {
    return { kind: "HELP" };
  }

  /**
   * «Покажи останню накладну Кунанця».
   *
   * Перед карткою клієнта: інакше шаблон «покажи …» забирає питання собі
   * й показує профіль там, де просили конкретний документ.
   */
  const lastOrder = subjectAfter(
    text,
    /((покажи|дай|глянь)\s+)?(останн[ьяєюій]{1,3}|остатн[ьяєюій]{1,3})\s+(накладн[а-яіїєґ]*|замовлен[а-яіїєґ]*|документ[а-яіїєґ]*|реалізаці[а-яіїєґ]*|відвантаженн[а-яіїєґ]*)\s*(у|в|по|для)?\s*/i
  );
  if (lastOrder) return { kind: "LAST_ORDER", subject: lastOrder };
  if (/(останн[ьяєюій]{1,3}|остатн[ьяєюій]{1,3})\s+(накладн|замовлен|документ|реалізаці)/i.test(text)) {
    return { kind: "LAST_ORDER", subject: null };
  }

  /**
   * «Чи брав Налисник піну», «коли Кунанець брав дріт».
   *
   * Питання про ПЕРЕТИН клієнта й товару: до дієслова — ім'я, після —
   * товар. Найдорожче з усього, що досі йшло в модель (до 24 тисяч
   * токенів за хід), і найпростіше для коду: дані вже є в картці з
   * фільтром товару.
   */
  /**
   * Два порядки слів, обидва живі.
   *
   * «Налисник брав піну» — ім'я до дієслова. «Чи брав Налисник піну» —
   * після нього, і тоді ім'я це ОДНЕ слово, а решта — товар: інакше
   * розділити їх у «брав Налисник піну монтажну» неможливо.
   */
  const pair =
    /^(?:чи\s+|коли\s+|скільки\s+(?:разів\s+)?)?(.{3,40}?)\s+(?:колись\s+)?(?:брав|бере|брала|купував|купувала|замовляв|замовляла)\s+(?:колись\s+)?(.{3,40})$/i.exec(
      text
    ) ??
    /^(?:чи\s+|а\s+)?(?:брав|бере|брала|купував|купувала|замовляв|замовляла)\s+([^\s]{3,30})\s+(.{3,40})$/i.exec(
      text
    );
  if (pair) {
    const client = clean(pair[1]).replace(/^(клієнт|фоп|магазин)\s+/i, "");
    const product = clean(pair[2]).replace(/\s+(востаннє|останній\s+раз|коли|і\s+скільки|\?)+$/i, "");
    if (client.length >= 3 && product.length >= 3 && !NOT_A_NAME.test(client) && !NOT_A_NAME.test(product)) {
      return { kind: "CLIENT_PRODUCT", subject: client, product };
    }
  }

  const card =
    subjectAfter(text, /(скільки\s+винен|який\s+борг\s+(у|в)|борг\s+(у|в))/i) ??
    subjectAfter(text, FIND_CLIENT) ??
    subjectAfter(text, /(що\s+з\s+|розкажи\s+про\s+|профіль\s+|картка\s+|що\s+ми\s+знаємо\s+про\s+|хто\s+такий\s+)/i);
  if (card) return { kind: "CLIENT_CARD", subject: card };

  /**
   * Питання без назви, коли помічник відкрито з картки клієнта.
   *
   * «Скільки винен» на екрані конкретного магазину означає саме його — і
   * без цієї гілки воно потрапляло б у зведення по всій дебіторці, тобто
   * відповідь була б про інше й виглядала б упевнено.
   */
  if (
    opts.hasClientHint &&
    /(скільки\s+винен|який\s+борг|що\s+ми\s+(про\s+нього\s+)?(знаємо|пам.ята)|пам.ять\s+про|що\s+з\s+ним|що\s+брав|що\s+замовляв|останнє\s+замовлення)/i.test(
      text
    )
  ) {
    return { kind: "CLIENT_CARD", subject: null };
  }

  /* Далі — питання без назви клієнта. */

  /**
   * План дня. День питаємо, коли його не назвали.
   *
   * «Сплануй мій день» о шостій вечора найчастіше означає «на завтра», а
   * о дев'ятій ранку — «на сьогодні». Вгадувати тут дорого: людина
   * поїде не туди й не тоді. Один дотик по кнопці дешевший за зіпсований
   * день, тому без явного дня показуємо вибір.
   */
  if (
    /(сплануй|які\s+клієнт[а-яіїєґ]*\s+(сьогодні|завтра)|кого\s+(сьогодні|завтра)|план\s+(на\s+)?(день|сьогодні|завтра|понеділок|вівторок|середу|четвер|п.?ятницю|суботу|неділю)|кого\s+(сьогодні|завтра|мені)?\s*(відвід|об.?їх)|куди\s+(мені\s+)?(сьогодні|завтра)\s+(їхати|їздити)|маршрут\s+на\s+(сьогодні|завтра|понеділок|вівторок|середу|четвер|п.?ятницю|суботу|неділю))/i.test(
      text
    )
  ) {
    const weekday = weekdayIn(text);
    if (/завтра/i.test(text)) return { kind: "DAY_PLAN", day: "tomorrow", weekday: null };
    if (/сьогодні/i.test(text)) return { kind: "DAY_PLAN", day: "today", weekday: null };
    if (weekday) return { kind: "DAY_PLAN", day: "ask", weekday };
    return { kind: "DAY_PLAN", day: "ask", weekday: null };
  }

  if (/(мертв|неліквід|залежал|не\s+продаєть|висить\s+на\s+складі|застоял)/i.test(text)) {
    const brand = subjectAfter(text, /(по\s+бренду|бренд[уа]?)\s*/i);
    return { kind: "DEAD_STOCK", brand };
  }

  if (
    /(давно\s+не\s+бра|хто\s+мовчить|ризик\s+втрат|перестал?[иов]?\s+бра|хто\s+зник|відстає|згаса)/i.test(
      text
    )
  ) {
    return { kind: "CHURN" };
  }

  if (/(поверненн|повертают|повернул|повертає|повернень)/i.test(text)) {
    return { kind: "RETURNS", period: periodIn(text, { kind: "days", days: 90 }) };
  }

  /**
   * «Побудуй маршрут: Кунанець, Левкович, Склад».
   *
   * Перед усім, що ловить назви клієнтів: інакше «маршрут до Кунанця»
   * забрав би шаблон картки клієнта й показав борг замість дороги.
   */
  const routeTo = subjectAfter(
    text,
    /(побуду(й|вати)\s+маршрут|склади\s+маршрут|проклад[еи]\s+маршрут|маршрут\s+(до|через|по)|покажи\s+(на\s+карті|маршрут)|заїду\s+(до|в))\s*:?\s*/i
  );
  if (routeTo) {
    // «Побудуй маршрут від мене: …» — «від мене» це старт, а не перша точка.
    const names = routeTo
      .replace(/^від\s+мене\s*:?\s*/i, "")
      .split(/[,;]|\s+(?:і|й|та|потім|далі)\s+/i)
      .map((n) => n.trim())
      .filter((n) => n.length >= 3)
      .slice(0, 12);
    if (names.length > 0) return { kind: "ROUTE_TO", names, start: "me" };
  }

  /**
   * Нагадування — перше, бо в тексті прохання лежить будь-що.
   *
   * «Нагадай у пʼятницю про борг Кунанця» містить і «борг», і назву
   * клієнта: будь-який пізніший шаблон забрав би це собі й показав
   * дебіторку замість того, щоб поставити нагадування.
   */
  if (/(^|\s)(нагадай|нагадати|нагадуй|не\s+дай\s+забути|постав(ити)?\s+нагадування)/i.test(text)) {
    return { kind: "REMIND", text };
  }
  if (/(мої\s+нагадуванн|які\s+(в\s+мене\s+)?нагадуванн|що\s+я\s+маю\s+зробити|що\s+на\s+мені|список\s+нагадувань)/i.test(text)) {
    return { kind: "REMINDERS" };
  }

  /**
   * «Кого розпрацювати в Сокільниках» — питання про МІСТО.
   *
   * Стоїть перед пошуком клієнта за назвою: інакше «клієнти в Сокільниках»
   * шукало б контрагента на ім'я «Сокільники» і не знаходило нічого.
   * Назва міста — це ПЕРШЕ слово хвоста: далі йде вже друга половина
   * питання («кого можна розпрацювати і до кого завітати»).
   */
  const cityTail = subjectAfter(
    text,
    /((знайди|покажи|дай)\s+(мені\s+)?)?(клієнт[а-яіїєґ]*|магазин[а-яіїєґ]*|точ[а-яіїєґ]*|кого|хто)\s+(можна\s+)?(розпрацювати|відвідати|завітати|заїхати|є|там)?\s*(у|в|по|на)\s+(місті|селі|смт|м\.|с\.)?\s*/i
  );
  if (cityTail) {
    const city = (cityTail.match(/^[А-ЯІЇЄҐа-яіїєґA-Za-z'ʼ-]{3,}/) ?? [])[0];
    if (city && !NOT_A_NAME.test(city)) return { kind: "CITY_CLIENTS", city };
  }

  /**
   * «Хто поруч» — питання про МІСЦЕ, і воно перебиває решту.
   *
   * Стоїть перед боргами навмисно: «хто поруч із боргом» — це все ще
   * питання про радіус, а шаблон дебіторки забрав би його собі й видав
   * список по всій області.
   */
  if (
    /(хто|що|кого)\s+(тут\s+)?(є\s+)?(поруч|поблизу|неподалік|близько|найближч)|поруч\s+зі\s+мною|де\s+я\s+зараз|кого\s+(тут\s+)?заїхати/i.test(
      text
    )
  ) {
    const km = /(\d{1,3})\s*(км|кілометр)/i.exec(text);
    return { kind: "NEARBY", radiusKm: km ? Math.min(100, Math.max(1, Number(km[1]))) : null };
  }

  /**
   * Оплати — це НЕ дебіторка.
   *
   * «Хто заплатив» і «хто винен» — питання протилежні, а слово «гроші» в
   * них спільне. Тому оплати розпізнаються раніше: інакше шаблон боргів
   * відповідав би списком боржників на питання про надходження.
   */
  if (
    /(хто\s+(мені\s+)?(заплатив|платив|оплатив)|чи\s+заплатив|які\s+(були\s+)?оплати|оплати\s+за|скільки\s+я\s+зібрав|скільки\s+зібрав|надійшл[аи]\s+гроші|прийшли\s+гроші)/i.test(
      text
    )
  ) {
    const subject =
      subjectAfter(text, /(чи\s+заплатив|заплатив|платив|оплатив)\s+/i) ??
      subjectAfter(text, /(оплати\s+(від|по))\s*/i);
    return { kind: "PAYMENTS", period: periodIn(text, { kind: "days", days: 7 }), subject };
  }

  /**
   * «Чи витягну план» — питання про ТЕМП, а не про факт.
   *
   * Стоїть перед продажами навмисно: «як мій план» під шаблоном продажів
   * віддавало суму за місяць, тобто відповідало на «скільки», коли
   * питали «чи встигаю».
   */
  if (
    /(прогноз|чи\s+(виконаю|витягну|встигаю|закрию|дотягну|буде\s+бонус)|виконання\s+плану|як\s+(мій|там\s+мій)\s+план|іду\s+по\s+плану|мій\s+темп|скільки\s+(вийде|буде)\s+до\s+кінця|встигаю\s+по\s+плану|який\s+бонус)/i.test(
      text
    )
  ) {
    return { kind: "FORECAST" };
  }

  if (
    /(на\s+фоні|порівняно\s+з\s+командою|проти\s+команди|серед\s+торгових|моє\s+місце|яке\s+в\s+мене\s+місце|рейтинг|табло|хто\s+(перший|лідер)|хто\s+попереду|як\s+я\s+проти|де\s+я\s+провисаю|мої\s+сильні)/i.test(
      text
    )
  ) {
    return { kind: "BENCHMARK", period: periodIn(text) };
  }

  if (
    /(abc|авс|80\s*\/\s*20|двадцять\s+відсотків|найважливіш[а-яіїєґ]*\s+клієнт|топ\s+клієнт|хто\s+тримає\s+(мій\s+)?оборот|головні\s+клієнт|ключові\s+клієнт)/i.test(
      text
    )
  ) {
    return { kind: "ABC_CLIENTS", period: periodIn(text, { kind: "days", days: 180 }) };
  }

  if (/(борг|дебіторк|прострочен|прострочк|заборгован|хто\s+(мені\s+)?винен|нагадати\s+про\s+гроші)/i.test(text)) {
    return { kind: "DEBTS" };
  }

  if (
    /(скільки\s+я\s+(продав|наторгував|зробив)|мої\s+продажі|мій\s+оборот|скільки\s+наторгував)/i.test(
      text
    )
  ) {
    return { kind: "SALES", period: periodIn(text) };
  }

  if (/(маршрут|куди\s+я\s+(їжджу|їзжу)|де\s+я\s+буваю|звичн\w+\s+маршрут)/i.test(text)) {
    return { kind: "ROUTE", weekday: weekdayIn(text) };
  }

  const basket = subjectAfter(
    text,
    /(що\s+(беруть|брати|йде|іде|купують)\s+разом\s+(з|із|зі)?|що\s+(докласти|додати|допродати)\s+до|що\s+іде\s+в\s+парі\s+(з|із))\s*/i
  );
  if (basket) return { kind: "BASKET", query: basket };

  const substitute = subjectAfter(
    text,
    /(чим\s+замінити|яка\s+заміна\s+(для|на)?|аналог\s+(до|для)?|що\s+замість|чим\s+можна\s+замінити)\s*/i
  );
  if (substitute) return { kind: "SUBSTITUTE", query: substitute };

  const product = productSubject(text);
  if (product) return { kind: "PRODUCT", query: product };

  return null;
}

/**
 * Питання водія — окремий, набагато вужчий список.
 *
 * Не тому, що водієві менше довіряють, а тому, що решта питань про нього
 * просто не має відповіді: продажів на водія не оформлюють, портфеля в
 * нього немає, і «скільки я продав» повернуло б нуль, який виглядає як
 * поламка. Усе, чого тут немає, іде до моделі — вона чесно скаже, що
 * таких даних у водія немає.
 */
function driverIntent(text: string): Intent | null {
  if (
    /(маршрут|мій\s+день|що\s+(в\s+мене\s+)?сьогодні|куди\s+(мені\s+)?їхати|скільки\s+точок|скільки\s+лишилось|скільки\s+(грошей\s+)?(мені\s+)?(зібрати|забрати)|скільки\s+привезти|каса|скільки\s+в\s+касі|лист\s+на\s+сьогодні)/i.test(
      text
    )
  ) {
    return {
      kind: "DRIVER_DAY",
      day: /завтра/i.test(text) ? "tomorrow" : /вчора/i.test(text) ? "yesterday" : "today",
    };
  }

  const card =
    subjectAfter(text, /(скільки\s+винен|який\s+борг\s+(у|в)|борг\s+(у|в))/i) ??
    subjectAfter(text, FIND_CLIENT) ??
    subjectAfter(text, /(що\s+з\s+|розкажи\s+про\s+|картка\s+|адреса\s+|телефон\s+|як\s+доїхати\s+до\s+)/i);
  if (card) return { kind: "CLIENT_CARD", subject: card };

  const product = productSubject(text);
  if (product) return { kind: "PRODUCT", query: product };

  return null;
}

/**
 * Питання складовщика — ще вужчий список, і навмисно.
 *
 * Кодом ловимо лише те, у чому неможливо помилитися: довідку, картку клієнта
 * й наявність товару. Головні складські питання — про водіїв, збірку й власні
 * накладні — свідомо йдуть до моделі: форм у них надто багато («де Пайда»,
 * «що везе», «чи вже виїхав», «що лишилось пакувати»), і хибне розпізнавання
 * коштує дорожче за один похід до моделі. Інструменти в неї вже є.
 *
 * Решта — зведення торгового — не ловиться взагалі: на складовщика продажів
 * не оформлюють, і код повернув би нуль, який виглядає як поламка.
 */
function warehouseIntent(text: string): Intent | null {
  if (
    /(що\s+ти\s+(вмієш|можеш|умієш)|чим\s+(ти\s+)?(можеш\s+)?допоможеш|які\s+в\s+тебе\s+можливості|довідка)/i.test(
      text
    )
  ) {
    return { kind: "HELP" };
  }

  const card =
    subjectAfter(text, /(скільки\s+винен|який\s+борг\s+(у|в)|борг\s+(у|в))/i) ??
    subjectAfter(text, FIND_CLIENT) ??
    subjectAfter(text, /(що\s+з\s+|розкажи\s+про\s+|картка\s+|адреса\s+|телефон\s+)/i);
  if (card) return { kind: "CLIENT_CARD", subject: card };

  const product = productSubject(text);
  if (product) return { kind: "PRODUCT", query: product };

  return null;
}

/**
 * Питання керівника.
 *
 * Спершу власні шаблони — вони про фірму, і саме тому мусять іти ПЕРЕД
 * торговими: «дебіторка» без імені для керівника означає всю базу, а не
 * його порожній портфель. Далі — каскад торгового, з якого пропускаємо
 * лише те, що має сенс без портфеля.
 *
 * Головна пастка тут — імена. «Борг у Кавецького» і «борг у Кунанця»
 * виглядають однаково, а означають різне: перший торговий, другий клієнт.
 * Розпізнавач цього не знає (він не ходить у базу) і не намагається
 * вгадати: він віддає ім'я у відповідь, а та вже питає довідник і, не
 * знайшовши співробітника, показує картку клієнта.
 */
function adminIntent(
  text: string,
  opts: { hasHistory: boolean; hasClientHint?: boolean }
): Intent | null {
  if (
    /(що\s+ти\s+(вмієш|можеш|умієш)|чим\s+(ти\s+)?(можеш\s+)?допоможеш|які\s+в\s+тебе\s+можливості|довідка)/i.test(
      text
    )
  ) {
    return { kind: "HELP" };
  }

  /* ── Що нового ────────────────────────────────────────────────────── */

  if (
    /(^|\s)(що\s+(нового|змінилось|змінилося|сталось|сталося)|як\s+(минув|пройшов)\s+(день|вчорашній)|підсумки\s+дня|зведенн[а-яіїєґ]*|дайджест|на\s+що\s+звернути\s+увагу)/i.test(
      text
    )
  ) {
    return { kind: "DIGEST" };
  }

  /* ── Накладні ─────────────────────────────────────────────────────── */

  /*
   * Перед усім іншим: «вчорашній оборот Кулика з накладними» містить і
   * «оборот», і період, і слово-документ, а означає саме перелік
   * накладних. «Останню накладну Кунанця» лишається карткою останнього
   * документа клієнта — вона нижче, у каскаді торгового.
   */
  if (!LAST_DOC.test(text)) {
    const num = DOC_NUMBER.exec(text);
    if (num) {
      return {
        kind: "DOCUMENTS",
        period: periodIn(text),
        number: num[4],
        who: null,
        asDriver: false,
        docType: /поверн/i.test(num[2]) ? "returns" : /замовл/i.test(num[2]) ? "orders" : "all",
        withLines: true,
      };
    }

    const haul = nameAfter(text, DRIVER_HAUL);
    if (haul) {
      return {
        kind: "DOCUMENTS",
        period: periodIn(text, { kind: "day", offset: 0 }),
        number: null,
        who: stripPeriodTail(haul) ?? haul,
        asDriver: true,
        docType: "all",
        withLines: false,
      };
    }

    const returnsOf = /(^|\s)поверненн/i.test(text) ? nameAfter(text, /(^|\s)поверненн[а-яіїєґ]*/) : null;
    if (DOC_WORD.test(text) || DOC_LIST.test(text) || DOC_ROWS.test(text) || SHIPPED_WHAT.test(text) || returnsOf) {
      const who =
        returnsOf ??
        nameAfter(
          text,
          /(^|\s)(накладн[аіуо][а-яіїєґ]*|документ[а-яіїєґ]*|реалізаці[а-яіїєґ]*|відвантаженн[а-яіїєґ]*)(\s+(по|у|в|від|для))?/
        ) ??
        nameAfter(text, /(^|\s)(виписав|виписала|оформив|оформила|провів|провела|зробив|зробила|відвантажив|відвантажила)/) ??
        nameAfter(text, /(^|\s)(оборот|продажі|виручка)/) ??
        subjectAfter(text, /(накладн[аіуо][а-яіїєґ]*|документ[а-яіїєґ]*|реалізаці[а-яіїєґ]*)\s+(по\s+|у\s+|в\s+|від\s+|для\s+)/i);
      return {
        kind: "DOCUMENTS",
        period: periodIn(text, { kind: "days", days: 7 }),
        number: null,
        who: stripPeriodTail(who),
        asDriver: false,
        docType: returnsOf ? "returns" : /(^|\s)замовленн/i.test(text) ? "orders" : "sales",
        withLines: DOC_ROWS.test(text),
      };
    }
  }

  /* ── Профіль співробітника ────────────────────────────────────────── */

  /*
   * «Розкажи про Кулика», «що з Куликом», «проаналізуй Пайду» — спершу
   * співробітник, потім клієнт: відповідь сама піде в картку клієнта, коли
   * в штаті такого імені немає («що з Кунанцем»).
   */
  const profileWho = nameAfter(
    text,
    /(^|\s)(розкажи\s+(мені\s+)?про|проаналізуй|проаналізувати|розбери|як\s+працює|як\s+справи\s+(у|в)|що\s+з|що\s+по|профіль|картка|оціни|як\s+там|що\s+там\s+(з|у|в|по))/
  );
  if (profileWho) {
    return { kind: "STAFF_PROFILE", who: stripPeriodTail(profileWho) ?? profileWho, period: periodIn(text) };
  }

  /* ── Хто де зараз ─────────────────────────────────────────────────── */

  if (
    /(^|\s)(хто\s+(зараз\s+)?(на\s+маршруті|в\s+дорозі|у\s+дорозі|на\s+зміні|онлайн|мовчить|працює)|хто\s+(не\s+)?(відкрив|закрив)\s+зміну|де\s+(зараз\s+)?(всі|усі|команда|люди|торгові))/i.test(
      text
    )
  ) {
    return {
      kind: "STAFF_NOW",
      who: null,
      role: /(^|\s)торгов/i.test(text) ? "SALES" : null,
    };
  }

  /* ── Водії на день ────────────────────────────────────────────────── */

  if (
    /(^|\s)(де\s+(зараз\s+)?водії|водії\s+(сьогодні|зараз|завтра|вчора)|що\s+(з\s+)?водіями|що\s+везуть|доставк[а-яіїєґ]*\s+(на\s+)?(сьогодні|завтра|вчора)|скільки\s+точок\s+(у\s+)?водіїв|хто\s+що\s+везе)/i.test(
      text
    )
  ) {
    return { kind: "DRIVERS_DAY", day: dayWord(text) };
  }

  /*
   * «Де Пайда» — ім'я з великої літери, і це не слово «водії».
   *
   * Прапорця /i тут бути не може: велика літера — це і є ознака імені.
   * Тому саме слово «де» виписане в обох регістрах — питання однаково
   * часто починають і з великої, і з малої.
   */
  const wherePerson = /(^|\s)[Дд]е\s+(зараз\s+)?([А-ЯІЇЄҐ][а-яіїєґ'ʼ-]{2,})(\s|$)/.exec(text);
  if (wherePerson) return { kind: "STAFF_NOW", who: wherePerson[3], role: null };

  /* ── Зарплата водіїв ──────────────────────────────────────────────── */

  if (
    /(^|\s)(зарплат[а-яіїєґ]*|нарахуванн[а-яіїєґ]*|скільки\s+заробив|ефективність\s+водіїв|вартість\s+точки|грн\s+на\s+точку|км\s+на\s+точку|маршрутн[а-яіїєґ]*\s+лист)/i.test(
      text
    )
  ) {
    const who = subjectAfter(text, /(зарплат[а-яіїєґ]*|скільки\s+заробив)\s+(у\s+|в\s+|по\s+)?/i);
    if (/(^|\s)воді/i.test(text) || who) {
      return { kind: "DRIVER_PAYROLL", period: periodIn(text), who: driverName(stripPeriodTail(who)) };
    }
  }

  /* ── Зміни, пробіг, пальне ────────────────────────────────────────── */

  if (
    /(^|\s)(змін[аиуи]?\s|змін\s|пробіг|кілометраж|пальне|паливо|одометр|автозакрит[а-яіїєґ]*|не\s+закрив\s+зміну)/i.test(
      text
    )
  ) {
    const who = subjectAfter(text, /(зміни|пробіг|кілометраж|пальне|паливо)\s+(у\s+|в\s+|по\s+)/i);
    return { kind: "SHIFTS", period: periodIn(text, { kind: "days", days: 7 }), who: stripPeriodTail(who) };
  }

  /* ── Замовлення з сайту ───────────────────────────────────────────── */

  if (
    /(^|\s)(замовленн[а-яіїєґ]*\s+(з|із|на)\s+сайт|сайт[а-яіїєґ]*\s+замовлен|інтернет[-\s]замовлен|нові\s+замовленн[а-яіїєґ]*|необроблен[а-яіїєґ]*|скільки\s+замовлень|чернетк[а-яіїєґ]*)/i.test(
      text
    )
  ) {
    return { kind: "SITE_REPORT", mode: "orders", period: periodIn(text, { kind: "days", days: 7 }) };
  }

  /* ── Відвідуваність сайту ─────────────────────────────────────────── */

  if (
    /(^|\s)(відвідувач[а-яіїєґ]*|скільки\s+люд[а-яіїєґ]*\s+(на|заходил)|трафік|конверсі[а-яіїєґ]*|що\s+шукають|пошук\s+на\s+сайті|звідки\s+приходять|що\s+на\s+сайті|сайт\s+за)/i.test(
      text
    )
  ) {
    return { kind: "SITE_REPORT", mode: "traffic", period: periodIn(text, { kind: "days", days: 30 }) };
  }

  /* ── Склад ────────────────────────────────────────────────────────── */

  if (
    /(^|\s)(закінчу[а-яіїєґ]*|дефіцит|що\s+(треба\s+)?(замовити|докупити|закупити)|нуль\s+на\s+складі|низьк[а-яіїєґ]*\s+залишк|оборотн[а-яіїєґ]*|мертв[а-яіїєґ]*\s+(залишк|запас|товар)|що\s+лежить\s+на\s+складі|запас\s+складу)/i.test(
      text
    )
  ) {
    const brand = subjectAfter(text, /(по\s+бренду|бренд[уа]?)\s*/i);
    const mode = /(^|\s)оборотн/i.test(text)
      ? ("turnover" as const)
      : /(^|\s)мертв/i.test(text)
        ? ("dead" as const)
        : ("low" as const);
    return { kind: "LOW_STOCK", brand, mode };
  }

  /* ── Закупівлі й прихід ───────────────────────────────────────────── */

  if (
    /(^|\s)(закупівл[а-яіїєґ]*|постача[а-яіїєґ]*|прихід|приходу|завезл[аи]|скільки\s+завезли|що\s+завезли)/i.test(
      text
    )
  ) {
    return { kind: "MONEY_FLOWS", period: periodIn(text), mode: "purchases" };
  }

  /* ── Рух коштів ───────────────────────────────────────────────────── */

  if (
    /(^|\s)(рух\s+кошт[а-яіїєґ]*|аванс[а-яіїєґ]*|переплат[а-яіїєґ]*|скільки\s+відвантажил[аи]|відвантажено\s+за|каса\s+фірми|грошов[а-яіїєґ]*\s+поток|бухгалтер[а-яіїєґ]*\s+звіт)/i.test(
      text
    )
  ) {
    return { kind: "MONEY_FLOWS", period: periodIn(text), mode: "flows" };
  }

  /* ── Глибші розрізи продажів ──────────────────────────────────────── */

  if (/(^|\s)(знижк[а-яіїєґ]*|нижче\s+(медіан|ціни)|хто\s+(дає|давав)\s+знижк)/i.test(text)) {
    return { kind: "SALES_ANALYSIS", period: periodIn(text), mode: "discounts" };
  }

  if (
    /(^|\s)(по\s+містах|у\s+яких\s+містах|де\s+ми\s+продаємо|географі[а-яіїєґ]*|оборот\s+по\s+містах|міста\s+продаж)/i.test(
      text
    )
  ) {
    return { kind: "SALES_ANALYSIS", period: periodIn(text), mode: "geo" };
  }

  if (
    /(^|\s)(когорт[а-яіїєґ]*|утриманн[а-яіїєґ]*|хто\s+відвалив|кого\s+(треба\s+)?повертати|скільки\s+клієнтів\s+втратил|відтік|нові\s+клієнти\s+по\s+місяц)/i.test(
      text
    )
  ) {
    return { kind: "SALES_ANALYSIS", period: periodIn(text), mode: "cohorts" };
  }

  /* ── Склад: хто збирає накладні ───────────────────────────────────── */

  /*
   * Перед грошима навмисно: «скільки зібрав Юра» — про накладні на складі,
   * а «скільки зібрали за тиждень» — про гроші. Розводить їх ім'я з
   * великої літери; відповідь ще й перевірить роль — торговий з таким
   * іменем поверне гроші.
   */
  if (
    /(^|\s)(складовщик[а-яіїєґ]*|складівник[а-яіїєґ]*|збірк[аиу]\s+(за|по|на|сьогодні|вчора)|хто\s+(на\s+складі\s+)?(збирає|збирав|зібрав|пакує|пакував|найшвидш|найповільн)|на\s+складі\s+(хто|скільки|найшвидш|найповільн)|хто\s+скільки\s+зібрав\s+на\s+складі)/i.test(
      text
    ) &&
    !DOC_NUMBER.test(text)
  ) {
    return { kind: "WAREHOUSE_ACTIVITY", period: periodIn(text, { kind: "days", days: 7 }), who: null };
  }
  const packedBy = nameAfter(text, /(^|\s)(скільки|що|які\s+накладні)\s+(зібрав|зібрала|запакував|запакувала|спакував|спакувала)/);
  if (packedBy) {
    return { kind: "WAREHOUSE_ACTIVITY", period: periodIn(text, { kind: "days", days: 7 }), who: stripPeriodTail(packedBy) };
  }

  /* ── Гроші, зібрані за період ─────────────────────────────────────── */

  if (
    /(^|\s)(скільки\s+зібрал[аи]|зібрано\s+грошей|надходженн[а-яіїєґ]*|хто\s+скільки\s+зібрав|оплати\s+(по|за)\s+(торгов|команд|фірм))/i.test(
      text
    )
  ) {
    return { kind: "TEAM_COLLECTED", period: periodIn(text, { kind: "days", days: 7 }) };
  }

  /* ── Дебіторка ────────────────────────────────────────────────────── */

  const teamWord = /(торгов[а-яіїєґ]*|команд[а-яіїєґ]*|фірм[а-яіїєґ]*|компані[а-яіїєґ]*|базі|всіх|усіх|кожн[а-яіїєґ]*)/i;

  if (
    /(^|\s)(хто\s+(найбільше\s+)?винен\s+(фірмі|нам)|найбільші\s+боржники|кому\s+не\s+(можна\s+)?відвантаж)/i.test(
      text
    )
  ) {
    return { kind: "TEAM_DEBTS", who: null };
  }
  if (/(^|\s)(дебіторк|борг|прострочк|прострочен|заборгован)/i.test(text)) {
    const after = subjectAfter(text, /(дебіторк[а-яіїєґ]*|борг[а-яіїєґ]*|прострочк[а-яіїєґ]*)\s+(по\s+|у\s+|в\s+)/i);
    if (after && teamWord.test(after)) return { kind: "TEAM_DEBTS", who: null };
    if (after) return { kind: "TEAM_DEBTS", who: stripPeriodTail(after) };
    if (teamWord.test(text)) return { kind: "TEAM_DEBTS", who: null };
  }

  /* ── Повернення ───────────────────────────────────────────────────── */

  if (/(^|\s)(поверненн|повертають|поверта[єю]ть)/i.test(text)) {
    return { kind: "TEAM_RETURNS", period: periodIn(text, { kind: "days", days: 90 }) };
  }

  /* ── План і прогноз ───────────────────────────────────────────────── */

  if (
    /(^|\s)(план\s+(фірми|команди|по\s+торгов)|хто\s+(не\s+)?(витягне|виконає|дотягне)\s+план|виконання\s+плану|прогноз\s+(по\s+)?(фірм|команд|торгов))/i.test(
      text
    )
  ) {
    return { kind: "TEAM_FORECAST" };
  }

  /* ── Продажі ──────────────────────────────────────────────────────── */

  const soldBy = subjectAfter(
    text,
    /(скільки\s+(продав|продала|наторгував|наторгувала)|оборот\s+(у|в|по)|продажі\s+(у|в|по))\s*/i
  );
  if (soldBy && !teamWord.test(soldBy)) {
    return { kind: "TEAM_SALES", period: periodIn(text), who: stripPeriodTail(soldBy) };
  }
  /* «Оборот Кулика», «продажі Скуратова за тиждень» — родовий відмінок без прийменника. */
  const soldGenitive = nameAfter(text, /(^|\s)(оборот|продажі|продаж|виручка|реалізації)/);
  if (soldGenitive && !teamWord.test(soldGenitive)) {
    return { kind: "TEAM_SALES", period: periodIn(text), who: stripPeriodTail(soldGenitive) };
  }
  /*
   * Оборот фірми без слова «фірма»: «оборот за вчора», «продажі цього
   * тижня», просто «оборот». Період або дуже коротке питання — ознака, що
   * питають про всю компанію, а не про товар зі словом «продаж» у назві.
   */
  if (
    /(^|\s)(продаж[а-яіїєґ]*|оборот[а-яіїєґ]*|виручк[а-яіїєґ]*|реалізаці[а-яіїєґ]*)/i.test(text) &&
    (teamWord.test(text) || soldBy != null || PERIOD_WORD.test(text) || text.split(/\s+/).length <= 2)
  ) {
    return { kind: "TEAM_SALES", period: periodIn(text), who: null };
  }
  if (/(^|\s)(хто\s+(скільки\s+)?(продав|наторгував)|як\s+(іде|йде|справи\s+у)\s+(фірм|команд|торгов)|як\s+(фірма|команда)(\s|$))/i.test(text)) {
    return { kind: "TEAM_SALES", period: periodIn(text), who: null };
  }

  /* ── Обмін із 1С ──────────────────────────────────────────────────── */

  if (
    /(^|\s)(обмін|синхронізаці[а-яіїєґ]*|1с|1c|агент\s|розбіжност[а-яіїєґ]*|чи\s+оновил[аи]сь|коли\s+(останн[а-яіїєґ]*\s+)?(обмін|синхрон|оновленн))/i.test(
      text
    )
  ) {
    return { kind: "SYNC_HEALTH" };
  }

  /* ── ABC по товарах і брендах ─────────────────────────────────────── */

  /*
   * Каскад торгового ловить кожне «abc» як ABC по клієнтах. Товари й
   * бренди — інший вимір того самого звіту, тож розводимо за словом поруч;
   * «ABC по клієнтах» і «хто тримає оборот» ідуть далі, як і раніше.
   */
  if (
    /(^|\s)(abc|авс|abc\/xyz|xyz)(\s|$)/i.test(text) &&
    /(товар|позиці|бренд|асортимент|продукт|склад|sku)/i.test(text)
  ) {
    return {
      kind: "ABC_ITEMS",
      dimension: /бренд/i.test(text) ? "brand" : "product",
      basis: /(прибут|марж)/i.test(text) ? "profit" : "amount",
      period: periodIn(text, { kind: "days", days: 180 }),
    };
  }

  /* ── Решта — каскад торгового, але не все з нього ─────────────────── */

  const base = salesIntent(text, opts);
  if (!base) return null;

  switch (base.kind) {
    /* Питання про базу, а не про портфель: працюють без змін. */
    case "CLIENT_CARD":
    case "LAST_ORDER":
    case "CLIENT_PRODUCT":
    case "PRODUCT":
    case "BASKET":
    case "SUBSTITUTE":
    case "CITY_CLIENTS":
    case "DEAD_STOCK":
    case "ABC_CLIENTS":
    case "HELP":
    case "REMIND":
    case "REMINDERS":
    case "ENTRY_OFFER":
    case "RECOMMEND":
      return base;

    /* Оплати без імені клієнта — це «скільки зібрала фірма». */
    case "PAYMENTS":
      return base.subject ? base : { kind: "TEAM_COLLECTED", period: base.period };

    /*
     * Маршрут за названими точками керівник будує від складу: власного
     * треку в нього немає. «Від мене» — з офісного ноутбука теж нічого не
     * дасть, але людина попросила явно, тож беремо її останню точку.
     */
    case "ROUTE_TO":
      return { ...base, start: /(^|\s)від\s+мене(\s|:|$)/i.test(text) ? "me" : "depot" };

    /* Зведення портфеля перетворюються на зведення фірми. */
    case "SALES":
      return { kind: "TEAM_SALES", period: base.period, who: null };
    /*
     * «Як я на фоні команди» в керівника не має «я»: табло торгового
     * наскрізь побудоване навколо власного рядка й особистого прогнозу.
     * Те саме питання про фірму — це просто продажі по команді.
     */
    case "BENCHMARK":
      return { kind: "TEAM_SALES", period: base.period, who: null };
    case "DEBTS":
      return { kind: "TEAM_DEBTS", who: null };
    case "RETURNS":
      return { kind: "TEAM_RETURNS", period: base.period };
    case "FORECAST":
      return { kind: "TEAM_FORECAST" };

    /*
     * Особисте — до моделі. У керівника немає ні маршруту, ні позиції на
     * карті, ні клієнтів, які «давно не брали»: усе це існує лише в межах
     * конкретного торгового. Модель пояснить це чесніше за нулі.
     */
    default:
      return null;
  }
}


/**
 * Хвіст періоду, що прилип до імені.
 *
 * «Скільки продав Кулик за тиждень» — subjectAfter віддає весь хвіст, і в
 * довідник людей летить «Кулик за тиждень». Період із цієї ж фрази вже
 * розібрано окремо, тож тут його лишається просто відрізати.
 */
function stripPeriodTail(name: string | null): string | null {
  if (!name) return null;
  const once = (value: string) =>
    value
      .replace(/^(вчорашн|учорашн|сьогоднішн|позавчорашн)[а-яіїєґ]*\s+/i, "")
      .replace(
        /\s+(з\s+накладними|по\s+накладних|з\s+документами|з\s+рядками|з\s+позиціями|з\s+деталями|детально|докладно)$/i,
        ""
      )
      .replace(
        /\s+за\s+(сьогодні|вчора|учора|позавчора|тиждень|тижн[а-яіїєґ]*|місяц[ья]?|місяць|квартал|рік|\d{1,3}\s*дн[а-яіїєґ]*)$/i,
        ""
      )
      .replace(/\s+(вчора|учора|сьогодні|позавчора)$/i, "")
      .replace(/\s+(за\s+)?(цього|поточного|минулого|попереднього)\s+(тижня|місяця)$/i, "")
      .replace(/\s+(за\s+)?(минул|попередн)[а-яіїєґ]*\s+(тиждень|місяц[ья]?|місяць)$/i, "")
      .replace(/\s+(за\s+|на\s+|по\s+)?\d{1,2}[.\/]\d{1,2}([.\/]\d{2,4})?$/i, "")
      .replace(new RegExp(`\\s+(за\\s+)?\\d{1,2}\\s+${MONTH_GEN}(\\s+\\d{4})?$`, "i"), "")
      .replace(/\s+з\s+\d{1,2}[.\/]\d{1,2}.*$/i, "")
      .trim();
  // Хвости чіпляються один за одного («Кулика за вчора з накладними»), тому два проходи.
  const cut = once(once(name));
  return cut.length >= 3 ? cut : null;
}

/** Слово, після якого стоїть період: ознака, що питають про звіт, а не про товар. */
const PERIOD_WORD =
  /(^|\s)(за|цього|поточного|минулого|попереднього|сьогодні|вчора|учора|позавчора|\d{1,2}[.\/]\d{1,2})(\s|$)/i;

/**
 * Ім'я з великої літери одразу після тригера: «оборот Кулика», «розкажи
 * про Пайду». Велика літера — і є ознака імені (як у «де Пайда»), тому
 * шаблон імені без прапорця /i, а тригер — з ним.
 */
const NAME_AT_START = /^([А-ЯІЇЄҐ][а-яіїєґ'ʼ-]{2,}(?:\s+[А-ЯІЇЄҐ][а-яіїєґ'ʼ-]{2,})?)(?=\s|$)/;
const NOT_A_PERSON = /^(Сьогодні|Вчора|Учора|Завтра|Позавчора|За|По|Цього|Минулого|Поточного|Попереднього)$/;

function nameAfter(text: string, trigger: RegExp): string | null {
  const match = new RegExp(trigger.source, "i").exec(text);
  if (!match) return null;
  const rest = text.slice(match.index + match[0].length).replace(/^\s+/, "");
  const name = NAME_AT_START.exec(rest);
  if (!name || NOT_A_NAME.test(name[1]) || NOT_A_PERSON.test(name[1])) return null;
  return name[1];
}

/** «Сьогодні / завтра / вчора» — спільно для водійських питань. */
function dayWord(text: string): "today" | "tomorrow" | "yesterday" {
  return /завтра/i.test(text) ? "tomorrow" : /вчора/i.test(text) ? "yesterday" : "today";
}

/** «Зарплата водіїв» — це не ім'я; «зарплата Пайди» — ім'я. */
function driverName(raw: string | null): string | null {
  if (!raw) return null;
  return /^(воді|всіх|усіх|команди|фірми)/i.test(raw) ? null : raw;
}
