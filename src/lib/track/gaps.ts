/**
 * Добір розривів у треку реальною дорогою.
 *
 * Трек — ламана між точками GPS. Поки планшет онлайн і шле точку кожні
 * 15 секунд, відрізки короткі й пряма між ними майже збігається з дорогою.
 * Але варто планшету втратити зв'язок (тримач без інтернету, вимкнений
 * екран, глухий підвал складу) — і в треку виникає розрив: дві точки з
 * різних кінців міста з'єднуються прямою через дахи.
 *
 * Наслідок не косметичний: у пробіг іде хорда, а вона коротша за дорогу.
 * На реальному дні водія два таких розриви дали 15,74 км із 15,76 км
 * «пробігу» — тобто майже весь показник був прямими лініями.
 *
 * Тут ці відрізки прокладаються через OSRM: у пробіг іде довжина дороги,
 * а на карту — її геометрія замість прямої.
 *
 * Окремо від geo.ts свідомо: там чиста геометрія без мережі, якуганяє
 * швидкий тест без бази й інтернету. Мережеві виклики живуть тут.
 */

import { getRoute } from "@/lib/geo/osrm";
import { haversineM, MAX_ACCURACY_M } from "@/lib/track/geo";

/**
 * Скільки розривів добираємо за один прохід.
 *
 * OSRM у нас публічний демо-сервер без ключа: він лімітує й падає під
 * навантаженням. День із десятком розривів — уже аномалія (планшет майже
 * весь час офлайн), і добирати їх усі сенсу немає: точність усе одно буде
 * приблизною, а запити з'їдять ліміт для решти водіїв.
 */
export const MAX_GAPS_PER_RUN = 8;

/** Довший за це маршрут OSRM — ознака, що він об'їхав щось дивне. */
const SANITY_FACTOR = 4;

/**
 * Стеля кроку, з яким слабкі фікси лягають у лінію на карті.
 *
 * Похибка фікса по вежі буває 500–900 м, і якщо вимагати від точки
 * зсуву «більше за власну похибку», з кілометрового шматка дороги на
 * карту потрапить одна вершина. 200 м — крок, на якому вулиця лишається
 * вулицею, а тремтіння на стоянці все ще відсіюється.
 */
const WEAK_DRAW_STEP_M = 200;

/**
 * Наскільки коротшою за шлях «туди й назад» має бути пряма між сусідами,
 * щоб вершину між ними визнати промахом GPS, а не поворотом.
 *
 * Число — це косинус форми трикутника, і читати його треба кутами: 0,71
 * відповідає прямому куту на перехресті, 0,5 — гострому кутові 60°, а
 * справжній зубець зі слабкого фікса дає 0,1–0,3, бо йде майже точно
 * назад.
 *
 * Спершу стояло 0,5, і на дні з рідкими фіксами воно з'їдало вже й
 * дорогу: круті повороти заміської траси на такому кроці точок теж
 * виглядають гострими. 0,3 лишає їх на місці й прибирає рівно те, що
 * стирчить убік і вертається.
 */
const SPIKE_RATIO = 0.3;

export type GapSegment = {
  /** Індекс точки-кінця розриву в масиві треку */
  index: number;
  from: { lat: number; lng: number };
  to: { lat: number; lng: number };
  /**
   * Слабкі фікси всередині розриву: дорога має пройти через них.
   *
   * Порожньо — пристрій мовчав, і єдине, що ми знаємо, це два кінці.
   */
  via: Array<{ lat: number; lng: number }>;
  /** Пряма між точками, метри */
  straightM: number;
};

export type ResolvedGap = GapSegment & {
  /** Дорогою, метри. null — OSRM не відповів або дав неправдоподібне */
  roadM: number | null;
  /** Геометрія дороги для карти */
  geometry: GeoJSON.LineString | null;
};

/**
 * Прокладає дорогу для кожного розриву.
 *
 * Помилка OSRM не валить розбір: розрив просто лишається прямою, як було
 * досі. Пробіг тоді занижений — але це рівно та поведінка, що була до
 * цієї функції, тож гірше не стане.
 */
export async function resolveGaps(gaps: GapSegment[]): Promise<ResolvedGap[]> {
  const take = gaps.slice(0, MAX_GAPS_PER_RUN);

  return Promise.all(
    take.map(async (g): Promise<ResolvedGap> => {
      try {
        const route = await getRoute([
          [g.from.lng, g.from.lat],
          ...g.via.map((v): [number, number] => [v.lng, v.lat]),
          [g.to.lng, g.to.lat],
        ]);
        const roadM = route.totalDistanceKm * 1000;

        // Дорога не буває коротшою за пряму, а вчетверо довша — ознака, що
        // OSRM повів через міст за 20 км або не знайшов з'їзду. Краще
        // лишити чесну пряму, ніж записати водієві зайві кілометри.
        //
        // Поріг стосується і маршруту через проміжні точки: гак до
        // клієнта в нього вкладається, а от слабкий фікс, що впав на
        // сусідню автостраду й потягнув маршрут на розв'язку, — ні.
        if (roadM < g.straightM || roadM > g.straightM * SANITY_FACTOR) {
          return { ...g, roadM: null, geometry: null };
        }

        return { ...g, roadM, geometry: route.geometry };
      } catch {
        return { ...g, roadM: null, geometry: null };
      }
    })
  );
}

/**
 * Збирає лінію треку для карти, вплітаючи дороги замість прямих.
 *
 * Там, де планшет був офлайн, замість хорди через півміста підставляємо
 * геометрію реального проїзду. Точки без gapGeometry (звичайний щільний
 * трек) лягають як були — з'єднувати їх дорогами і зайве, і дорого.
 */
export function buildTrackPath(
  points: Array<{
    lat: number;
    lng: number;
    accuracyM?: number | null;
    gapGeometry?: unknown;
  }>
): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  /**
   * Скільки вершин у хвості масиву прийшли зі слабких фіксів.
   *
   * Потрібне для склейки з дорогою: коли для відрізка приходить
   * геометрія OSRM, вона описує рівно той шлях, який слабкі точки
   * намалювали від руки. Лишити обидва означало б повести лінію
   * спершу павутиною, а потім назад до опори й по дорозі.
   */
  let weakTail = 0;

  for (let i = 0; i < points.length; i++) {
    const p = points[i];
    const weak = p.accuracyM != null && p.accuracyM > MAX_ACCURACY_M;

    const line = asLineString(p.gapGeometry);
    if (line) {
      // Дорога заміняє собою чернетку зі слабких фіксів усередині розриву.
      if (weakTail > 0) out.splice(out.length - weakTail, weakTail);
      weakTail = 0;
      // Геометрія OSRM іде в [lng, lat] і включає обидва кінці. Перший
      // кінець — це попередня точка, вона вже в масиві: пропускаємо, щоб
      // не задвоїти вершину.
      for (const [lng, lat] of line.coordinates.slice(1)) {
        out.push([lat, lng]);
      }
      continue;
    }

    /**
     * Слабкий фікс малюємо лише тоді, коли він щось каже.
     *
     * Такі точки (похибка понад 100 м) з'явилися в треку навмисно: саме
     * вони засвідчують заміську дорогу, де GPS не бачить неба, і без них
     * у дні зяяли прямі на десятки кілометрів. Але на стоянці вони ж
     * дають «стрибки» на пів кварталу туди-сюди — лінія починає
     * тремтіти там, де людина година не рухалась.
     *
     * Правило: зсув менший за похибку — це шум, а не рух. Але саму
     * похибку обмежуємо стелею: фікс по вежі заявляє 800 м, і брати їх
     * буквально означало б ставити вершину раз на кілометр — саме так
     * заміська дорога перетворювалась на пряму через поля.
     */
    if (weak && out.length > 0) {
      const [prevLat, prevLng] = out[out.length - 1];
      const threshold = Math.min(p.accuracyM!, WEAK_DRAW_STEP_M);
      if (haversineM(prevLat, prevLng, p.lat, p.lng) < threshold) continue;

      /**
       * Зубець: пішов убік і одразу повернувся — це не поворот, а промах.
       *
       * Саме з таких точок на карті виростали «віяла»: слабкий фікс
       * відскакує на пів кілометра, наступний повертається на дорогу, і
       * обидва плечі проходять поріг зсуву — бо він міряє відстань, а не
       * напрямок. Дивимось на трикутник: якщо шлях у дві ноги вдвічі
       * довший за пряму між сусідами, вершина між ними — шум.
       *
       * Поворот вулиці таку перевірку проходить: там пряма між сусідами
       * лише трохи коротша за дві ноги. Зникає рівно те, що стирчить.
       */
      const next = points[i + 1];
      if (next && !asLineString(next.gapGeometry)) {
        const outM = haversineM(prevLat, prevLng, p.lat, p.lng);
        const backM = haversineM(p.lat, p.lng, next.lat, next.lng);
        const acrossM = haversineM(prevLat, prevLng, next.lat, next.lng);
        if (acrossM < (outM + backM) * SPIKE_RATIO) continue;
      }
    }

    out.push([p.lat, p.lng]);
    weakTail = weak ? weakTail + 1 : 0;
  }

  return out;
}

/** Обережне читання Json з бази: там може лежати будь-що. */
function asLineString(v: unknown): GeoJSON.LineString | null {
  if (!v || typeof v !== "object") return null;
  const g = v as { type?: unknown; coordinates?: unknown };
  if (g.type !== "LineString" || !Array.isArray(g.coordinates)) return null;
  if (g.coordinates.length < 2) return null;
  return v as GeoJSON.LineString;
}

/**
 * Знаходить розриви серед підготовлених точок.
 *
 * Приймає вже підготовлені точки (див. preparePoints). Розривом вважається
 * лише відрізок між точками, яким можна вірити: слабкі фікси в треку
 * лишаються, але дорогу між ними прокладати немає сенсу — вони й самі
 * приблизні.
 */
export function findGaps(
  points: Array<{
    lat: number;
    lng: number;
    isGap: boolean;
    gapFrom?: { lat: number; lng: number } | null;
    gapVia?: Array<{ lat: number; lng: number }> | null;
  }>,
  prev?: { lat: number; lng: number } | null
): GapSegment[] {
  const out: GapSegment[] = [];

  points.forEach((p, i) => {
    if (!p.isGap) return;
    // Опора розриву відома з підготовки: між надійними кінцями могли
    // лягти слабкі точки, і мірятися треба від кінця, а не від сусіда.
    // Якщо опори немає (старий виклик) — від сусіда, як було.
    const from = p.gapFrom ?? (i === 0 ? prev : points[i - 1]);
    if (!from) return;
    out.push({
      index: i,
      from: { lat: from.lat, lng: from.lng },
      to: { lat: p.lat, lng: p.lng },
      via: p.gapVia ?? [],
      straightM: haversineM(from.lat, from.lng, p.lat, p.lng),
    });
  });

  return out;
}
