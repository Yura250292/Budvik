-- Фото магазину — окреме поле, а не «останній знімок зі стрічки».
--
-- Нотатка з фото — це спостереження на дату, і їх багато. Фото магазину
-- одне: за ним упізнають місце, під'їхавши. Поки поля не було, картка й
-- пін на карті показували останній знімок із коментарів — а ним легко
-- виявляється кадр піддону, накладної або воріт сусіда.
--
-- photoKey потрібен, щоб замінене фото можна було прибрати з R2, а не
-- лишати назавжди висіти в сховищі.

ALTER TABLE "Counterparty"
  ADD COLUMN "photoUrl"  TEXT,
  ADD COLUMN "photoKey"  TEXT,
  ADD COLUMN "photoAt"   TIMESTAMP(3),
  ADD COLUMN "photoById" TEXT;
