/**
 * Оновлення застосовується саме — без «перезапустіть застосунок».
 *
 * Досі виправлення доїжджало так: сторож завантажував нове JS, а застосовував
 * його лише холодний старт або натиск на жовту смугу. У полі це означало, що
 * кожну публікацію треба супроводжувати вказівкою п'ятьом людям вийти й зайти,
 * і поки триває розробка, вони роблять це по кілька разів на день. Виправлення
 * при цьому не спрацьовує рівно там, де воно потрібне: у планшета, який ніхто
 * не чіпає, бо він лежить у машині.
 *
 * Тепер перезавантаження робиться в мить, коли воно нікому не заважає — коли
 * застосунок пішов з екрана. Людина повертається вже на новій версії й нічого
 * про це не знає.
 *
 * ЩО ЦЕ КОШТУЄ. Перезавантаження стирає незбережене в кабінеті: якщо торговий
 * почав заповнювати замовлення, вийшов подивитися щось в іншому застосунку й
 * повернувся — форма буде порожня. Вікно вузьке (лише коли оновлення справді
 * чекає, тобто раз на публікацію), і те саме робить сам Android, коли вбиває
 * процес заради пам'яті. На тлі щоденних ручних перезапусків розмін вигідний,
 * але він є, і знати про нього треба.
 *
 * ЩО ЦЕ НЕ ЛАМАЄ. Трек переживає перезавантаження цілим: точки лежать у
 * SQLite, служба локації нативна й `killServiceOnDestroy: false` не дає їй
 * вмерти разом із процесом, а завдання переоголошується в task.ts на першому ж
 * імпорті. Відкладена зміна й невідправлені візити теж у SQLite.
 */

import { useEffect, useRef } from "react";
import { AppState } from "react-native";
import * as Updates from "expo-updates";
import { checkJsUpdate } from "@/lib/self-update";
import { getMeta, setMeta } from "@/track/db";

/**
 * Скільки застосунок має пробути поза екраном, щоб перезавантажити його при
 * поверненні.
 *
 * Запасний шлях на випадок, коли перезавантаження у фоні не спрацювало:
 * Android має право приспати процес рівно в ту мить. Десять хвилин — щоб
 * швидке перемикання «глянув пошту й назад» не рвало роботу.
 */
const AWAY_ENOUGH_MS = 10 * 60_000;

/** Ключ у сховищі: яке саме оновлення ми вже пробували застосувати самі. */
const TRIED_KEY = "autoReloadTried";

export function useAutoUpdate(): void {
  const { isUpdatePending, downloadedUpdate } = Updates.useUpdates();
  /** Слухач AppState живе довше за рендер — свіже значення беремо з рефа. */
  const pending = useRef(isUpdatePending);
  pending.current = isUpdatePending;
  const readyId = useRef(downloadedUpdate?.updateId);
  readyId.current = downloadedUpdate?.updateId;
  const awaySince = useRef(0);

  useEffect(() => {
    if (!Updates.isEnabled) return;

    /**
     * Одне оновлення — одна спроба, і це не перестраховка.
     *
     * Якщо завантажене оновлення чомусь не піднімається, expo-updates
     * відкочується на попереднє, а `isUpdatePending` лишається піднятим. Без
     * пам'яті про спробу планшет перезавантажувався б на кожному згасанні
     * екрана — тобто застосунок помер би по колу, і саме на тих п'ятьох
     * планшетах, які ми не бачимо. Мітка живе у тій самій SQLite, що й буфер
     * треку: вона мусить пережити рестарт, інакше ніякої пам'яті немає.
     */
    const applyOnce = async () => {
      const id = readyId.current;
      if (!id) return;
      if ((await getMeta(TRIED_KEY).catch(() => null)) === id) return;
      await setMeta(TRIED_KEY, id).catch(() => {});
      await Updates.reloadAsync().catch(() => {});
    };

    const sub = AppState.addEventListener("change", (state) => {
      if (state === "background") {
        awaySince.current = Date.now();
        // Тут і є та сама мить: екрана немає, втрачати нічого.
        if (pending.current) void applyOnce();
        return;
      }

      if (state !== "active") return;

      /**
       * Повернулися — питаємо про оновлення одразу, не чекаючи сторожа.
       * Так наступний вихід з екрана вже застосує свіже.
       */
      void checkJsUpdate().catch(() => {});

      if (pending.current && Date.now() - awaySince.current >= AWAY_ENOUGH_MS) {
        void applyOnce();
      }
    });

    return () => sub.remove();
  }, []);
}
