-- Ідемпотентність накладних із застосунку.
--
-- У бота роль ключа грає telegramFileId: переслане вдруге фото не створює
-- другий звіт. Застосунок file_id не має — зате має самі байти, тож ключем
-- стає їхній SHA-256. Без нього обірваний посеред відповіді запит (мережа на
-- складі рветься щодня) давав би офісу другу копію тієї самої накладної на
-- кожен повтор.
--
-- Унікальність по людині, а не глобальна: та сама накладна, сфотографована
-- двома складовщиками, — це дві різні події, а не дубль.
ALTER TABLE "WarehouseReport" ADD COLUMN "photoSha256" TEXT;

CREATE UNIQUE INDEX "WarehouseReport_userId_photoSha256_key"
  ON "WarehouseReport"("userId", "photoSha256");
