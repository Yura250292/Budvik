/**
 * Пробудження сповіщенням: єдиний спосіб оживити трек без людини.
 *
 * ЩО ЦЕ ЛІКУЄ. Android із 12-ї версії забороняє піднімати службу переднього
 * плану з фону. Тобто застосунок, якого система прибила, не має права
 * повернути себе до життя — він не зламаний, він у наручниках. Саме тому
 * місяць єдиною порадою при мертвому треку було «відкрийте застосунок»: з
 * переднього плану запуск дозволений завжди, а з фону — ніколи.
 *
 * ЧОМУ САМЕ СПОВІЩЕННЯ. Постукати ззовні у сплячий Android може рівно одна
 * річ: канал Google, через який приходять повідомлення месенджерів. Він
 * єдиний на весь пристрій і живе незалежно від нашого процесу — тому Telegram
 * і дзвонить, коли його не відкривали тиждень.
 *
 * І головне: доставка сповіщення заносить застосунок у ТИМЧАСОВИЙ білий
 * список системи. У цьому вікні запуск служби переднього плану дозволений —
 * це один із небагатьох винятків, які Android залишив. Тобто сповіщення тут
 * не текст для людини, а ключ, який знімає наручники.
 *
 * ЧОГО ЦЕ НЕ ЛІКУЄ, і не треба вдавати інакше. Якщо застосунок змахнули зі
 * списку відкритих, система вважає його примусово зупиненим — і тоді до нього
 * не доходить навіть сповіщення. Жодна страховка не працює, доки людина не
 * відкриє його руками. Тому текст сповіщення просить саме про це: воно і
 * пробує полагодити мовчки, і залишає видиму просьбу, якщо не вийшло.
 */

import { ensureRecording } from "./controller";
import { flush, heartbeat } from "./uploader";
import { logEvent } from "./db";
import { isShiftOpen } from "./state";

/**
 * Що робити, коли сервер постукав.
 *
 * Порядок від найважливішого до найдешевшого: спершу підняти запис (заради
 * цього все й затівалося), потім віддати те, що лежить у планшеті, і аж потім
 * доповісти про себе. Кожен крок окремо загорнутий: провал одного не має
 * коштувати наступних, бо вікно дозволу коротке й другого не буде.
 */
export async function onWakePush(reason: string): Promise<void> {
  void logEvent("wake", reason.slice(0, 180));

  /**
   * Не піднімаємо запис, якщо зміна закрита.
   *
   * Сервер міг послати сигнал за мить до того, як офіс закрив зміну, — і
   * планшет, який чесно виконав команду, писав би трек людині, що вже вдома.
   * Рішення про потребу запису ухвалює `ensureRecording` за роллю й станом
   * зміни; тут лише швидкий вихід, щоб не будити службу дарма.
   */
  const open = await isShiftOpen().catch(() => false);
  if (!open) {
    void logEvent("wake", "зміна закрита — запис не піднімаємо");
    await heartbeat(true).catch(() => {});
    return;
  }

  const raised = await ensureRecording().catch(() => false);
  void logEvent("wake", raised ? "запис піднято" : "запис уже йшов або не піднявся");

  // Те, що лежить у планшеті, віддаємо тим самим пробудженням: мережа зараз
  // напевно є — сповіщення щойно доїхало саме нею.
  await flush(true).catch(() => {});

  /**
   * Пульс примусовий: без нього сервер не дізнається, чим скінчилося
   * пробудження, і слатиме сигнал знову й знову. А з ним у пульті видно
   * головне — чи ожив запис від стуку, чи ні.
   */
  await heartbeat(true).catch(() => {});
}
