/**
 * Пробудження сповіщенням: єдиний спосіб оживити трек без людини.
 *
 * ЩО ЦЕ ЛІКУЄ. Android із 12-ї версії забороняє піднімати службу переднього
 * плану з фону. Тобто застосунок, якого система прибила, не має права
 * повернути себе до життя — він не зламаний, він у наручниках. Саме тому
 * місяць єдиною порадою при мертвому треку було «відкрийте застосунок»: з
 * переднього плану запуск дозволений завжди, а з фону — ніколи.
 *
 * ЧОМУ САМЕ СПОВІЩЕННЯ. Постукати ззовні у сплячий Android може рівно одна
 * річ: канал Google, через який приходять повідомлення месенджерів. Він
 * єдиний на весь пристрій і живе незалежно від нашого процесу — тому Telegram
 * і дзвонить, коли його не відкривали тиждень.
 *
 * І головне: доставка сповіщення заносить застосунок у ТИМЧАСОВИЙ білий
 * список системи. У цьому вікні запуск служби переднього плану дозволений —
 * це один із небагатьох винятків, які Android залишив. Тобто сповіщення тут
 * не текст для людини, а ключ, який знімає наручники.
 *
 * ЧОМУ СИГНАЛ ТИХИЙ. Правило Google: повідомлення З ТЕКСТОМ Android віддає
 * одразу в шторку й застосунок не запускає взагалі. Тобто видиме сповіщення —
 * саме те, що зробило б усе це неможливим. Будить лише повідомлення без
 * тексту, самими даними. Перевірено на живому планшеті 08.09: із текстом Expo
 * двічі відзвітував «доставлено», сповіщення на екрані було, а застосунок не
 * прокинувся.
 *
 * Тому текст для людини малює сам застосунок — і лише тоді, коли тихе
 * підняття не вдалося. Спрацювало тихо — людину не турбуємо взагалі.
 *
 * ЧОГО ЦЕ НЕ ЛІКУЄ, і не треба вдавати інакше. Якщо застосунок змахнули зі
 * списку відкритих, система вважає його примусово зупиненим — і тоді до нього
 * не доходить навіть сповіщення. Жодна страховка не працює, доки людина не
 * відкриє його руками.
 */

import { isTracking, warnRecordingDown } from "./controller";
import { ensureFreshFixes } from "./health";
import { reloadIfStuck } from "./unstick";
import { flush, heartbeat } from "./uploader";
import { logEvent } from "./db";
import { isShiftOpen } from "./state";

/**
 * Що робити, коли сервер постукав.
 *
 * Порядок від найважливішого до найдешевшого: спершу підняти запис (заради
 * цього все й затівалося), потім віддати те, що лежить у планшеті, і аж потім
 * доповісти про себе. Кожен крок окремо загорнутий: провал одного не має
 * коштувати наступних, бо вікно дозволу коротке й другого не буде.
 */
export async function onWakePush(reason: string): Promise<void> {
  void logEvent("wake", reason.slice(0, 180));

  /**
   * Не піднімаємо запис, якщо зміна закрита.
   *
   * Сервер міг послати сигнал за мить до того, як офіс закрив зміну, — і
   * планшет, який чесно виконав команду, писав би трек людині, що вже вдома.
   * Рішення про потребу запису ухвалює `ensureRecording` за роллю й станом
   * зміни; тут лише швидкий вихід, щоб не будити службу дарма.
   */
  const open = await isShiftOpen().catch(() => false);
  if (!open) {
    void logEvent("wake", "зміна закрита — запис не піднімаємо");
    await heartbeat(true).catch(() => {});
    return;
  }

  /**
   * Лікуємо ЗАСТІЙ, а не читаємо прапорець.
   *
   * Досі тут стояв `ensureRecording`, який дивиться на `isTracking()` — а той
   * після підняття процесу з фону бреше. 10.09 Кулик о 14:26: «розбуджено
   * сповіщенням» → «службу запущено» → нуль точок, а пульс поруч каже
   * `sub=false` і фікс з учора. Єдине законне вікно змарнували на «вже
   * пишемо».
   *
   * `ensureFreshFixes` питає інше — чи приходили фікси, — і сам падає в
   * `ensureRecording`, коли режиму немає. `pushWindow` каже йому, що зараз
   * можна піднімати службу з фону: сповіщення щойно доїхало, система дала
   * тимчасове помилування. Параметр існував від початку — його просто ніхто
   * не передавав.
   */
  const health = await ensureFreshFixes({ pushWindow: true }).catch(() => "не-пишемо" as const);
  const raised = health === "перепідписались";
  const ok = raised || health === "свіжо";
  void logEvent("wake", `запис: ${health}`);

  /**
   * Не піднявся — аж тепер кажемо людині.
   *
   * Сигнал із сервера приходить ТИХИМ навмисно: сповіщення з текстом Android
   * віддає в шторку й застосунок не будить, тобто саме воно й унеможливило б
   * усе це. Тож видимий текст малює застосунок сам — і лише коли тихе
   * підняття не спрацювало.
   *
   * Порядок правильний і сам собою: якщо запис ожив, людину не турбуємо
   * взагалі. Вона й не мала знати, що трек падав і піднявся, — це наша
   * робота, а не її.
   *
   * `warnRecordingDown` уже має власну межу (раз на пів години) і мовчить
   * при закритій зміні, тож повторів не буде.
   */
  if (!ok) {
    const stillDown = await isTracking().catch(() => false);
    if (!stillDown) await warnRecordingDown().catch(() => {});
  }

  // Те, що лежить у планшеті, віддаємо тим самим пробудженням: мережа зараз
  // напевно є — сповіщення щойно доїхало саме нею.
  await flush(true).catch(() => {});

  /**
   * Сервер стукає саме тоді, коли точок немає давно, — тобто в тому стані,
   * коли контекст міг застрягти при живій службі. Перепідписка вище цього не
   * лікує; рестарт — лікує (див. unstick.ts). Щойно перепідписалися — даємо
   * їй хвилину, не рвемо одразу.
   *
   * ПІСЛЯ зливу навмисно: якщо рестарт станеться, цей контекст більше нічого
   * не відправить, а мережа саме зараз є. Буфер у SQLite переживе рестарт, але
   * навіщо відкладати те, що можна віддати цієї ж миті.
   */
  await reloadIfStuck("пробудження", { justResubscribed: raised }).catch(() => {});

  /**
   * Пульс примусовий: без нього сервер не дізнається, чим скінчилося
   * пробудження, і слатиме сигнал знову й знову. А з ним у пульті видно
   * головне — чи ожив запис від стуку, чи ні.
   */
  await heartbeat(true).catch(() => {});
}
