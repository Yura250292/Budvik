/**
 * Ринки Львова з перевіреними координатами.
 *
 * Окремих павільйонів у жодному довіднику немає, тож ціль — сам ринок:
 * це десятки метрів замість кілометрів до центру міста. Геокодер тут шкодить:
 * «ринок Торпедо» знаходить стадіон «Торпедо» на Золотій, а «Шувар» — Верхній
 * ТЦ на Червоної Калини замість Нижнього оптового за кілометр.
 */

export type Market = { match: RegExp; lat: number; lng: number; label: string };

export const LVIV_MARKETS: Market[] = [
  { match: /торпедо/i, lat: 49.865165, lng: 24.056877, label: "ринок Торпедо" },
  { match: /краківськ/i, lat: 49.8463445, lng: 24.0177547, label: "Краківський ринок" },
  { match: /нижній\s*шувар|шувар/i, lat: 49.7961, lng: 24.034774, label: "ринок Нижній Шувар" },
  { match: /привокзальн/i, lat: 49.8397, lng: 23.9944, label: "Привокзальний ринок" },
  { match: /перфецьког/i, lat: 49.8028, lng: 23.9909, label: "ринок на Перфецького" },
  { match: /галицьк\S*\s*перехрест/i, lat: 49.8742, lng: 24.06276, label: "ринок Галицьке перехрестя" },
  { match: /галицьк(ий)?\s*ринок/i, lat: 49.8383, lng: 24.0322, label: "Галицький ринок" },
];

/** Відомий львівський ринок з адреси, якщо він там є. */
export function lvivMarketOf(address: string): Market | null {
  return LVIV_MARKETS.find((m) => m.match.test(address)) ?? null;
}
