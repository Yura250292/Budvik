/**
 * Поточна версія збірки — для самолікування відкритих вкладок.
 *
 * Планшет водія висить у тримачі з відкритою вкладкою годинами, а деплої
 * їдуть кілька разів на день. Після деплою стара сторінка не може
 * довантажити свої чанки (хеші змінились), і кнопки тихо перестають
 * працювати — «натискаю і нічого». Клієнт опитує цей ендпоінт і, коли
 * версія змінилась, перезавантажує себе сам.
 */

import { NextResponse } from "next/server";

export const dynamic = "force-dynamic";

export async function GET() {
  return NextResponse.json({
    // На Vercel це sha коміту; локально — стабільна заглушка, щоб дев не
    // перезавантажувався по колу.
    version: process.env.VERCEL_GIT_COMMIT_SHA ?? "dev",
  });
}
