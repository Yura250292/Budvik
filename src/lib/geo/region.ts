/**
 * Де шукати адресу клієнта.
 *
 * Майже вся база — Львівщина, а геокодер без рамки знаходить однойменну
 * вулицю будь-де в Україні: «Жовква, вул. Б.Хмельницького, 8» ставало в
 * Крим, «Кам'янка-Бузька, Незалежності 79» — на Чернігівщину, «Стрий, базар»
 * — у Київ. Такі точки виглядали точними й ніде не позначались.
 *
 * Тому для львівських адрес пошук обмежуємо рамкою області, а рамку знімаємо
 * лише там, де адреса сама каже, що вона деінде: відділення Нової Пошти в
 * іншому місті, Київ, Чернівці, «Запорізька обл.» тощо.
 */

export type GeoBox = { south: number; west: number; north: number; east: number };

/**
 * Прямокутник Львівщини з запасом — рамка ПОШУКУ для Nominatim (viewbox).
 * Точний контур області — LVIV_OBLAST у ./lviv-oblast (для «наш чи лише
 * доставка»); тут навмисно ширше: клієнт біля кордону не має відпадати.
 */
export const LVIV_OBLAST_BOX: GeoBox = { south: 48.6, west: 22.5, north: 50.9, east: 25.6 };

export function inBox(box: GeoBox, lat: number, lng: number): boolean {
  return lat >= box.south && lat <= box.north && lng >= box.west && lng <= box.east;
}

/**
 * Міста поза Львівщиною, які трапляються в наших адресах. Корені, а не повні
 * назви: «Чернівці», «м.Чернівці», «Черновцы» — усі мають ловитися.
 *
 * Лише назви, яких немає на Львівщині: «Миколаїв» тут і місто біля Стрия,
 * і обласний центр на півдні (24.09.2026 клієнта з-під Стрия так і
 * відправило до моря), а «Івано-Франкове» — село під Яворовом.
 */
const ELSEWHERE =
  /(київ|киев|kyiv|чернівц|черновц|дніпр|днепр|запоріж|запорож|харків|харьков|одес|вінниц|винниц|івано-франківськ|ивано-франковск|тернопіл|тернопол|луцьк|луцк|рівне|ровно|ужгород|мукачев|хмельниц|житомир|черкас|полтав|суми|сумы|чернігів|чернигов|херсон|кропивниц|кременчу|біла\s*церкв|белая\s*церк|ірпін|ирпен|бровар|бориспіл|кривий\s*ріг|кривой\s*рог|світловодськ|светловодск)/iu;

/** «Запорізька обл.», «Київська область» — будь-яка область, крім Львівської. */
const OTHER_OBLAST = /([а-яіїєґ']+ськ[аоі]\w*)\s+(обл\.?|област)/giu;

const PARCEL_POINT = /нова\s*пошта|нп\s*№|поштомат|rozetka|розетка|укрпошта|meest|міст\s*експрес/iu;

/**
 * Рамка пошуку для адреси: Львівщина, або нічого, якщо адреса явно деінде.
 *
 * Пункт видачі посилок без «Львів» у рядку теж без рамки: «НОВА ПОШТА №2,
 * с.Солочин» — це Закарпаття, і клієнт там отримує товар, а не торгує.
 */
export function searchBoxFor(address: string): GeoBox | undefined {
  const s = address.toLowerCase();
  // Назви вулиць не рахуються: «вул. Б.Хмельницького» у Жовкві — не місто
  // Хмельницький, «вул. Київська» — не Київ.
  const places = s.replace(/(вул|вулиц|просп|пл\.|площ|пров|бульв|шосе)[^,]*/gu, " ");
  if (ELSEWHERE.test(places)) return undefined;
  for (const m of places.matchAll(OTHER_OBLAST)) {
    if (!/^львівськ/u.test(m[1])) return undefined;
  }
  if (PARCEL_POINT.test(s) && !/львів|львов/u.test(s)) return undefined;
  return LVIV_OBLAST_BOX;
}
