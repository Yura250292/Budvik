/**
 * Вікно «швидкості» складських звітів: за скільки днів рахувати рух.
 *
 * Одне на закупівлі (low-stock) і оборотність (turnover) — дефіцит і
 * неліквід є двома сторонами одного питання, і рахувати їх за різними
 * вікнами означало б давати закупівельникові два різні уявлення про той
 * самий товар. Тому й варіанти, і розбір параметра живуть в одному місці,
 * а не в кожному роуті окремо.
 *
 * Стеля 180, а не 365: складський звіт питає «як рухається ЗАРАЗ», і річне
 * вікно усереднило б сезон у кашу — літній і зимовий товар отримали б ту
 * саму швидкість. Історія з 2024 року для цього не потрібна; вона живе в
 * сезонному профілі (seasonality.ts).
 */
export const VELOCITY_OPTIONS = [30, 60, 90, 180] as const;

export const DEFAULT_VELOCITY_DAYS = 90;

/** Розбирає ?days= із запиту: усе поза списком варіантів — дефолт. */
export function parseVelocityDays(raw: string | null): number {
  const n = Number(raw);
  return (VELOCITY_OPTIONS as readonly number[]).includes(n) ? n : DEFAULT_VELOCITY_DAYS;
}
