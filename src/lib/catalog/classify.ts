/**
 * Класифікатор товару: до якої групи і якого розділу він належить.
 *
 * Чому не «перше слово назви», як було. Правило «зріж бренд, візьми перше
 * слово» дешеве й покривало 80% каталогу — але воно не знає, що в назві
 * написано. Через нього в каталозі жили три різні хвороби:
 *
 *   1. Розділ і фільтр рахували РІЗНЕ. Зміст рахував тип за першим словом,
 *      а посилання розділу фільтрувало `name contains «болгарка»` — і в
 *      «Електроінструмент» приїжджали «Щітка чаша (КШМ)» і «Ланцюг до
 *      бензопили». Заміряно: 42% видачі розділу були чужими товарами.
 *   2. Перше слово часто не іменник: «Акумуляторна батарея» давала тип
 *      «акумуляторна», «Кабельна кліпса» — «кабельна», «Косильна струна» —
 *      «косильна». У змісті це виглядало як окремі групи товарів.
 *   3. Одне слово — різні товари: «Пила садова» (ручна, сад) і «Циркулярна
 *      пила» (електро); «Компресор автомобільний» (авто) і «Компресор
 *      поршневий 100 л» (пневмо); «Штуцер цанговий MT ½"» (пневматика) і
 *      «Штуцер для шланга» (полив).
 *
 * Тому тип виводиться з УСІЄЇ назви впорядкованим списком правил: перше, що
 * збіглося, і виграє. Правила читаються згори вниз, тож найточніші стоять
 * першими — спершу «щітка для КШМ», і тільки потім «болгарка».
 *
 * Ключ типу (`type`) — це те, що стоїть у ?type= і в /catalog/typ/<...>, тож
 * він лишається людською кирилицею: /catalog/typ/свердло каже більше за
 * трансліт.
 */

/**
 * Латинські двійники кириличних літер.
 *
 * У 1С назви набирають вручну, і в базі співіснують «Свердло» та «Cвердло» з
 * латинською C — це 24 товари, які випадали з групи свердел. Те саме з
 * «Ізоляцiйна», «Лiска», «Карабiн», «Термозбiжна» — латинська i.
 */
const HOMOGLYPHS: Record<string, string> = {
  a: "а", c: "с", e: "е", i: "і", o: "о", p: "р", x: "х", y: "у",
  k: "к", m: "м", t: "т", h: "н", b: "в",
};

const CYRILLIC = /[Ѐ-ӿ]/;

/**
 * Назва в одному написанні: NFC, нижній регістр, латинські двійники в
 * кириличних словах замінені, апострофи й лапки зведені до одного знаку.
 *
 * Замінюємо лише всередині слів, де кирилиця вже є: інакше «PRO», «HSS» і
 * «MT ¼"» перетворились би на кирилицю й перестали збігатися з правилами.
 */
export function normalizeName(raw: string): string {
  const lowered = raw.normalize("NFC").toLowerCase().replace(/[`'’ʼ]/g, "'");
  return lowered.replace(/[\p{L}\p{N}]+/gu, (word) => {
    if (!CYRILLIC.test(word)) return word;
    return word.replace(/[a-z]/g, (ch) => HOMOGLYPHS[ch] ?? ch);
  });
}

