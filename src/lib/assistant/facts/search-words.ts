/**
 * Слова запиту → шаблони для ILIKE.
 *
 * Дві біди, обидві з бойових питань, і обидві однакові для клієнтів і
 * для товарів.
 *
 * Перша: суцільний підрядок не збігається. Питають «круг відрізний 125»,
 * а в 1С товар зветься «Круг відрізний (метал) ATAMAN 125 1,2 22,23».
 * Тому кожне слово шукається окремо, і всі мають знайтися.
 *
 * Друга: питають у непрямому відмінку. «Скільки ще піни Soma fix»,
 * «з чим заходити до Химича», «винен Кунанця» — а в базі лежить
 * називний. Тому від слова відкидається закінчення.
 *
 * Два символи від шести — саме стільки з'їдають українські закінчення з
 * чергуванням (Кунанець → Кунанця), один — від чотирьох (піни → пін).
 * Коротші слова не чіпаємо: від «Біб» після обрізання лишиться шум.
 *
 * `cut` відрізає ще стільки ж — це ДРУГА спроба, коли перша не знайшла
 * нікого. «Кунанцем» після звичайного обрізання дає «Кунанц», а в базі
 * лежить «Кунанець»: випала та сама голосна, через яку основа й не
 * збіглася. Одразу різати глибше не можна — коротка основа знаходить
 * половину бази.
 */

/**
 * Кирилиця → латиниця для назв брендів.
 *
 * Люди пишуть і кажуть бренди українською: «сома фікс», «грьосер»,
 * «поляк». У базі ж вони латиницею — «SOMA FIX», «Grösser», «POLAX», — і
 * підрядковий пошук між абетками не працює взагалі: жодна буква не
 * збігається.
 *
 * Найважливіше правило — «кс» → «x»: без нього «фікс» стає «fiks» і не
 * знаходить «FIX». Далі — звичайна українська латинка; «г» → «h» і
 * «g» одночасно дати не можна, тож беремо «g»: у назвах брендів воно
 * частіше («Grösser», «GRAD», «GRANITE»).
 */
const TRANSLIT: Array<[RegExp, string]> = [
  // «Юніфікс» — це UNIFIX: на початку слова «ю» звучить як u, а не iu.
  [/^ю/, "u"],
  // Розпізнавач інколи віддає російські літери («грёсер») — не сперечаємось.
  [/ё/g, "o"],
  [/ы/g, "y"],
  [/э/g, "e"],
  [/ъ/g, ""],
  [/кс/g, "x"],
  [/щ/g, "shch"],
  [/ш/g, "sh"],
  [/ч/g, "ch"],
  [/ц/g, "ts"],
  [/х/g, "kh"],
  [/ж/g, "zh"],
  [/ю/g, "iu"],
  [/я/g, "ia"],
  [/є/g, "ie"],
  [/ї/g, "i"],
  [/й/g, "i"],
  [/[ьʼ']/g, ""],
  [/а/g, "a"], [/б/g, "b"], [/в/g, "v"], [/г/g, "g"], [/ґ/g, "g"],
  [/д/g, "d"], [/е/g, "e"], [/з/g, "z"], [/и/g, "y"], [/і/g, "i"],
  [/к/g, "k"], [/л/g, "l"], [/м/g, "m"], [/н/g, "n"], [/о/g, "o"],
  [/п/g, "p"], [/р/g, "r"], [/с/g, "s"], [/т/g, "t"], [/у/g, "u"],
  [/ф/g, "f"],
];

/**
 * Українська абетка з латиницею — те, що вважається буквою в назві.
 *
 * Одне визначення на всіх навмисно: цей клас стоїть і в межі слова для
 * строгого пошуку, і в оцінці релевантності, і в пошуку по закупівлях
 * клієнта. Копії розходяться мовчки — дописана в одну апострофа чи
 * «ö» з «Grösser» змусить два правила по-різному думати, де кінчається
 * слово.
 */
export const LETTER = "А-Яа-яІіЇїЄєҐґA-Za-z";

/** «фікс» → «fix». Слово без кирилиці повертається як є. */
export function translit(word: string): string {
  if (!/[а-яіїєґ]/i.test(word)) return word;
  let out = word.toLowerCase();
  for (const [re, to] of TRANSLIT) out = out.replace(re, to);
  return out;
}

/**
 * Довгі закінчення, яких обрізанням на два символи не дістати.
 *
 * «Зварювання» і «зварювальний» — те саме слово, але корінь у них
 * розходиться на четвертій з кінця букві, а правило різало дві. Виходило
 * «зварюван», яке не збігається зі «зварювальний» ЖОДНИМ підрядком, і
 * запит про зварювальний дріт повертав нуль на товар, якого на складі
 * 650 штук.
 *
 * Відрізаємо ПЕРШЕ збіжне закінчення, тому порядок — частина правила, а
 * не оформлення: коротше «ний», яке стоїть попереду довшого «альний»,
 * мовчки недоріже «зварювальний» до «зварюваль» і поверне той самий
 * нуль. Покладатися на те, що наступний рядок допишуть у правильне
 * місце, не варто, тож сортуємо на місці.
 *
 * Підлога в пʼять букв стримує від надто короткої основи: «зварю» знайде
 * ще й «зварювати» разом із половиною сусіднього змісту.
 */
const ENDINGS = [
  "ування", "ювання", "альний", "ований", "альна", "альні", "ована",
  "ання", "ення", "іння", "еної", "ений", "ості", "істю", "овий",
  "ова", "ого", "ому", "ими", "ами", "ями", "ний", "них", "ної",
].sort((a, b) => b.length - a.length);

/**
 * Основа слова для пошуку за підрядком.
 *
 * Правил тут два, і беремо ЗАВЖДИ коротший результат: закінчення
 * дістає те, що не дістає обрізання («зварювання» → «зварюв»), а
 * обрізання — те, чого немає в списку («свердла» → «сверд», бо в базі
 * лежить «свердел»). Коротша основа знаходить надмножину, тож жоден
 * збіг, який працював досі, не губиться.
 */
export function stem(word: string, cut = 0): string {
  const extra = Math.max(0, cut);
  const cutTo = word.length >= 6 ? -(2 + extra) : word.length >= 4 ? -(1 + extra) : 0;
  const byLength = cutTo === 0 ? word : word.slice(0, cutTo);

  /*
   * Порівнюємо в нижньому регістрі, бо люди пишуть КАПСОМ, а розпізнавач
   * голосу віддає слово з великої. «ЗВАРЮВАННЯ» не закінчувалося на
   * «ання» й лишалося «ЗВАРЮВАН» — тобто саме той нуль, проти якого
   * закінчення й додавали. Різати треба вихідне слово: ILIKE регістр
   * однаково не розрізняє, а от підкреслення в чергуванні — розрізняє.
   */
  const lower = word.toLowerCase();
  const ending = ENDINGS.find((e) => lower.length - e.length >= 5 && lower.endsWith(e));
  const byEnding = ending ? word.slice(0, -ending.length - extra) : byLength;

  const stemmed = byEnding.length < byLength.length ? byEnding : byLength;

  /**
   * Три букви — підлога.
   *
   * Друга спроба з коротшою основою на слові «фікс» давала «фі», і пошук
   * «сома фікс» повертав «фібергласову рукоятку»: два символи є майже в
   * кожній назві. Коротше за три букви шукати немає сенсу — краще
   * повернути порожньо й піти наступною спробою.
   */
  return stemmed.length >= 3 ? stemmed : word.slice(0, Math.min(3, word.length));
}

/**
 * Шаблони `%основа%` для кожного значущого слова запиту.
 *
 * Максимум шість слів: довший запит — це вже речення, і кожне зайве
 * слово в ILIKE ALL відсікає правильні збіги замість того, щоб уточнити.
 */
export function searchPatterns(query: string, limitWords = 6, cut = 0): string[] {
  // Правову форму відпускаємо лише на другій спробі — див. LEGAL.
  return words(query, limitWords, cut > 0).map((w) => `%${stem(w, cut)}%`);
}

/**
 * Кожне слово запиту — з варіантами написання.
 *
 * «Сігма піна» — це половина латиницею («SIGMA»), половина кирилицею
 * («Піна монтажна»), і жоден суцільний набір шаблонів такого не знайде:
 * транслітерувавши все, ми втрачаємо «піну», не транслітерувавши — не
 * знаходимо «SIGMA». Тому на слово повертається кілька шаблонів, і
 * збігтися має ХОЧ ОДИН із них — а слова між собою лишаються обовʼязковими.
 *
 * Порядок усередині слова важливий: спершу транслітеруємо ЦІЛЕ слово,
 * потім відкидаємо закінчення. Навпаки виходить «фік» → «fik», що не
 * знаходить «FIX».
 */
export function wordVariants(query: string, limitWords = 6, cut = 0): string[][] {
  return words(query, limitWords, true).map((w) => {
    const base = stem(w, cut);
    const variants = new Set<string>([`%${base}%`]);
    const swap = vowelSwap(base);
    if (swap) variants.add(`%${swap}%`);
    const latin = translit(w);
    if (latin !== w.toLowerCase()) variants.add(`%${stem(latin)}%`);
    const alias = ALIASES.find(([re]) => re.test(w));
    if (alias) variants.add(alias[1]);
    return [...variants];
  });
}

/**
 * Чергування голосних: «дріт» у непрямому відмінку стає «дроту».
 *
 * У закритому складі українська пише «і», у відкритому — «о» або «е»:
 * дріт/дроту, стіл/столу, ніж/ножа, піч/печі. Основа при цьому
 * розходиться на ОДНУ букву всередині слова, і підрядок такого не
 * прощає: «що є з дроту для зварювання» не знаходило «Дріт зварювальний»
 * узагалі. Триграми теж не рятують — вони чіпляються за «для
 * зварювання» й видають рукавиці зварювальника.
 *
 * Підкреслення в ILIKE — рівно одна будь-яка буква, тож «др_т» покриває
 * обидва написання. Міняється лише ОСТАННЯ голосна кореня, і лише в
 * основах від чотирьох букв: коротші дають «др_», яке є в кожному
 * другому слові.
 */
function vowelSwap(stemmed: string): string | null {
  /*
   * Чергування живе в КОРОТКИХ коренях — дріт, стіл, ніж, віз, піч. На
   * довгій основі підкреслення лише розмиває пошук: «м_нтаж» знаходить
   * рівно те саме, що «монтаж», зате «ст_л» чіпляє «кристал» і
   * «хрустальний». Тому вікно вузьке з обох боків.
   */
  if (stemmed.length < 4 || stemmed.length > 6) return null;
  const lower = stemmed.toLowerCase();
  const at = Math.max(lower.lastIndexOf("і"), lower.lastIndexOf("о"), lower.lastIndexOf("е"));
  // Голосна на самому краю основи нічого не уточнює: «електр_» замість
  // «електро» знайде рівно те саме, лише повільніше.
  if (at < 1 || at >= stemmed.length - 1) return null;
  return `${stemmed.slice(0, at)}_${stemmed.slice(at + 1)}`;
}

/**
 * Назви, яких транслітерація не дістає в принципі.
 *
 * «Grösser» вимовляють «грьосер», «гресер», «гросер» — і жодне з них не
 * дає «grös»: умляут латинкою не пишеться, а підрядок вимагає точної
 * букви. Підкреслення в ILIKE — рівно одна будь-яка буква, і саме воно
 * покриває всі варіанти написання одразу.
 *
 * Список короткий навмисно: кожен рядок тут — визнання, що правило не
 * спрацювало, і множити такі визнання без потреби не варто.
 */
const ALIASES: Array<[RegExp, string]> = [[/^гр[ьеоё]{0,2}с[еє]р/i, "%gr_sser%"]];

/**
 * Прийменники й сполучники, яких у назві товару немає ніколи.
 *
 * Слова запиту зшиваються через AND, тож кожне з них — обовʼязкове. І
 * рівно тому «дріт ДЛЯ зварювання» не знаходило нічого: у 1С позиція
 * зветься «Дріт зварювальний оміднений ER70S-6», прийменника в ній
 * немає, і одне службове слово перекреслювало обидва змістовні.
 * Заміряно 08.09.2026: «дріт для зварювання» — 0 позицій, «дріт
 * зварювання» — пʼять, і серед них 650 шт вільного залишку.
 *
 * Список навмисно лише зі службових частин мови: усе, що може стояти в
 * назві товару, лишається обовʼязковим, інакше пошук почне знаходити
 * зайве замість того, щоб знаходити потрібне.
 */
const STOP = new Set([
  "для", "із", "зі", "на", "до", "по", "під", "над", "при", "про", "перед",
  "від", "за", "об", "без", "між", "через", "та", "чи", "або", "що", "як",
  "не", "ще", "теж", "цей", "ця", "це", "той", "які", "який", "яка", "яке",
]);

/**
 * Правова форма — службове слово лише наполовину.
 *
 * У 1С половина контрагентів заведена без неї, і «ФОП Левкович» не
 * знаходило «Левкович Олександр». Але друга половина форму МАЄ, і там
 * вона єдине, що відрізняє «ТОВ Схід» від однойменного ФОПа: викинути
 * її одразу означає проміняти точність на повноту в кожному запиті.
 *
 * Тому тут вона не в STOP: товарний пошук відкидає її завжди (у назвах
 * товарів таких скорочень немає), а клієнтський — лише другою спробою,
 * коли перша, точна, не знайшла нікого.
 */
const LEGAL = new Set(["фоп", "тов", "тзов", "пп", "спд", "прат", "пат", "кп", "чп", "ооо"]);

/**
 * Значущі слова запиту, як їх бачить пошук: без службових і без обрізання.
 *
 * Потрібні впорядкуванню: воно міряє, чи основа збіглася з ЦІЛИМ словом
 * назви, а для цього треба знати самі слова запиту. Без такої перевірки
 * «електроди» обрізалося до «електро» і піднімало шину для електропили
 * над самими електродами.
 */
export function queryWords(query: string, limitWords = 6): string[] {
  return words(query, limitWords, true);
}

function words(query: string, limitWords: number, dropLegal: boolean): string[] {
  const all = query
    .split(/\s+/)
    .map((w) => w.replace(/[%_]/g, "").trim())
    .filter((w) => w.length >= 2);

  // Питання з самих службових слів («що є на складі») сенсу не має, але
  // краще пошукати буквально, ніж повернути порожній набір шаблонів.
  const meaningful = all.filter((w) => {
    const lower = w.toLowerCase();
    return !STOP.has(lower) && !(dropLegal && LEGAL.has(lower));
  });
  const list = (meaningful.length ? meaningful : all).slice(0, limitWords);
  return list.length ? list : [query];
}
