/**
 * Компіляція правила.
 *
 * У JavaScript `\w` і `\b` кирилиці не знають: `\w` — це [A-Za-z0-9_], тож
 * `свердл\w*` не бачить «свердла», а `\bніж\b` не спрацьовує ніколи —
 * між пробілом і «н» межі слова немає, бо обидва символи для рушія
 * «не-літери». Через це перша версія правил мовчки не ловила половину назв.
 *
 * Тому межі слова пишемо явно: « — початок слова, » — кінець, ~ — будь-яке
 * закінчення. «ніж» читається, а працює однаково для кирилиці й латиниці.
 */
function rx(src: string): RegExp {
  return new RegExp(
    src
      .replace(/«/g, "(?<![\\p{L}\\p{N}])")
      .replace(/»/g, "(?![\\p{L}\\p{N}])")
      .replace(/~/g, "[\\p{L}]*"),
    "iu"
  );
}

