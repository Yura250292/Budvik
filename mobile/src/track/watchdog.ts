/**
 * Періодична перевірка, що трек живий.
 *
 * Служба переднього плану стійка, але не безсмертна: виробничі оболонки її
 * прибивають, а після перезавантаження планшета система не відновлює доставку
 * координат сама. WorkManager же переживає і перезавантаження, і вбивство
 * процесу — тому саме він тут за сторожа.
 *
 * Це не заміна службі, а страховка: він прокидається не частіше ніж раз на 15
 * хвилин (жорстке обмеження Android), тож у найгіршому випадку втрачається
 * чверть години треку, а не день.
 */

import * as BackgroundTask from "expo-background-task";
import * as Notifications from "expo-notifications";
import * as TaskManager from "expo-task-manager";
import {
  hasOfflineGuard,
  scheduleOfflineGuard,
  cancelOfflineGuard,
  scheduleExactGuard,
  cancelExactGuard,
} from "@modules/track-guard";
import { WAKE_TASK, WATCHDOG_TASK } from "./task-name";
import { logEvent } from "./db";
import {
  getLastFixAt,
  getMode,
  getRole,
  isShiftOpen,
  setLastError,
  setWatchdogRun,
  setWatchdogStatus,
} from "./state";
import { heartbeat, maybeFlush } from "./uploader";
import { flushPendingShift } from "./pending-shift";
import { flushPendingVisits } from "./pending-visits";
import { ensureRecording, isTracking, startTracking, warnRecordingDown } from "./controller";
import { ensureFreshFixes } from "./health";
import { checkJsUpdate } from "@/lib/self-update";

/**
 * Скільки хвилин без жодної координати означають, що трек стоїть.
 *
 * Точка пишеться щонайрідше раз на хвилину навіть на місці, тож двадцять
 * хвилин тиші при відкритій зміні — це вже не «не встиг», а поламка. Межа
 * навмисно більша за крок сторожа (чверть години): інакше перше ж пробудження
 * після відкриття зміни лякало б людину до першого фікса.
 */
const FIX_STALE_MS = 20 * 60_000;

export async function runWatchdog(): Promise<void> {
  /**
   * Найперше — відмітка «я прокинувся».
   *
   * Ставиться ДО будь-якої роботи навмисно: якщо сторож упаде на першому ж
   * кроці, знати, що він взагалі запускався, важливіше за причину падіння.
   * Саме цього числа бракувало, щоб відрізнити «сторож спить» від «застосунок
   * мертвий» — з сервера обидва стани виглядали однаково.
   */
  await setWatchdogRun(Date.now()).catch(() => {});

  /**
   * Запис — ПЕРШИМ, поперед усієї мережевої роботи. Порядок тут не про
   * важливість, а про час.
   *
   * Коли сторожа підняв будильник, ми стоїмо у вікні, де Android дозволяє
   * запустити службу переднього плану, — і вікно це коротке. Флаш буфера,
   * відкладена зміна й пульс — усе це походи в мережу, які в селі тривають
   * десятки секунд і легко з'їдають вікно цілком. Тобто єдина мить, коли трек
   * можна полагодити без людини, витрачалася на відправку даних, а лікування
   * приходило вже поза дозволом і падало з «Couldn't start the foreground».
   *
   * Дані від переставляння нічого не втрачають: вони лежать у SQLite і
   * дочекаються наступного рядка. Мертвий трек не дочекається нічого.
   */
  await ensureFreshFixes().catch(() => {});

  /**
   * Відкладена зміна — найперша з мережевого: поки вона не пройшла, сервер не
   * знає, що людина на маршруті, і трек лягає в день без зміни.
   */
  await flushPendingShift().catch(() => {});
  // Відмітки візитів — теж наперед: із них складається день і каса.
  await flushPendingVisits().catch(() => {});
  // Далі віддати те, що назбиралося: буфер важливіший за все інше.
  await maybeFlush().catch(() => {});
  await heartbeat().catch(() => {});

  const [role, shiftOpen, tracking, mode] = await Promise.all([
    getRole(),
    isShiftOpen(),
    isTracking(),
    getMode(),
  ]);

  /**
   * Прапорець «пишемо» бреше — і саме на цьому все й трималося 07.09.
   *
   * `hasStartedLocationUpdatesAsync` читає збережену позначку, а не живу
   * службу. Після того, як Android прибив процес і підняв його у фоні,
   * позначка лишається піднятою, `ensureRecording` бачить «усе гаразд» і
   * нічого не робить, а фіксів немає. З сервера це виглядало бездоганно:
   * mode SHIFT, tracking true, subscribed true, дозвіл ALWAYS, проба
   * приймача ±5 м — і НУЛЬ точок за чотири години у чотирьох торгових.
   *
   * Підняти службу з фону Android не дасть, тож єдиний, хто може це
   * полагодити, — людина з відкритим застосунком. Значить їй треба сказати,
   * і сказати незалежно від прапорців: питаємо не «чи ми пишемо», а «чи
   * прийшла хоч одна координата».
   */
  if (shiftOpen) {
    const fixAt = await getLastFixAt().catch(() => 0);
    if (!fixAt || Date.now() - fixAt > FIX_STALE_MS) {
      await warnRecordingDown().catch(() => {});
    }
  }

  // Водій пише трек від входу, торговий — поки відкрита зміна (див. controller.ts).
  const shouldTrack = shiftOpen || role === "DRIVER";
  if (shouldTrack && !tracking) {
    // Саме правило живе в controller.ensureRecording — його ж кличе перевірка
    // на передньому плані. Дві копії розійшлися б непомітно.
    await ensureRecording();
    return;
  }

  /**
   * Дорога додому теж не має обриватися.
   *
   * Режим «після зміни» вмикає геозона, і якщо систему після цього щось
   * прибило, відновити запис немає кому: геозона вже спрацювала й знята.
   * Тому сторож піднімає і його — інакше поїздка після роботи обірвалася б на
   * першому ж прибитті процесу, і саме та відповідь, заради якої все це
   * робиться, загубилася б.
   */
  if (!shouldTrack && mode === "AFTER_SHIFT" && !tracking) {
    await startTracking("AFTER_SHIFT");
  }

  /**
   * Оновлення JS — останнім, бо це не робота треку, а її майбутнє.
   *
   * `checkAutomatically: "ON_LOAD"` питає про оновлення ЛИШЕ на запуску, а
   * планшет у машині не вимикають тижнями: виправлення, опубліковане вранці,
   * могло не дійти взагалі. Саме так 01.09 троє їздили без треку на збірці, у
   * якій буфер висів, — хоч виправлення лежало опубліковане три доби.
   *
   * Тут лише завантаження. Перезапуск робить людина смугою вгорі екрана
   * (UpdateBar): рестарт посеред візиту стер би незбережене, а посеред зміни
   * зупинив би службу — ціна помилки вища за чверть години очікування.
   */
  await checkJsUpdate().catch(() => {});
}

export async function registerWatchdog(): Promise<void> {
  const status = await BackgroundTask.getStatusAsync().catch(() => null);

  /**
   * Стан фонових завдань їде в пульс — і це не діагностична дрібниця.
   *
   * `Restricted` означає, що система не даватиме сторожеві прокидатися
   * взагалі: планшет потрапив в обмежений режим економії, і жодна наша
   * страховка вже не працює. Досі ми в цьому випадку мовчки виходили, і
   * планшет ставав невидимим для всіх перевірок — без єдиного сліду.
   */
  await setWatchdogStatus(
    status === BackgroundTask.BackgroundTaskStatus.Restricted
      ? "RESTRICTED"
      : status === BackgroundTask.BackgroundTaskStatus.Available
        ? "AVAILABLE"
        : "UNKNOWN"
  ).catch(() => {});

  if (status === BackgroundTask.BackgroundTaskStatus.Restricted) {
    await setLastError(
      "Система заборонила фонові завдання — сторож треку не працюватиме"
    ).catch(() => {});
    return;
  }

  await BackgroundTask.registerTaskAsync(WATCHDOG_TASK, {
    // 15 хвилин — мінімум, який дозволяє Android; менше просто ігнорується.
    minimumInterval: 15,
  }).catch(() => {});

  /**
   * Другий будильник — без вимоги мережі.
   *
   * Реєстрація вище ставить роботу з обмеженням `NetworkType.CONNECTED`, яке
   * expo-background-task зашиває намертво. Тобто в селі без зв'язку вона не
   * спрацьовує — саме там, де служба треку й гине. Власний нативний модуль
   * ставить те саме завдання ще раз, але без жодних обмежень.
   *
   * Два запуски замість одного нешкідливі: тіло завдання ідемпотентне.
   */
  scheduleOfflineGuard(15);

  /**
   * ТРЕТІЙ сторож — на будильнику, і саме він тепер головний.
   *
   * Два попередні — це WorkManager, тобто прохання до системи. Оболонки
   * Lenovo, на яких стоїть усе поле, це прохання відкладають на години: 08.09
   * планшет доповів рівно ОДНЕ пробудження сторожа за чотири години відкритої
   * зміни, і трек увесь цей час стояв. Будильник — зобов'язання системи: він
   * пробиває Doze і не залежить від економії енергії.
   *
   * Друга причина, важливіша за першу. Android 12+ забороняє піднімати службу
   * переднього плану з фону — саме через це вбитий запис не оживає сам, і
   * єдиною порадою лишалося «відкрийте застосунок». Спрацювання ТОЧНОГО
   * будильника входить у перелік винятків: це та коротка мить, коли запис
   * можна підняти без людини.
   *
   * Ставиться поруч, а не замість: три незалежні приводи прокинутись кращі за
   * один, тіло завдання ідемпотентне, і зайве пробудження нічого не коштує.
   *
   * У збірках до 1.6.1 нативної частини немає — виклик тихо поверне false, і
   * в полі лишиться рівно те, що було.
   */
  scheduleExactGuard(15);

  /**
   * ЧЕТВЕРТИЙ сторож — і єдиний, що не залежить від нашого процесу взагалі.
   *
   * Три попередні живуть усередині планшета: якщо система прибила процес і не
   * дає його підняти, вони мовчать разом із ним. Цей приходить ЗЗОВНІ. Сервер
   * бачить, що зміна відкрита, а точок немає, і шле сповіщення — тим самим
   * каналом Google, яким приходять повідомлення месенджерів. Він один на весь
   * пристрій і живе незалежно від нас, тому Telegram і дзвонить у застосунок,
   * який не відкривали тиждень.
   *
   * Реєстрація обов'язкова: без неї сповіщення просто покаже текст, а фонове
   * завдання не запуститься — тобто найцінніше (тихе підняття запису) не
   * станеться, і лишиться та сама просьба до людини.
   */
  const registered = await Notifications.registerTaskAsync(WAKE_TASK)
    .then(() => true)
    .catch(async (e) => {
      await setLastError(
        `Пробудження сповіщенням не зареєстровано: ${e instanceof Error ? e.message : String(e)}`
      ).catch(() => {});
      return false;
    });

  /**
   * Чи справді завдання є в списку системи — питаємо, а не віримо.
   *
   * 08.09 перевірка на живому планшеті тричі дала той самий результат: Expo
   * звітує «доставлено», застосунок має найсвіжіший код і зареєстровану
   * адресу, а події немає. Між «ми викликали реєстрацію» і «система про неї
   * знає» лежить проміжок, у який ми досі не заглядали — і рівно там уже
   * ховалися дві поламки за сьогодні.
   *
   * `getRegisteredTasksAsync` віддає те, що система вважає зареєстрованим
   * НАСПРАВДІ. Рядок їде в журнал, тобто відповідь буде видно по всіх
   * планшетах, а не лише на тому, який тримають у руках.
   */
  const names = await TaskManager.getRegisteredTasksAsync()
    .then((list) => list.map((t) => t.taskName).join(", "))
    .catch((e) => `не вдалося спитати: ${e instanceof Error ? e.message : String(e)}`);
  void logEvent("wake", `реєстрація=${registered} · у системі: ${names}`.slice(0, 180));
}

export async function unregisterWatchdog(): Promise<void> {
  await BackgroundTask.unregisterTaskAsync(WATCHDOG_TASK).catch(() => {});
  await Notifications.unregisterTaskAsync(WAKE_TASK).catch(() => {});
  cancelOfflineGuard();
  cancelExactGuard();
}

