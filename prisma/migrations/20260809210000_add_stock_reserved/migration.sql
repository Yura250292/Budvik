-- Резерв у залишках по складах.
--
-- Навіщо: quantity — фізичний залишок із регістру 1С ТоварыНаСкладах. Якщо на
-- складі 5 викруток і 3 зарезервовано під замовлення клієнта, там і далі 5.
-- Менеджер у 1С при цьому бачить 2. Без окремого поля резерву сайт показував
-- би торговим товар, уже обіцяний іншому клієнту, і другий торговий продав би
-- те саме вдруге.
--
-- available зберігаємо, а не рахуємо на льоту, щоб по ньому можна було
-- сортувати й фільтрувати без обчислень у кожному запиті.
--
-- Additive-only: обидва поля з DEFAULT 0, наявні рядки лишаються валідними.
ALTER TABLE "LocationStock" ADD COLUMN "reserved" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "LocationStock" ADD COLUMN "available" INTEGER NOT NULL DEFAULT 0;

-- До першої синхронізації резервів вільний залишок дорівнює фізичному.
-- Інакше available лишився б нулем і сайт показав би, що товару немає взагалі.
UPDATE "LocationStock" SET "available" = "quantity";
