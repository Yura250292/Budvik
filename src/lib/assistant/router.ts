const ANAPHORA = /(^|\s)(він|його|йому|ним|нього|вона|її|їй|цей|цього|цьому|там|туди|той|тому клієнт|ще раз|а що|а як|а скільки|а коли)(\s|[?.,!]|$)/i;

/**
 * Те, що виглядає як назва, але нею не є.
 *
 * «Що запропонувати цьому клієнту» — хвіст «цьому клієнту» формально
 * підходить під ім'я, і пошук за ним не знайде нічого; питання ж мало на
 * увазі клієнта, чию картку торговий щойно відкрив.
 *
 * Тут же слова про САМУ картку товару: «скажи артикул», «яка ціна»,
 * «покажи залишок». Це уточнення до попередньої відповіді, а не новий
 * пошук. Без них «Скажи артикул» шукало товар зі словом «артикул»,
 * знаходило по короткій основі «арти» контрагентів Мартинюків і
 * показувало людей у таблиці товарів.
 */
const NOT_A_NAME =
  // Закінчення виписані як [а-яіїєґ], а не \w: у JavaScript \w — це ASCII,
  // і «клієнт\w*» не збігається з «клієнту» взагалі.
  /^((цьому|цього|цей|тому|того|цим|нашому|нашого|своєму)\s+)?(клієнт[а-яіїєґ]*|боржник[а-яіїєґ]*|магазин[а-яіїєґ]*|точ[кц][а-яіїєґ]*|контрагент[а-яіїєґ]*|йому|його|їм|когось|кого|всіх|усіх|них|мої|моїх|сьогодні|завтра|тут|це|щось|грош[а-яіїєґ]*|борг[а-яіїєґ]*|оплат[а-яіїєґ]*|замовлен[а-яіїєґ]*|продаж[а-яіїєґ]*|повернен[а-яіїєґ]*|точ[а-яіїєґ]*|нагадуван[а-яіїєґ]*|маршрут[а-яіїєґ]*|план[а-яіїєґ]*|артикул[а-яіїєґ]*|код[и]?|склад[а-яіїєґ]*|наявніст[а-яіїєґ]*|штрихкод[а-яіїєґ]*|назв[а-яіїєґ]*|ціну|ціни|залишок|залишки|наявність)$|^за\s+(тиждень|тижн[а-яіїєґ]*|місяц[ья]?|день|дні|днів|\d+\s*дн[а-яіїєґ]*|квартал|сьогодні|вчора|учора|позавчора|\d{1,2}[.\/]\d{1,2}([.\/]\d{2,4})?|\d{1,2}\s+(січня|лютого|березня|квітня|травня|червня|липня|серпня|вересня|жовтня|листопада|грудня)|(цей|минулий|попередній)\s+(тиждень|місяць))$|^(цього|минулого|попереднього)\s+(тижня|місяця)$|^(вчора|учора|сьогодні|позавчора)$/i;

/**
 * Хвіст, що починається зі сполучника чи питального слова, — це друга
 * половина питання, а не ім'я: «скільки винен і що памʼятаємо».
 */
const TAIL_NOT_NAME = /^(і|й|та|а|чи|що|як|коли|скільки|де|чому|навіщо|який|яка|яке)(\s|$)/i;

/**
 * «Знайди клієнта Химич» — довідник названо прямо, гадати не треба.
 *
 * Шаблон спільний для всіх ролей навмисно. Дієслова «знайди/пошукай»
 * ловить іще й PRODUCT_ASK, тож варто цій гілці бути лише в торгового —
 * і водій зі складовщиком отримували пошук ТОВАРУ на прізвище людини.
 *
 * ОДНИНА обовʼязкова: «покажи клієнтІВ у Сокільниках» — це список по
 * місту, і множина тут єдина ознака, яка відрізняє його від картки.
 */
const FIND_CLIENT = /(знайди|покажи|пошукай|шукай|найди)\s+(мені\s+)?(клієнта|клієнту|контрагента|магазин)\s+/i;

/**
 * Як питають про товар і залишок.
 *
 * Список довгий навмисно. «Скільки ще піни», «залишки піни», «що по
 * піні» — це те саме питання, і кожне непізнане формулювання коштує
 * дев'ять тисяч токенів і десять секунд там, де код відповідає за
 * секунду й безкоштовно.
 */
const PRODUCT_ASK =
  /(які\s+(в\s+нас\s+)?є\s+|що\s+є\s+(з\s+)?|чи\s+є\s+(в\s+наявності\s+)?|скільки\s+(ще\s+)?(на\s+складі|залишилось|лишилось|є)\s*|який\s+залишок\s*|(скажи|покажи|глянь|подивись|подивися|пошукай|пошукати|знайди|найди|шукай)\s+(мені\s+)?(який\s+)?((залиш[а-яіїєґ]*|наявність|ціну)\s+)?((по|на)\s+)?|залиш[а-яіїєґ]*\s+(по\s+)?|є\s+на\s+складі\s*|що\s+(там\s+)?по\s+|яка\s+ціна\s+(на\s+)?|почім\s+|скільки\s+кошту[а-яіїєґ]*\s+|скільки\s+ще\s+|скільки\s+|^(чи\s+)?є\s+)/i;

/**
 * Те саме питання з товаром ПОСЕРЕДИНІ: «скільки піни залишилось».
 *
 * PRODUCT_ASK ловить лише хвіст після ключових слів, а тут назва стоїть
 * між «скільки» і «залишилось» — і найчастіше питають саме так. Без цієї
 * гілки просте питання про залишок ішло в модель за дев'ять тисяч токенів.
 */
const PRODUCT_MIDDLE =
  /(?:скільки|чи)\s+(?:ще\s+|є\s+)?(.{2,40}?)\s+(?:ще\s+)?(?:залишилось|лишилось|залишилося|є\s+в\s+наявності|є\s+на\s+складі|на\s+складі|в\s+наявності)/i;

/**
 * Назва спереду, питання про склад позаду: «маски total на складі».
 *
 * PRODUCT_ASK шукає ключове слово ПЕРЕД назвою, PRODUCT_MIDDLE — назву між
 * «скільки» і «залишилось». Це третя форма, і найчастіша в живій мові:
 * людина просто називає товар і питає, чи він є.
 */
const PRODUCT_LEADING =
  /^(.{3,40}?)\s+(на\s+складі|в\s+наявності|у\s+наявності|на\s+залишку|в\s+залишку|є\s+в\s+наявності)\s*\??$/i;

const clean = (raw: string) =>
  raw
    .replace(/[«»"'’`]/g, "")
    .replace(/[?!.,;:]+\s*$/g, "")
    .replace(/\s+/g, " ")
    .trim();

/**
 * Питальні слова, що прилипають до назви з обох боків.
 *
 * «Драбина Dnipro M яка є на складі» — шаблон бере все до «на складі», і
 * в пошук летить «Драбина Dnipro M яка є». Каталог такого не знає, і
 * відповідь виходить «нічого не знайшли» на товар, який лежить на складі.
 * Саме «яка є» посередині фрази й ламало запит.
 */
function stripAsk(value: string): string {
  return value
    .replace(/^(яка|які|який|яке|що|шо|чи)\s+(є\s+|в\s+наявності\s+)?/i, "")
    .replace(/(\s+(яка|які|який|яке|що|шо|є|наявні|наявність|залишок|залишки))+\s*$/i, "")
    .trim();
}

/** Хвіст питання після ключового слова — ім'я клієнта або назва товару. */
function subjectAfter(text: string, re: RegExp): string | null {
  const match = re.exec(text);
  if (!match) return null;

  const rawTail = clean(text.slice(match.index + match[0].length))
    .replace(/^(до|в|у|про|для|клієнта|клієнту|магазину|магазин)\s+/i, "")
    // «скільки в нас піни на складі» — питальні хвости не є назвою.
    .replace(/^(нас|мене|тебе|вас)\s+/i, "")
    /*
     * Питання перед назвою: «пошукай НА СКЛАДІ який є дріт», «подивись
     * СКІЛЬКИ Є кругів 125». Шаблон зупиняється на першому дієслові, а
     * решта питання лишається в хвості — і той або йшов у пошук цілком
     * («на складі дроту»), або відкидався як «починається з питального
     * слова».
     *
     * Група повторювана, бо звороти чіпляються один за одного в обидва
     * боки: «скільки є на складі дроту» і «на складі скільки є дроту» —
     * те саме питання, і один прохід зніме лише половину.
     */
    .replace(
      /^((скільки\s+(ще\s+)?(є|залишилось|лишилось|залишилося)|на\s+складі|на\s+склад|складі|складу|в\s+наявності|у\s+наявності|по\s+складу)\s+)+/i,
      ""
    )
    // Хвіст «…залишилось на складі» — це питання, а не частина назви.
    /*
     * Хвіст про склад — це питання, а не частина назви. Група повторювана
     * навмисно: «на залишку складу» знімається двома кроками, спершу
     * «складу», потім «на залишку».
     */
    .replace(
      /(\s+(на\s+складі|на\s+склад|в\s+наявності|у\s+наявності|в\s+залишку|на\s+залишку|по\s+складу|складу|складі|залишилось|залишилося|лишилось|лишилося|лишилися|є))+\s*$/i,
      ""
    )
    .replace(/\s+(і|та)\s+(чи|що|як|скільки)(\s|$).*$/i, "");

  const tail = stripAsk(rawTail);

  /**
   * «Скільки я продав за тиждень» — це не назва товару.
   *
   * Широке «скільки …» ловить і питання про себе. У торгового такі
   * питання перехоплюються раніше власними шаблонами, а от у водія
   * шаблонів продажів немає взагалі — і хвіст «я продав за тиждень»
   * ішов у пошук товару.
   */
  if (/^(я|мені|мій|моя|моїх|мого|нам)\s/i.test(tail)) return null;

  if (tail.length < 3 || NOT_A_NAME.test(tail) || TAIL_NOT_NAME.test(tail)) return null;
  if (!/[а-яіїєґa-z]/i.test(tail)) return null;
  // Довгий хвіст — це вже не назва, а окреме питання.
  return tail.length > 60 ? null : tail;
}

/** Назва, затиснута між двома половинами питання. */
function subjectBetween(text: string, re: RegExp): string | null {
  const match = re.exec(text);
  if (!match?.[1]) return null;

  const name = stripAsk(clean(match[1]).replace(/^(ще|там|у\s+нас|в\s+нас|нам|мені)\s+/i, ""));
  if (name.length < 3 || NOT_A_NAME.test(name) || TAIL_NOT_NAME.test(name)) return null;
  if (!/[а-яіїєґa-z]/i.test(name)) return null;
  return name;
}

/**
 * Хвіст, який виглядає як назва товару, але говорить про звіт.
 *
 * «Покажи вчорашній оборот Кулика з накладними» після голого «покажи »
 * лишало хвіст із пʼяти слів, і той ішов у пошук товару: 0 позицій, 0
 * клієнтів, упевнене «не знайшли» — і модель, яка це питання вміє, не
 * отримувала його ніколи. Словник тут — аналітика й період; закінчення
 * підібрані так, щоб «накладка», «планка», «змінний» і «трековий» лишалися
 * товарами.
 */
const NOT_A_PRODUCT =
  /(^|\s)(оборот[а-яіїєґ]*|продаж[а-яіїєґ]*|накладн[аіуо][а-яіїєґ]*|документ[а-яіїєґ]*|реалізаці[а-яіїєґ]*|відвантаж[а-яіїєґ]*|борг[а-яіїєґ]*|дебіторк[а-яіїєґ]*|прострочк[а-яіїєґ]*|оплат[а-яіїєґ]*|зібра[а-яіїєґ]*|збірк[а-яіїєґ]*|змін[аиу]?|пробіг[а-яіїєґ]*|маршрут[а-яіїєґ]*|зарплат[а-яіїєґ]*|виручк[а-яіїєґ]*|замовленн?[а-яіїєґ]*|візит[а-яіїєґ]*|трек[уи]?|клієнт[а-яіїєґ]*|торгов(ий|ого|ому|им|і|их|ими|а|ої|ій|ою)|воді[йїя][а-яіїєґ]*|складовщик[а-яіїєґ]*|план(у|ом|и|ів)?|прогноз[а-яіїєґ]*|порівня[а-яіїєґ]*|звіт[а-яіїєґ]*|вчора|учора|позавчора|сьогодні|тиждень|тижн[а-яіїєґ]*|місяц[ьяі]?)(\s|$)/i;

/**
 * Назва товару з питання — або null, якщо це не про товар.
 *
 * Три форми питання (ключове слово перед назвою, назва посередині, назва
 * спереду) і один запобіжник на всіх: хвіст зі словами про звіт або довший
 * за шість слів — не назва. Шість, а не менше: «кругів відрізних по металу
 * 125 Ataman» — справжній запит, і справжній запобіжник тут словник.
 */
function productSubject(text: string): string | null {
  const query =
    subjectAfter(text, PRODUCT_ASK) ??
    subjectBetween(text, PRODUCT_MIDDLE) ??
    subjectBetween(text, PRODUCT_LEADING);
  if (!query || NOT_A_PRODUCT.test(query)) return null;
  return query.split(/\s+/).length > 6 ? null : query;
}

