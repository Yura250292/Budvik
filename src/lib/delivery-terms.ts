/**
 * Умови доставки вітрини — одне джерело для сторінки «Оплата і доставка»,
 * оформлення, картки товару, JSON-LD і фіда Merchant Center.
 *
 * Google звіряє ціну доставки в розмітці й фіді з тим, що покупець бачить на
 * сайті, тож цифри, вписані текстом у п'ять місць, розійшлися б при першій же
 * зміні тарифу.
 */
export const DELIVERY_TERMS = {
  /** Доставка Новою поштою по Україні, грн. */
  fee: 120,
  /** Від цієї суми замовлення доставка безкоштовна, грн. */
  freeFrom: 2000,
  /** Зібрати й відправити, днів. */
  handlingDays: { min: 0, max: 1 },
  /** Дорога Новою поштою, днів. */
  transitDays: { min: 1, max: 3 },
  /**
   * Понад цю вагу Нова пошта рахує за кілограм, і таку доставку менеджер
   * рахує окремо. Автоматично не відсіюється: вага є лише в кількох десятків
   * товарів, тому виняток живе текстом на сторінці доставки.
   */
  heavyKg: 30,
} as const;

/**
 * З цього дня діють умови вище. Ціна доставки в замовленні не зберігається,
 * тож сторінка замовлення рахує її за правилом — а раніше доставку в
 * замовлення не рахували зовсім, і старим замовленням рядок не потрібен.
 * Зміниться тариф — старі замовлення покажуть новий, доки ціну не почнуть
 * зберігати в Order.
 */
export const DELIVERY_TERMS_SINCE = new Date("2026-09-15T00:00:00+03:00");

/** Скільки коштує доставка замовлення на цю суму (самовивіз — завжди 0). */
export function deliveryFee(orderTotal: number): number {
  return orderTotal >= DELIVERY_TERMS.freeFrom ? 0 : DELIVERY_TERMS.fee;
}

/** Повний строк для людей: від відправки до відділення, «1–4 дні». */
export const DELIVERY_DAYS_LABEL = `${
  DELIVERY_TERMS.handlingDays.min + DELIVERY_TERMS.transitDays.min
}–${DELIVERY_TERMS.handlingDays.max + DELIVERY_TERMS.transitDays.max} дні`;
