/**
 * Кольорова система аналітики.
 *
 * До цього все було жовтим: #FFD600 — єдиний брендовий акцент, тож ним
 * малювалися і графіки, і прогрес, і активні вкладки. Через це на дашборді
 * не було жодної підказки, що є що.
 *
 * Тепер у кольору три різні роботи, і вони не змішуються:
 *
 *   1. БРЕНД (#FFD600) — тільки органи керування: активна вкладка, головна
 *      кнопка. У даних не використовується взагалі.
 *   2. СТАТУС — стан показника: виконано / близько / відстає / проблема.
 *      Завжди супроводжується числом або підписом, ніколи не сам колір.
 *   3. КАТЕГОРІЯ — тотожність ряду (бренд товару, торговий). Вісім хюїв у
 *      фіксованому порядку; дев'ятий ряд не отримує новий колір, а йде в
 *      «Інші».
 *
 * Чому брендовий жовтий не годиться для даних: у нього світлість 0.885 при
 * допустимій межі 0.77 і контраст 1.35:1 на білому при потрібних 3:1 —
 * тонка смужка ним просто зникає. Перевірено валідатором, а не на око.
 *
 * Палітра нижче пройшла всі перевірки на білому фоні картки:
 * найгірша пара за дальтонізмом ΔE 9.1 (норма ≥8), для звичайного зору
 * ΔE 19.6 (норма ≥15). Три кольори (aqua, yellow, magenta) мають контраст
 * нижче 3:1 — тому біля них ЗАВЖДИ є підпис або число, ніколи не сам колір.
 */

/** Вісім хюїв у фіксованому порядку. Порядок і є механізмом CVD-безпеки — не міняти. */
export const CATEGORICAL = [
  "#2a78d6", // 1 синій
  "#eb6834", // 2 помаранчевий
  "#1baf7a", // 3 бірюзовий
  "#eda100", // 4 жовтий (темніший за брендовий — той не проходить контраст)
  "#e87ba4", // 5 маджента
  "#008300", // 6 зелений
  "#4a3aa7", // 7 фіолетовий
  "#e34948", // 8 червоний
] as const;

/** Для форм, де будь-які дві точки можуть опинитися поруч, безпечні лише 3 слоти. */
export const CATEGORICAL_SAFE_LIMIT = 3;

/** Колір для рядів без власного (наприклад, «Без бренду», «Інші»). */
export const NEUTRAL = "#9E9E9E";

/**
 * Колір ряду за індексом. Ніколи не циклиться: індекс за межами палітри
 * отримує нейтральний сірий, щоб два різні бренди не ділили один колір.
 */
export function categoricalColor(index: number, fallback?: string | null): string {
  if (fallback) return fallback;
  return index >= 0 && index < CATEGORICAL.length ? CATEGORICAL[index] : NEUTRAL;
}

/** Стани показника. Значення різні за світлістю, а не лише за хюєм. */
export const STATUS = {
  good: { fg: "#047857", bg: "#ECFDF5", border: "#A7F3D0", mark: "#059669" },
  warn: { fg: "#B45309", bg: "#FFFBEB", border: "#FDE68A", mark: "#D97706" },
  bad: { fg: "#B91C1C", bg: "#FEF2F2", border: "#FECACA", mark: "#DC2626" },
  neutral: { fg: "#475569", bg: "#F8FAFC", border: "#E2E8F0", mark: "#64748B" },
  info: { fg: "#1D4ED8", bg: "#EFF6FF", border: "#BFDBFE", mark: "#2563EB" },
} as const;

export type StatusKey = keyof typeof STATUS;

/**
 * Стан виконання плану.
 *
 * Пороги: 100% — виконано, 85% — ще досяжно до кінця місяця, нижче 60% —
 * проблема, яку не витягнути без втручання.
 */
export function attainmentStatus(percent: number, hasTarget = true): StatusKey {
  if (!hasTarget) return "neutral";
  if (percent >= 100) return "good";
  if (percent >= 85) return "info";
  if (percent >= 60) return "warn";
  return "bad";
}

/**
 * Стан «км на точку»: скільки торговий накатує заради одного візиту.
 * Порівнюється з середнім по команді, бо абсолютна норма залежить від
 * напрямку — у міського й сільського вона різна.
 */
export function efficiencyStatus(value: number, teamAverage: number): StatusKey {
  if (teamAverage <= 0 || value <= 0) return "neutral";
  const ratio = value / teamAverage;
  if (ratio <= 0.85) return "good";
  if (ratio <= 1.2) return "neutral";
  if (ratio <= 1.6) return "warn";
  return "bad";
}

/**
 * Стани клієнта на карті.
 *
 * Порядок хюїв узятий з CATEGORICAL, але не за індексом: тут кольори мають
 * читатися як шкала «добре → погано» (зелений → жовтий → помаранчевий →
 * червоний), тому вони виписані явно. Синій для нових і фіолетовий для
 * точок розпрацювання свідомо випадають зі шкали — це не стадії згасання,
 * а окремі категорії.
 *
 * Колір ніколи не єдиний сигнал: у легенді поруч завжди підпис і число, а
 * точки розпрацювання ще й квадратні — на випадок дальтонізму й друку.
 */
export const CLIENT_STATE = {
  ACTIVE: { label: "Стабільні", color: "#008300", hint: "беруть у своєму звичному ритмі" },
  NEW: { label: "Нові", color: "#2a78d6", hint: "перший документ у межах періоду" },
  SLIPPING: { label: "Рідко беруть", color: "#eda100", hint: "пауза довша за власний ритм клієнта" },
  DORMANT: { label: "Дуже рідко", color: "#eb6834", hint: "60+ днів без документа" },
  LOST: { label: "Втрачені", color: "#e34948", hint: "90+ днів без документа" },
  PROSPECT: { label: "Для розпрацювання", color: "#4a3aa7", hint: "нанесені вручну майбутні клієнти" },
} as const;

export type ClientStateKey = keyof typeof CLIENT_STATE;

/** Стан поїздки за її статусом у боті. */
export function tripStatus(status: string): StatusKey {
  if (status === "OPEN") return "info";
  if (status === "ABANDONED") return "bad";
  return "neutral";
}
