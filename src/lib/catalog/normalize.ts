/**
 * Підготовка пошукового запиту до українських реалій.
 *
 * Пошук по базі — це `ILIKE '%терм%'`, тобто підрядок. Він знаходить «валик» у
 * «валику» і «валиках», але не навпаки: людина пише «валики», а в назві товару
 * стоїть «Валик малярний» — і видача порожня. Тому закінчення зрізаємо саме в
 * запиті, а не в базі: скорочений терм лишається підрядком усіх форм слова.
 *
 * Друга біда — розкладка. «makita», «dnipro», «diamant» люди набирають і
 * латиницею, і кирилицею, а в назвах з 1С трапляється і те, і те.
 */

/**
 * Закінчення від найдовшого до найкоротшого — інакше «ами» зрізалося б як «и»
 * і «дисками» перетворилось би на «дискам» замість «диск».
 */
const ENDINGS = [
  "ами", "ями", "ові", "еві", "ів", "їв", "ам", "ям", "ах", "ях",
  "ою", "ею", "ій", "ий", "ий", "ки", "ку", "ці", "ем", "ом",
  "а", "и", "і", "у", "ю", "е", "о", "я", "й",
];

/** Коротше за це слово вже не несе змісту: «дриль» не можна різати до «дри». */
const MIN_STEM = 4;

/**
 * Зрізає типове закінчення. Слова коротші за 5 літер лишає як є —
 * там ризик зіпсувати слово вищий за виграш.
 */
export function stemTerm(term: string): string {
  if (term.length < 5) return term;
  for (const end of ENDINGS) {
    if (term.length - end.length >= MIN_STEM && term.endsWith(end)) {
      return term.slice(0, -end.length);
    }
  }
  return term;
}

// Диграфи першими: інакше «sh» розпалося б на «с»+«х».
const LAT_TO_CYR: [string, string][] = [
  ["shch", "щ"], ["sch", "щ"], ["zh", "ж"], ["kh", "х"], ["ts", "ц"],
  ["ch", "ч"], ["sh", "ш"], ["ya", "я"], ["yu", "ю"], ["ye", "є"],
  ["yi", "ї"], ["ie", "є"], ["a", "а"], ["b", "б"], ["v", "в"],
  ["h", "г"], ["g", "г"], ["d", "д"], ["e", "е"], ["z", "з"],
  ["y", "и"], ["i", "і"], ["j", "й"], ["k", "к"], ["l", "л"],
  ["m", "м"], ["n", "н"], ["o", "о"], ["p", "п"], ["r", "р"],
  ["s", "с"], ["t", "т"], ["u", "у"], ["f", "ф"], ["c", "ц"],
  ["w", "в"], ["x", "кс"], ["q", "к"],
];

const CYR_TO_LAT: [string, string][] = [
  ["щ", "shch"], ["ж", "zh"], ["х", "kh"], ["ц", "ts"], ["ч", "ch"],
  ["ш", "sh"], ["я", "ya"], ["ю", "yu"], ["є", "ye"], ["ї", "yi"],
  ["а", "a"], ["б", "b"], ["в", "v"], ["г", "h"], ["ґ", "g"],
  ["д", "d"], ["е", "e"], ["з", "z"], ["и", "y"], ["і", "i"],
  ["й", "j"], ["к", "k"], ["л", "l"], ["м", "m"], ["н", "n"],
  ["о", "o"], ["п", "p"], ["р", "r"], ["с", "s"], ["т", "t"],
  ["у", "u"], ["ф", "f"], ["ь", ""], ["ы", "y"], ["э", "e"],
];

function convert(text: string, table: [string, string][]): string {
  let out = "";
  let i = 0;
  outer: while (i < text.length) {
    for (const [from, to] of table) {
      if (text.startsWith(from, i)) {
        out += to;
        i += from.length;
        continue outer;
      }
    }
    out += text[i];
    i += 1;
  }
  return out;
}

const HAS_CYR = /[Ѐ-ӿ]/;
const HAS_LAT = /[a-z]/i;

/**
 * Варіанти запиту в іншій абетці. Порожній масив, якщо переклад нічого не
 * дасть: у «makita 5030» латиниця вже є, а в «дриль» — сама кирилиця, і
 * обидва напрямки пробувати немає сенсу.
 */
export function translitVariants(query: string): string[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];

  const variants: string[] = [];
  if (HAS_LAT.test(q)) variants.push(convert(q, LAT_TO_CYR));
  if (HAS_CYR.test(q)) variants.push(convert(q, CYR_TO_LAT));

  return variants.filter((v) => v && v !== q);
}
