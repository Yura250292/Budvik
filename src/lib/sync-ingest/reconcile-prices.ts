/**
 * Звірка цін: товар, у якого 1С більше не має ціни, має бути видно.
 *
 * Зріз `ЦеныНоменклатуры.СрезПоследних` віддає лише позиції з ціною > 0
 * (`queries.json`, плюс агент відсіює нульові й ті, чию валюту не вдалося
 * перерахувати). Тож коли ціну в 1С прибирають, товар не приходить нулем —
 * він просто зникає з вивантаження, а на вітрині лишається стара ціна.
 *
 * Чому звірка ЛИШЕ на повному прогоні: інкрементальні (кожні 5 хвилин)
 * читають ціни тільки для позицій, що рухалися з моменту вотермарка
 * (`extract.ps1`, `pricesChangedSince`). Незмінена ціна там не приходить за
 * визначенням, тож «немає у зрізі» на такому прогоні означає лише «не
 * змінювалась». Повний зріз буває раз на добу — нічний прогін о 03:30.
 *
 * Чому нічого не обнуляємо, а лише реєструємо розбіжність: ціна — це гроші,
 * і зникнення з зрізу має щонайменше три різні причини. Ціну справді
 * прибрали; ціна є, але у валюті, курс якої агент не дістав (у цій базі
 * таких рядків 335 — вони не приходили ніколи); зріз обірвався. Перші дві
 * вимагають протилежних дій, розрізнити їх на боці сайту неможливо, а
 * помилка коштує або продажу за неправильною ціною, або зникнення живого
 * товару з вітрини. Тому рішення лишається за людиною — але тепер воно
 * хоча б видиме: доти про такі позиції не знав ніхто.
 */

import { prisma } from "@/lib/prisma";
import { ApplyContext } from "./context";
import { channelDelivered } from "./stale";

/**
 * Скільки товар має бути відсутнім у зрізі, щоб це вважалося сигналом.
 *
 * Повний зріз приходить раз на добу, тож 36 годин означає «пропустив
 * щонайменше два нічні прогони поспіль». Один пропуск — це збій вивантаження
 * або перерваний сеанс 1С, і роздувати з нього тривогу не варто.
 */
const MISSING_PRICE_GRACE_MS = 36 * 60 * 60_000;

/** Скільки позицій показати в журналі за раз. Більше — це вже не список. */
const REPORT_LIMIT = 200;

/**
 * Реєструє товари, ціну яких повний зріз 1С більше не підтверджує.
 *
 * Повертає кількість знайдених (не змінених — звірка нічого не пише в самі
 * товари). Викликач ловить помилку: гігієна не має валити закриття прогону.
 */
export async function reconcilePrices(ctx: ApplyContext): Promise<number> {
  if (ctx.kind !== "full") return 0;

  const delivered = await channelDelivered(ctx, "price");
  if (!delivered) return 0;

  const cutoff = new Date(Date.now() - MISSING_PRICE_GRACE_MS);

  const stale = await prisma.product.findMany({
    where: {
      externalId: { not: null },
      isActive: true,
      price: { gt: 0 },
      // NULL сюди не входить навмисно: це «ще не спостерігали». Стартову
      // мітку всім, хто мав ціну, проставила міграція priceSyncedAt.
      priceSyncedAt: { lt: cutoff },
    },
    select: { sku: true, externalId: true, name: true, price: true, stock: true },
    orderBy: { price: "desc" },
    take: REPORT_LIMIT + 1,
  });

  if (stale.length === 0) return 0;

  for (const p of stale.slice(0, REPORT_LIMIT)) {
    ctx.discrepancy({
      entityType: "product",
      entityRef: p.sku || p.externalId!,
      entityName: p.name,
      field: "price_missing_in_1c",
      value1C: "немає у зрізі цін",
      valueBudvik: `${p.price.toFixed(2)} грн, залишок ${p.stock}`,
    });
  }

  if (stale.length > REPORT_LIMIT) {
    console.warn(
      `sync-ingest: цін без підтвердження 1С більше за ${REPORT_LIMIT} — у журнал потрапили найдорожчі`
    );
  }

  return Math.min(stale.length, REPORT_LIMIT);
}
