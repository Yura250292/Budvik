-- Авторство ручного піна клієнта.
--
-- Доти база знала лише ФАКТ уточнення (geoSource='MANUAL') і час останньої
-- спроби геокодування. Хто саме стояв біля дверей магазину — ніде не
-- лишалося, тож питання «чи працюють торгові над геолокацією» не мало
-- відповіді: 35 ручних пінів було видно, а чиїх — ні.
--
-- geoAt окремо від geoAttemptedAt навмисно: останній перезаписує будь-яка
-- спроба геокодера, зокрема невдала, і момент польової роботи в ньому
-- губився б через тиждень.
--
-- geoAccuracyM відрізняє два різні вчинки: число — «Я зараз тут» із GPS
-- (людина була на місці), NULL — пін посунули пальцем по карті ввечері.
--
-- Усі три nullable без значення за замовчуванням: 35 уже поставлених пінів
-- автора не мають і не матимуть — відновити його нізвідки.
--
-- Індексу немає свідомо: звіт групує по geoById по всій таблиці
-- контрагентів, а їх 3 700 — Postgres читає її повністю дешевше, ніж ходив
-- би індексом.
ALTER TABLE "Counterparty"
  ADD COLUMN "geoById" TEXT,
  ADD COLUMN "geoAt" TIMESTAMP(3),
  ADD COLUMN "geoAccuracyM" INTEGER;
