/**
 * Робота, яку треба зробити ПІСЛЯ відповіді, а не замість неї.
 *
 * Голий `void doSomething()` у роуті на Vercel ненадійний: функція
 * засинає одразу після відповіді, і незавершений проміс зникає разом із
 * нею. Для цього в Next є `after()` — він тримає виклик живим саме
 * стільки, скільки треба.
 *
 * Але `after()` кидає помилку, якщо його викликати поза запитом, а роути
 * тут викликаються не лише з HTTP: перевірочні скрипти
 * (`scripts/check-shift-auto-close.ts` і сусіди) звертаються до
 * обробників НАПРЯМУ, щоб не залежати від піднятого `next dev`. Без цієї
 * обгортки додавання фонової роботи в роут ламало б перевірку, яка про
 * ту роботу навіть не питає.
 *
 * Тому: у запиті — `after()`, поза ним — звичайний проміс. І в обох
 * випадках збій усередині роботи не виходить назовні: фонове — значить
 * не критичне для відповіді, яку людина вже отримала.
 */

import { after } from "next/server";

export function afterResponse(run: () => Promise<unknown>): void {
  const guarded = () =>
    Promise.resolve()
      .then(run)
      .catch((e) => {
        console.error("[afterResponse] фонова робота впала", e);
      });

  try {
    after(guarded);
  } catch {
    // Поза контекстом запиту (скрипт, тест) — виконуємо просто зараз.
    void guarded();
  }
}
