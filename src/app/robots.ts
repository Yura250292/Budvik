import type { MetadataRoute } from "next";
import { SITE_URL } from "@/lib/seo/site";

/**
 * Роботи, яким тут немає чого робити.
 *
 * Це SEO-сканери й збирачі даних для навчання моделей: вони обходять каталог
 * так само наполегливо, як Google, але не приводять жодного покупця. 18.08,
 * коли сайт оголосив себе в sitemap, кількість запитів до сервера зросла
 * у 65 разів — з ~20 тис. до ~1,4 млн на добу при шести живих відвідувачах.
 * Платили за це ми.
 *
 * Пошукові агенти ШІ (OAI-SearchBot, PerplexityBot, ChatGPT-User) навмисно
 * НЕ в списку: вони приводять людей, на відміну від збирачів навчальних
 * даних. Це різні роботи, хоч і від тих самих компаній.
 *
 * robots.txt — домовленість, а не замок: перелічені нижче її поважають.
 * Тих, хто не поважає, ловить правило у фаєрволі Vercel — там запит гине на
 * межі мережі, не встигнувши запустити функцію.
 */
const UNWANTED_CRAWLERS = [
  // SEO-сканери
  "AhrefsBot",
  "SemrushBot",
  "MJ12bot",
  "DotBot",
  "DataForSeoBot",
  "BLEXBot",
  "serpstatbot",
  "Barkrowler",
  "ZoominfoBot",
  // Збирачі даних для навчання моделей
  "GPTBot",
  "CCBot",
  "Bytespider",
  "ImagesiftBot",
  "Amazonbot",
  // Пошуковики без нашої аудиторії
  "PetalBot",
  "SeekportBot",
];

/**
 * Каталог із фільтрами закритий від обходу цілком.
 *
 * 360 брендів × сотні типів × сортування × діапазони цін × пагінація — це
 * фактично нескінченний простір адрес, і кожна з них рендериться наживо
 * (читання `searchParams` вимикає ISR для всього маршруту). Робот у такому
 * просторі не «дообходить» сайт ніколи: щойно він бере наступну комбінацію,
 * з'являється ще десять.
 *
 * Нічого не втрачаємо: бренди й типи мають власні чисті адреси
 * (/brand/... і /catalog/typ/...), вони в sitemap і вони кешуються. Товари
 * робот бере прямо з sitemap. Простір обходу стає скінченним — близько
 * півтори тисячі сторінок, — а отже, обхід колись завершується.
 */
export default function robots(): MetadataRoute.Robots {
  const privateAreas = [
    "/admin/",
    "/dashboard/",
    "/api/",
    "/cart",
    "/checkout",
    "/compare",
    "/wishlist",
    "/login",
    "/register",
    "/order/",
    "/sales/",
    "/driver/",
    "/manager/",
    "/warehouse/",
    "/simulation",
    "/ai/",
    "/r/",
  ];

  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: [
          ...privateAreas,
          // Будь-яка адреса каталогу з параметрами. Префіксне правило —
          // його розуміють усі роботи, на відміну від масок із зірочками.
          "/catalog?",
          // Пагінація лендінгів: сторінки з другої й далі дублюють першу,
          // а товари робот і так має із sitemap.
          "/brand/*/storinka/",
          "/catalog/typ/*/storinka/",
        ],
      },
      {
        userAgent: UNWANTED_CRAWLERS,
        disallow: "/",
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
  };
}
