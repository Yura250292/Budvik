/**
 * Чому трек не йде — однією фразою.
 *
 * Живе окремо, бо той самий висновок потрібен у трьох місцях: на карті
 * «На маршруті», у сповіщенні в Telegram і в картці самоперевірки. Якщо
 * писати його щоразу заново, вони почнуть розходитися — і найгірше саме
 * те, що розходження помітять не одразу: карта казатиме «немає зв'язку»,
 * а сповіщення «дозвіл не виданий», і людину пошлють перевіряти не те.
 *
 * Порядок перевірок — від причини до наслідку, і він тут головне.
 * Немає застосунку → немає пульсу → служба стоїть → немає дозволу →
 * вимкнена локація → немає жодного фікса → немає неба → немає зв'язку →
 * і аж наприкінці економія батареї. Кожна наступна перевірка має сенс
 * лише тоді, коли попередня пройшла.
 */

/** Скільки хвилин без пульсу означає, що застосунок не працює. */
export const HEARTBEAT_WINDOW_MIN = 10;

/** Скільки хвилин без свіжого фікса означає, що GPS не бачить неба. */
export const FIX_WINDOW_MIN = 10;

/** Точок у буфері, після яких зв'язок — уже проблема, а не пауза. */
export const BUFFER_ALARM = 50;

/**
 * Похибка, вище якої фікс приходить не від супутників.
 *
 * Супутниковий фікс просто неба — 3–15 м, під деревами й між будинками до
 * сотні. Сотні метрів означають вежу або Wi-Fi, тобто «людина всередині
 * будівлі». Поріг свідомо вищий за MAX_ACCURACY_M (100 м, межа довіри до
 * пробігу): там ідеться про якість кілометражу, тут — про якісно інший стан.
 */
export const INDOOR_ACCURACY_M = 200;

export type DeviceBeat = {
  /** Хвилин тому прийшов останній пульс. */
  minutesAgo: number | null;
  tracking: boolean;
  buffered: number;
  /** Хвилин тому був останній фікс GPS. */
  lastFixMinutesAgo: number | null;
  /**
   * Похибка останнього фікса, метри.
   *
   * Без неї «є координати» і «є КОРИСНІ координати» зливаються в одне. Планшет
   * у приміщенні отримує позицію по вежі з похибкою в кілометр: приймач живий,
   * але записувати таке в трек не можна — це не місце, а коло на пів села.
   */
  lastFixAccuracyM?: number | null;
  locationPermission: string | null;
  locationMode: string | null;
  batteryOptimized: boolean | null;
  /**
   * На що скаржився сам застосунок під час останньої відправки.
   *
   * Потрібне рівно в одному місці — щоб відрізнити «мережі немає» від
   * «відправка стоїть». Порожньо при повному буфері означає друге.
   */
  lastError?: string | null;
};

export type DiagnosisInput = {
  /** Чи зареєстрований хоч один планшет. */
  hasDevice: boolean;
  /** Чи відкрита зміна просто зараз. */
  shiftOpen: boolean;
  /** Останній пульс або null, якщо його не було зовсім. */
  beat: DeviceBeat | null;
  /**
   * Яка збірка стоїть на планшеті — з User-Agent його ж кабінету.
   *
   * Єдине джерело для збірок до 1.3: пульсу вони не шлють, і без цього
   * поля «пульсу немає» означало і стару збірку, і мертвий застосунок
   * водночас — тобто не означало нічого.
   */
  installedVersion?: string | null;
};

/**
 * Повертає готову фразу для людини або null, якщо все гаразд.
 *
 * Мовчання при закритій зміні — не проблема: планшет має право спати.
 */
export function diagnose({
  hasDevice,
  shiftOpen,
  beat,
  installedVersion,
}: DiagnosisInput): string | null {
  if (!hasDevice) return "Планшет не зареєстрований";

  if (!beat) {
    // Пульсу немає взагалі. Якщо кабінет назвав свою версію — це стара
    // збірка, і сказати це треба прямо: у неї немає ні сторожа, який
    // піднімає вбиту службу, ні доповіді про власний стан.
    if (!shiftOpen) return null;
    return installedVersion
      ? `Збірка ${installedVersion} застаріла — без сторожа треку, оновіть застосунок`
      : "Пульсу немає: стара збірка або застосунок не працює";
  }

  if (beat.minutesAgo != null && beat.minutesAgo > HEARTBEAT_WINDOW_MIN) {
    return `Застосунок мовчить ${beat.minutesAgo} хв`;
  }

  if (!beat.tracking && shiftOpen) return "Запис вимкнено при відкритій зміні";

  if (beat.locationPermission && beat.locationPermission !== "ALWAYS") {
    return beat.locationPermission === "DENIED"
      ? "Дозвіл на локацію не виданий"
      : "Дозвіл лише «поки застосунок відкрито»";
  }

  if (beat.locationMode === "OFF") {
    return "Геолокація вимкнена перемикачем у налаштуваннях планшета";
  }

  /**
   * Служба працює, а координат не було жодного разу.
   *
   * Окремо від «не дає координат N хвилин»: там був фікс і зник, тут не
   * було взагалі. Друге майже завжди означає щось у налаштуваннях
   * пристрою, а не глухе місце.
   */
  if (beat.tracking && beat.lastFixMinutesAgo == null) {
    return "Запис іде, але жодної координати не отримано";
  }

  /**
   * Приймач працює, але бачить не небо, а вежі.
   *
   * Це НЕ поламка, і саме тому стоїть перед перевіркою мовчання. Людина зайшла
   * до клієнта, на склад, у власний офіс — супутників немає, і система віддає
   * позицію по вежі з похибкою в сотні метрів. У трек ми таке не пишемо
   * свідомо: намальована точка за кілометр від справжнього місця гірша за
   * чесну відсутність точки.
   *
   * 02.09 цей стан два дні виглядав як поламка: пульс казав «приймач мовчить»,
   * і ми перебрали службу, дозволи, батарею й саму систему, поки не побачили
   * фото планшета, що спокійно лежав у приміщенні з живим сповіщенням.
   */
  if (
    beat.lastFixMinutesAgo != null &&
    beat.lastFixMinutesAgo <= FIX_WINDOW_MIN &&
    beat.lastFixAccuracyM != null &&
    beat.lastFixAccuracyM > INDOOR_ACCURACY_M
  ) {
    return `У приміщенні: приймач дає лише ±${beat.lastFixAccuracyM} м, тому трек стоїть`;
  }

  if (beat.lastFixMinutesAgo != null && beat.lastFixMinutesAgo > FIX_WINDOW_MIN) {
    return `GPS не дає координат ${beat.lastFixMinutesAgo} хв`;
  }

  if (beat.buffered > BUFFER_ALARM) {
    /**
     * «Немає зв'язку» тут можна сказати лише з однією умовою, і колись її
     * бракувало. Пульс, який ми саме читаємо, прийшов ТІЄЮ САМОЮ мережею,
     * якою мали їхати точки, і не давніше ніж HEARTBEAT_WINDOW_MIN тому —
     * інакше ми б вийшли вище з «застосунок мовчить». Тобто мережа є.
     *
     * Різницю дає скарга застосунку. Пачка вчетверо більша за пульс, і на
     * поганому каналі вона справді може не долізти — але тоді застосунок
     * пише помилку. Порожньо при буфері в сотні точок означає, що спроби
     * не було зовсім: відправка стоїть, і планшет треба перезапустити.
     *
     * 01.09 троє торгових півдня їздили без треку саме так, а сповіщення
     * казало «немає зв'язку» — і шукали причину в мережі, якої не було.
     */
    if (!beat.lastError) {
      return `Точки не доїжджають: ${beat.buffered} у планшеті, а зв'язок є — перезапустіть застосунок`;
    }
    return `Немає зв'язку: ${beat.buffered} точок чекають у планшеті (${beat.lastError})`;
  }

  /**
   * Економія батареї — остання в черзі, і це навмисно.
   *
   * Це не поламка, а ризик: Android МОЖЕ прибити службу, а може й ні.
   * Виняток за замовчуванням не виданий нікому, тож перевіркою вище цей
   * рядок затуляв би собою всі справжні причини — і карта показувала б
   * «економія батареї» там, де насправді вимкнена геолокація.
   */
  if (beat.batteryOptimized === true) {
    return "Не виданий виняток економії батареї — Android може глушити службу";
  }

  return null;
}
