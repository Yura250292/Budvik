/**
 * Які фільтри-характеристики показувати і для чого.
 *
 * Бренд, розділ і група відповідають на питання «що це за товар», але не на
 * те, з чим людина приходить у магазин: болгарку обирають не за фірмою, а за
 * тим, акумуляторна вона чи мережева і який круг у неї стає. Доти фільтрів
 * такого рівня на вітрині не було зовсім — звузити видачу можна було лише до
 * «Болгарки (КШМ)», а далі гортати сорок позицій очима.
 *
 * Реєстр навмисно окремо від класифікатора (classify.ts): той відповідає на
 * питання «до якої полиці належить товар», цей — «що питати про товар, який
 * уже на полиці». Правила видобування значень живуть у attributes.ts.
 *
 * Межа підходу — колонки Product. Поки фасетів одиниці, типізована колонка
 * дає найдешевші лічильники (groupBy без raw SQL). Якщо реєстр доросте до
 * півтора десятка різнорідних характеристик («ширина пензля», «матеріал
 * щетини»), хвіст варто буде перенести в jsonb, лишивши колонками лише ці
 * найчастіші.
 */

/** Чим працює інструмент. NULL у базі — невідомо, а не «мережевий». */
export type PowerSource = "akum" | "merezha" | "benzo";

export interface FacetDef {
  /** Ключ у адресі: ?power=akum,merezha */
  key: string;
  /** Колонка Product, у якій лежить значення. */
  column: "powerSource" | "discDiameterMm" | "voltageV" | "powerWatts";
  label: string;
  /** Одиниця для показу значення: «125 мм», «18 В». */
  unit?: string;
  /**
   * enum — фіксований перелік (живлення);
   * number — значення з бази як є (діаметр, напруга);
   * range — числові діапазони, коли точних значень надто мало для списку.
   */
  kind: "enum" | "number" | "range";
  options?: { value: string; label: string }[];
  buckets?: { id: string; label: string; gte?: number; lt?: number }[];
}

