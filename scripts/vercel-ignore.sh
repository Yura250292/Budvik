#!/usr/bin/env bash
#
# Чи варто Vercel збирати цей пуш.
#
# Коди виходу задає Vercel: 0 — пропустити збірку, будь-що інше — будувати.
#
# Чому окремим файлом, а не рядком у vercel.json: схема Vercel не приймає
# ignoreCommand довший за 256 символів, і спроба вписати сюди ще й перевірку
# наявності коміта валила деплой на етапі валідації — мовчки, без збірки.
#
# Дві пастки, на яких ми вже горіли:
#
# 1. Порівнювати лише з HEAD^ не можна: коли в одному пуші кілька комітів,
#    у порівняння потрапляв тільки верхній, і зміни решти їхали на прод
#    непоміченими (закрито 27.08.2026).
# 2. VERCEL_GIT_PREVIOUS_SHA може бути відсутнім у неглибокому клоні —
#    тоді git diff падає з «fatal: bad object», а разом із ним падає весь
#    деплой. Невідомий попередній коміт означає «будуємо», а не помилку.

set -u

PREV="${VERCEL_GIT_PREVIOUS_SHA:-HEAD^}"

git cat-file -e "$PREV^{commit}" 2>/dev/null || exit 1

# Каталоги, що на сайт не потрапляють: скрипти-проби, вивантаження, макети,
# воркер Railway, агент 1С, мобільний застосунок і документація.
git diff --quiet "$PREV" HEAD -- \
  ":!scripts" \
  ":!output" \
  ":!design" \
  ":!worker" \
  ":!agent" \
  ":!mobile" \
  ":!railway.json" \
  ":!.railwayignore" \
  ":!.nvmrc" \
  ":!*.md"
