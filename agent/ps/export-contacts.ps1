# One-off export of counterparty contact information from 1C.
#
# READ-ONLY. This script issues SELECT-style queries and writes ONE file on
# the operator's own machine. It does not write to the 1C database, does not
# post documents, and does not modify anything on the server -- not even the
# sync agent, which stays exactly as it is.
#
# Why it exists: addresses are not attributes of the counterparty catalogue on
# this configuration (probe-coverage.ps1 tried seven candidate names, none
# exist). They live in the contact-information register: 7995 address rows
# over 3263 counterparties, plus 2991 phones. The site geocodes clients from
# the address, and without it only 375 cards of 3689 have coordinates -- which
# is what leaves the client map, route building and delivery zones half blind.
#
# The kind of contact is chosen by priority, and the order is not cosmetic:
# "delivery address" is where the goods actually go, while a company's legal
# address is often in a different town, and geocoding the wrong one puts the
# client's pin on the wrong side of the region.
#
# Output: NDJSON, one counterparty per line, UTF-8 without BOM.
#
# Run in 32-bit PowerShell (the COM connector is 32-bit):
#   C:\Windows\SysWOW64\WindowsPowerShell\v1.0\powershell.exe -ep bypass -f \\tsclient\Downloads\export-contacts.ps1

[CmdletBinding()]
