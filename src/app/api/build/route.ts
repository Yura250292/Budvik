/**
 * Яка збірка зараз на сервері.
 *
 * Потрібно застосунку-PWA. У standalone-вікні документ живе днями: людина
 * не «відкриває сайт», вона повертається у вже відкритий. App Router при
 * цьому ходить по чанках тієї збірки, з якою стартував, і після деплою
 * далі виконує старий код — доти, доки сторінку не перезавантажать цілком.
 * Саме через це доводилось виходити із застосунку й заходити знову, щоб
 * побачити зміни.
 *
 * Відповідь навмисно крихітна й без кешу: її смикають на кожне повернення
 * в застосунок.
 */

import { NextResponse } from "next/server";

export const dynamic = "force-dynamic";

export function GET() {
  return NextResponse.json(
    {
      // VERCEL_DEPLOYMENT_ID — той самий `dpl_…`, що Next дописує до адрес
      // своїх чанків, тож клієнту є з чим порівнювати без жодних змінних
      // на етапі збірки. Коміт — запасний варіант, "dev" — для локальної
      // розробки, де сенсу в перевірці немає взагалі.
      id:
        process.env.VERCEL_DEPLOYMENT_ID ??
        process.env.VERCEL_GIT_COMMIT_SHA ??
        "dev",
    },
    { headers: { "Cache-Control": "no-store" } }
  );
}
