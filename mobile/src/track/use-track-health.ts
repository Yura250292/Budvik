/**
 * Стежить за живістю запису, поки застосунок відкритий.
 *
 * Це єдиний шлях перевірки, який не залежить від мережі й від системного
 * планувальника: він працює рівно тоді, коли процес живий. Разом із перевіркою
 * при поверненні застосунку на екран цього досить, щоб зависла підписка не
 * тривала годинами — у водія планшет у тримачі й екран увімкнений, а торговий
 * відкриває застосунок між справами.
 *
 * Мережевий сторож (watchdog.ts) лишається другим рубежем: він переживає
 * перезапуск процесу, але без мережі не прокидається взагалі.
 */

import { useEffect } from "react";
import { AppState } from "react-native";
import { IS_STAFF_BUILD } from "@/lib/flavor";
import { ensureFreshFixes } from "./health";
import { ensureRecording, isTracking, startTracking } from "./controller";
import { flush } from "./uploader";
import { trackProbeParam } from "./self-probe";
import { staffApi } from "@/api/staff";
import { isShiftOpen, getRole, getLastFixAt } from "./state";

/** Рідше, ніж поріг тиші, — щоб перевірка не била в ту саму мить, що й фікс. */
const CHECK_INTERVAL_MS = 2 * 60_000;

/**
 * Скільки тиші приймача означає, що прапорцю «пишемо» вірити не можна.
 *
 * Те саме число, що в сторожі (`watchdog.ts`): точка пишеться щонайрідше раз
 * на хвилину навіть на місці, тож двадцять хвилин — це вже не «погано видно
 * небо», а зупинений запис при піднятому прапорці.
 */
const FIX_STALE_MS = 20 * 60_000;

/**
 * Як часто слати пробу шару треку.
 *
 * Десять хвилин: вона потрібна не для стеження, а щоб зламаний планшет мав
 * голос. Мітка лежить у пам'яті процесу навмисно — після перезапуску проба
 * піде одразу, і саме перезапуск найцікавіший.
 */
const PROBE_EVERY_MS = 10 * 60_000;
let lastProbeAt = 0;

export function useTrackHealth(): void {
  useEffect(() => {
    if (!IS_STAFF_BUILD) return;

    const check = () => void ensureFreshFixes().catch(() => {});

    check();
    const timer = setInterval(check, CHECK_INTERVAL_MS);

    /**
     * Повернення на екран — найцінніший момент перевірки: саме тоді людина
     * дивиться на застосунок, і саме тоді процес гарантовано живий після
     * можливого присипляння.
     *
     * І єдиний момент, коли запис можна ПІДНЯТИ. Android від 12-ї версії не
     * дає стартувати службу переднього плану з фону, тож сторож, який
     * прокидається щочверть години, у більшості випадків нічого вдіяти не
     * може. А з переднього плану старт дозволений завжди — і це та мить,
     * коли людина відкрила застосунок, часто саме тому, що їй прийшло
     * сповіщення «Трек зупинився».
     */
    const revive = async () => {
      const [shiftOpen, role, tracking, fixAt] = await Promise.all([
        isShiftOpen(),
        getRole(),
        isTracking().catch(() => true),
        getLastFixAt().catch(() => null),
      ]);
      if (!(shiftOpen || role === "DRIVER")) return;

      /**
       * Прапорець «пишемо» — не доказ, і саме тому тут його вже мало.
       *
       * `hasStartedLocationUpdatesAsync` читає збережену позначку, а не живу
       * службу. Коли Android прибиває процес, позначка лишається піднятою — і
       * наступного ранку застосунок бачить «усе гаразд» і не робить нічого.
       * 10.09.2026 так минув ранок у трьох торгових: зміну відкрито, планшет
       * у руках, а запис не стартував жодного разу.
       *
       * Тому питаємо не «чи ми пишемо», а «чи приходять координати». Немає
       * фікса понад двадцять хвилин при відкритій зміні — запускаємо
       * ПРИМУСОВО, попри піднятий прапорець.
       *
       * Робити це можна саме тут і тільки тут: хук живе на передньому плані, а
       * з переднього плану Android дозволяє підняти службу завжди. У фоні той
       * самий крок був би зупинкою без запуску — див. health.ts.
       */
      const silentMs = fixAt ? Date.now() - fixAt : Infinity;
      const stale = silentMs > FIX_STALE_MS;
      if (tracking && !stale) return;

      if (tracking && stale) {
        await startTracking("SHIFT", { force: true }).catch(() => {});
        return;
      }
      await ensureRecording().catch(() => {});
    };

    /**
     * Відкритий застосунок — найкращий момент віддати все, що назбиралося.
     *
     * Точки лежать у SQLite і не гинуть, але поки трек не пишеться, відправку
     * нікому запустити: рекордер мовчить, а сторож прокидається раз на чверть
     * години й на деяких планшетах не прокидається зовсім. Тож день міг
     * лежати в буфері годинами при живій мережі — саме тоді, коли людина
     * дивиться в застосунок і думає, що все відправлено.
     */
    const push = () => void flush().catch(() => {});

    /**
     * Скарга шару треку — з НАТИВНОГО боку, а не з вебкабінету.
     *
     * Перша спроба чіпляла пробу до `checkApkUpdate()`, і це була помилка:
     * ту функцію не кличе ніхто, а відмітку `app:staff:installed`, за якою
     * здавалося, ніби застосунок озивається, пише вебкабінет усередині
     * WebView (StaffBuildCard/UpgradeBanner на сайті). Тобто вона доводить
     * лише те, що жива вебсторінка, і нічого не каже про нативний JS.
     *
     * Тут — інша річ: хук живе в кореневому layout, тобто виконується рівно
     * тоді, коли працює сам застосунок. І він НЕ залежить від бази треку:
     * `trackProbeParam` гасить у собі будь-яку помилку, а межа повторів
     * лежить у пам'яті процесу, а не в SQLite, — інакше зламана база забрала б
     * і цей канал теж.
     */
    const reportProbe = async () => {
      if (Date.now() - lastProbeAt < PROBE_EVERY_MS) return;
      lastProbeAt = Date.now();
      try {
        await staffApi.staffVersion(await trackProbeParam());
      } catch {
        // Мовчки: нема зв'язку — скажемо наступного разу.
      }
    };

    const sub = AppState.addEventListener("change", (state) => {
      if (state !== "active") return;
      check();
      void revive();
      push();
      void reportProbe();
    });

    // І одразу на монтуванні: холодний старт по натиску на сповіщення теж
    // мусить піднімати запис, а не лише перевіряти свіжість фіксів.
    void revive();
    push();
    void reportProbe();

    return () => {
      clearInterval(timer);
      sub.remove();
    };
  }, []);
}
