-- Мітка «ціну підтвердив повний зріз 1С».
--
-- Зріз цін віддає лише позиції з ціною > 0, тож прибрана в 1С ціна не
-- приходить нулем — товар просто зникає з вивантаження. Без цієї мітки
-- відрізнити його від товару, чия ціна просто не змінювалась, неможливо:
-- syncedAt рухається тільки на зміну значення.
ALTER TABLE "Product" ADD COLUMN "priceSyncedAt" TIMESTAMP(3);

-- Стартова точка відліку для товарів, які вже мають ціну.
--
-- Без неї звірка ніколи б не спрацювала: NULL означає «ще не спостерігали»
-- і кандидатом не вважається, тож позиція, що зникла зі зрізу ДО появи цієї
-- колонки, лишалася б із NULL вічно. Ставимо теперішній час — далі повний
-- зріз (нічний прогін) оновить мітку тим, хто в ньому є, а решта природно
-- постаріє й потрапить у звірку.
UPDATE "Product" SET "priceSyncedAt" = now() WHERE price > 0;
