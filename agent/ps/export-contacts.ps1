function RunQuery([string] $text) {
    $q = $ib.NewObject("Query")
    $q.Text = $text
    $rs = $q.Execute()
    if ($null -eq $rs) { return $null }
    return $rs.Choose()
}

function Str($value) {
    if ($null -eq $value) { return "" }
    return ([string]$value).Trim()
}

# Reference -> GUID. XMLString is the only reliable way over COM here.
function RefId($value) {
    if ($null -eq $value) { return "" }
    try {
        $x = $ib.XMLString($value)
        if ($x -match "([0-9a-fA-F\-]{36})") { return $Matches[1] }
        return ""
    } catch { return "" }
}

# Picks the first value whose kind is in the priority list.
function PickByVid($byVid, $priority) {
    foreach ($vid in $priority) {
        if ($byVid.ContainsKey($vid)) { return $byVid[$vid] }
    }
    return ""
}

# JSON by hand: ConvertTo-Json on PS5 escapes Cyrillic into \uXXXX and wraps
# single objects oddly. A tiny writer keeps the file readable and stable.
function JsonEscape([string] $s) {
    $s = $s -replace '\\', '\\\\'
    $s = $s -replace '"', '\"'
    $s = $s -replace "`r", ' '
    $s = $s -replace "`n", ' '
    $s = $s -replace "`t", ' '
    return $s
}

