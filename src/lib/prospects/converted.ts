/**
 * Коли точка для розпрацювання перестає бути ромбом.
 *
 * Правило власника: розпрацьовано = у прив'язаного контрагента є хоч одне
 * замовлення (чи реалізація) від торгового. Відтоді на карті лише кружок
 * клієнта з кольором за звичними станами, а ромб зникає. Доки замовлення
 * немає, навпаки: видно ромб, а кружок того самого контрагента ховаємо —
 * дві точки одного магазину поруч читалися б як два магазини.
 *
 * Статус CONVERTED тут не пишемо: правило обчислюється на льоту, тож
 * скасоване замовлення чи перепривʼязка повертають ромб без жодного кроку.
 */

import type { Prisma } from "@prisma/client";

/** Документ, що рахується «замовленням від торгового». */
const REP_ORDER: Prisma.SalesDocumentWhereInput = {
  salesRepId: { not: null },
  docType: { in: ["ORDER", "REALIZATION"] },
  status: { not: "CANCELLED" },
};

/** Точки, які ще треба розпрацювати (показуються ромбами). */
export const OPEN_PROSPECT: Prisma.ProspectClientWhereInput = {
  status: { in: ["NEW", "IN_PROGRESS"] },
  OR: [{ counterpartyId: null }, { counterparty: { salesDocuments: { none: REP_ORDER } } }],
};
