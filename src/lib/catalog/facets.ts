/**
 * Фасети для поточного місця в каталозі.
 *
 * Групи мають перевагу над розділом: коли людина дійшла до болгарок, питати
 * треба саме про болгарки. Кілька обраних груп дають обʼєднання — фільтр, що
 * нічого не значить для частини з них, просто лишить ці товари без значення.
 */
export function facetsFor(f: { section?: string; types?: string[] }): FacetDef[] {
  const keys = new Set<string>();

  if (f.types?.length) {
    for (const t of f.types) for (const k of BY_TYPE[t] ?? []) keys.add(k);
  }
  if (keys.size === 0 && f.section) {
    for (const k of BY_SECTION[f.section] ?? []) keys.add(k);
  }

  // Порядок реєстру, а не порядок додавання: панель фільтрів має виглядати
  // однаково в усіх групах, інакше блоки стрибають при кожному звуженні.
  return FACETS.filter((def) => keys.has(def.key));
}

/**
 * Що можна ЗАПИСАТИ товару цієї групи — без відкату на розділ.
 *
 * Питання не те саме, що «які фільтри показати». На екрані розділу «Садова
 * техніка» блок «Живлення» доречний: людина обирає між бензиновою мотокосою і
 * акумуляторною. Але сам розділ на дві третини складається з приладдя —
 * шлангів, лісок, ланцюгів, запчастин, — і записувати їм живлення тільки
 * тому, що вони лежать на садовій полиці, означає вигадувати: у ланцюга до
 * бензопили немає живлення, є сумісність.
 *
 * Тому наповнення (scripts/extract-specs.mts) питає саме цю функцію, а панель
 * фільтрів — facetsFor() вище.
 */
export function facetsForType(typeKey: string | null | undefined): FacetDef[] {
  if (!typeKey) return [];
  const keys = new Set(BY_TYPE[typeKey] ?? []);
  return FACETS.filter((def) => keys.has(def.key));
}
