-- Номер рядка документа 1С.
--
-- Порядок позицій у картці документа доти був довільним: свого поля під
-- нього не було, а Postgres віддає рядки як лежить — той самий документ у
-- замовленні йшов за назвою товару, а в реалізації за артикулом. Торговий
-- звіряє нашу картку з екраном 1С поруч, і переставлені позиції читаються
-- як інші дані.
--
-- Nullable без значення за замовчуванням: усе, що вже лежить у базі,
-- порядку не має і матиме NULL, а картка такі документи сортує за назвою
-- товару, як доти. Заповнюються рядки самі, коли обмін перезапише табличну
-- частину документа (вона перезаписується цілком на кожному прогоні).
--
-- Індекс не потрібен: рядки завжди читаються разом із документом, а їх у
-- документі десятки — сортування йде в пам'яті вже після вибірки за
-- "SalesDocumentItem_salesDocumentId_idx".
ALTER TABLE "SalesDocumentItem" ADD COLUMN "lineNo" INTEGER;
