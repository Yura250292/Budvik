-- Пошук за клієнтом більше не перебирає таблицю цілком.
--
-- До цього ані "SalesDocument", ані "SalesRepClient" не мали індексу, яким
-- можна знайти рядки ОДНОГО контрагента: у SalesRepClient унікальний ключ
-- починається з salesRepId, тож для зворотного питання він непридатний.
--
-- Ціна була видима торговим. debtDeltaByRep() питає обидві таблиці про
-- кожного контрагента в LATERAL-циклі, тобто 3 699 разів; кожен раз ішов
-- Seq Scan по всіх 11 187 документах. Разом — 41 млн переглянутих рядків і
-- 2,5 млн звернень до буфера на ОДНЕ відкриття головної кабінету, звідки й
-- бралися 4 з 6 секунд її очікування. Тими самими вибірками ходять карта
-- торгового (EXISTS по документах на кожну точку) і список клієнтів
-- (mine=1).
--
-- Заміряно на копіях цих таблиць: 3043 мс → 47 мс.
--
-- CONCURRENTLY тут навмисно немає: у Prisma воно падає з 25001 і блокує
-- наступні міграції (див. prisma-concurrently-migrations), а на 11 тис.
-- рядків звичайна побудова триває десятки мілісекунд.

CREATE INDEX "SalesDocument_counterpartyId_docType_createdAt_idx"
  ON "SalesDocument" ("counterpartyId", "docType", "createdAt" DESC);

CREATE INDEX "SalesRepClient_counterpartyId_idx"
  ON "SalesRepClient" ("counterpartyId");
